// 遅れて読み込む部品が読む文言(本体の文言 + ここの文言 + フィルターの管理の文言)。
export type PopupLocaleText = ResolvedGridLocaleText &
  Readonly<Pick<GridLocaleText, keyof typeof DEFAULT_POPUP_LOCALE_TEXT | keyof typeof DEFAULT_FILTERING_LOCALE_TEXT>>;

// グリッドが渡した文言(ResolvedGridLocaleText)の残りを、ここの既定で埋めます。
// 変更(英語対応): ツールパネルのフィルター / 並べ替え / 列のタブは、フィルターのチップのバーと同じ文言(localeTextFiltering.ts)も使います。
export const resolvePopupLocaleText = (texts: ResolvedGridLocaleText): PopupLocaleText => ({
  ...DEFAULT_POPUP_LOCALE_TEXT,
  ...DEFAULT_FILTERING_LOCALE_TEXT,
  ...texts,
});
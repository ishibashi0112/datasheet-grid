const { launch, BASE, serverLog, clearLog, chaos, cell, texts } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await launch()
  await chaos(page, { getFailRate: 0, patchFailRate: 0, getDelay: 100 })
  await page.goto(BASE + '/users')
  await page.waitForSelector('.ssg-body-row:not([data-skeleton-row])')
  await clearLog(page)
  const id0 = await cell(page, 0, 'id').textContent()
  await page.locator('.ssg-scroll-container').evaluate((e) => (e.scrollLeft = 10000))
  await page.waitForTimeout(400)
  const btn = page.locator('.ssg-body-row[data-row-index="0"] [data-ssg-col-key="actions"] button')
  console.log('btn count', await btn.count(), await page.evaluate(() => document.querySelector('.ssg-body-row[data-row-index="0"] [data-ssg-col-key="actions"]')?.outerHTML))
  const bb = await btn.boundingBox()
  console.log('bb', bb, await page.evaluate(([x, y]) => { const e = document.elementFromPoint(x, y); return e?.outerHTML.slice(0, 200) }, [bb.x + bb.width / 2, bb.y + bb.height / 2]))
  await page.mouse.click(bb.x + bb.width / 2, bb.y + bb.height / 2)
  await page.waitForTimeout(1500)
  console.log('log', JSON.stringify((await serverLog(page)).map((x) => x.method + (x.start ?? x.id))))
  console.log('after', id0, await cell(page, 0, 'id').textContent())
  // built-in retry
  await page.locator('.ssg-scroll-container').evaluate((e) => (e.scrollLeft = 0))
  await chaos(page, { getFailRate: 1 })
  await page.mouse.move(700, 400)
  for (let i = 0; i < 5; i++) { await page.mouse.wheel(0, 5000); await page.waitForTimeout(100) }
  await page.waitForTimeout(1200)
  console.log('alert', await texts(page, '.ssg-root [role="alert"]'))
  await chaos(page, { getFailRate: 0 })
  await clearLog(page)
  await page.locator('.ssg-root [role="alert"] button', { hasText: 'Retry' }).first().click()
  await page.waitForTimeout(1500)
  console.log('builtin retry', JSON.stringify((await serverLog(page)).map((x) => x.method + x.start)), await texts(page, '.ssg-root [role="alert"]'), await page.evaluate(() => document.querySelectorAll('[data-skeleton-row]').length))
  // × で閉じる → 同じ失敗の間は出ない
  await chaos(page, { getFailRate: 1 })
  await page.mouse.move(700, 400)
  for (let i = 0; i < 3; i++) { await page.mouse.wheel(0, 5000); await page.waitForTimeout(100) }
  await page.waitForTimeout(1200)
  const close = page.locator('.ssg-root [role="alert"] button').last()
  console.log('close label', await close.getAttribute('aria-label'))
  await close.click()
  await page.waitForTimeout(300)
  console.log('closed', await texts(page, '.ssg-root [role="alert"]'))
  await chaos(page, { getFailRate: 0 })
  console.log(logs.join('\n'))
  await browser.close()
})()

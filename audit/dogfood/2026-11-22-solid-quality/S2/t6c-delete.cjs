// 追加 → 上へスクロール → 削除ボタン(t6-refresh の手順を細かく)
const { launch, BASE, serverLog, clearLog, chaos, cell } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await launch()
  await chaos(page, { getFailRate: 0, patchFailRate: 0, getDelay: 100 })
  await page.goto(BASE + '/users')
  await page.waitForSelector('.ssg-body-row:not([data-skeleton-row])')
  await page.mouse.move(700, 400)
  await page.mouse.wheel(0, 360)
  await page.waitForTimeout(500)
  await clearLog(page)
  await page.getByRole('button', { name: 'Add user' }).click()
  await page.waitForTimeout(1200)
  await page.mouse.wheel(0, -2000)
  await page.waitForTimeout(800)
  const id0 = await cell(page, 0, 'id').textContent()
  await page.locator('.ssg-scroll-container').evaluate((e) => (e.scrollLeft = 10000))
  await page.waitForTimeout(400)
  const btn = page.locator('.ssg-body-row[data-row-index="0"] [data-ssg-col-key="actions"] button')
  const bb = await btn.boundingBox()
  const hit = await page.evaluate(([x, y]) => document.elementFromPoint(x, y)?.outerHTML.slice(0, 120), [bb.x + bb.width / 2, bb.y + bb.height / 2])
  await page.mouse.click(bb.x + bb.width / 2, bb.y + bb.height / 2)
  await page.waitForTimeout(1500)
  console.log(JSON.stringify({ id0, bb, sl: await page.evaluate(() => { const s = document.querySelector(".ssg-scroll-container"); return [s.scrollLeft, s.scrollWidth, s.clientWidth, s.scrollTop] }), hit: hit ?? null, after: await cell(page, 0, 'id').textContent(), log: (await serverLog(page)).map((x) => x.method + (x.start ?? x.id)) }))
  console.log(logs.join('\n'))
  await browser.close()
})()

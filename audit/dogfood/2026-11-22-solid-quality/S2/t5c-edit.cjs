// t5-edit の 3)〜7) を、横スクロールを 0 に戻してから押す形で(固定列の下にセルが隠れないように)
const { launch, BASE, serverLog, clearLog, chaos, cell } = require('./lib.cjs')
;(async () => {
  const { browser, ctx, page, logs } = await launch()
  await ctx.grantPermissions(['clipboard-read', 'clipboard-write'])
  await chaos(page, { getFailRate: 0, patchFailRate: 0, getDelay: 100 })
  await page.goto(BASE + '/users')
  await page.locator('.ssg-body-row:not([data-skeleton-row])').first().waitFor()
  await page.waitForTimeout(500)
  const out = []
  const press = async (r, k, dbl) => {
    await page.locator('.ssg-scroll-container').evaluate((e) => { e.scrollLeft = 0 })
    await page.waitForTimeout(150)
    const b = await cell(page, r, k).boundingBox()
    const hit = await page.evaluate(([x, y]) => document.elementFromPoint(x, y)?.closest('[data-ssg-col-key]')?.getAttribute('data-ssg-col-key'), [b.x + b.width / 2, b.y + b.height / 2])
    if (dbl) await page.mouse.dblclick(b.x + b.width / 2, b.y + b.height / 2)
    else await page.mouse.click(b.x + b.width / 2, b.y + b.height / 2)
    return hit
  }
  out.push(['hit email', await press(3, 'email', true)])
  await page.waitForTimeout(200)
  await page.keyboard.press('End'); await page.keyboard.type('.jp')
  const before = await page.evaluate(() => document.activeElement?.className)
  await page.mouse.move(700, 400); await page.mouse.wheel(0, 3000); await page.waitForTimeout(500)
  const during = await page.evaluate(() => ({ focused: document.activeElement?.className, editors: document.querySelectorAll('.ssg-cell-editor-input, .ssg-root textarea').length }))
  await page.mouse.wheel(0, -3000); await page.waitForTimeout(500)
  await page.keyboard.press('Enter'); await page.waitForTimeout(1500)
  out.push(['edit+scroll', before, JSON.stringify(during), await cell(page, 3, 'email').textContent()])
  await clearLog(page)
  await page.evaluate(() => navigator.clipboard.writeText('admin\tactive\nviewer\tsuspended\neditor\tinvited'))
  out.push(['hit role', await press(5, 'role')])
  await page.keyboard.press('Control+V'); await page.waitForTimeout(1500)
  out.push(['paste', JSON.stringify((await serverLog(page)).filter((x) => x.method === 'PATCH').map((x) => x.body))])
  await clearLog(page)
  out.push(['hit email8', await press(8, 'email')])
  await page.keyboard.press('Delete'); await page.waitForTimeout(1500)
  out.push(['delete email', await cell(page, 8, 'email').getAttribute('aria-invalid'), JSON.stringify((await serverLog(page)).filter((x) => x.method === 'PATCH').map((x) => x.body))])
  for (const o of out) console.log(JSON.stringify(o))
  console.log(logs.filter((l) => !/Failed to load resource/.test(l)).join('\n'))
  await browser.close()
})()

const { launch, BASE, serverLog, clearLog, chaos, cell, clickCell, texts, sleep } = require('./lib.cjs')
const cellHtml = (page, r, k) => page.evaluate(([r, k]) => document.querySelector(`.ssg-body-row[data-row-index="${r}"] [data-ssg-col-key="${k}"]`)?.outerHTML.replace(/<!--[^>]*-->/g, '').replace(/<svg.*?<\/svg>/g, '<svg/>'), [r, k])
;(async () => {
  const { browser, ctx, page, logs } = await launch()
  await ctx.grantPermissions(['clipboard-read', 'clipboard-write'])
  await chaos(page, { getFailRate: 0, patchFailRate: 0, getDelay: 100 })
  await page.goto(BASE + '/users')
  await page.waitForSelector('.ssg-body-row:not([data-skeleton-row])')
  await clearLog(page)
  const out = []
  // 1) 名前を編集して Enter
  await clickCell(page, 1, 'name')
  await page.keyboard.type('Zed Example')
  await page.waitForTimeout(100)
  await page.keyboard.press('Enter')
  await page.waitForTimeout(100)
  out.push(['saving', await cellHtml(page, 1, 'name')])
  await page.screenshot({ path: 'shot-saving.png', clip: { x: 0, y: 120, width: 700, height: 200 } })
  await page.waitForTimeout(1200)
  out.push(['saved', await cellHtml(page, 1, 'name')])
  await page.screenshot({ path: 'shot-saved.png', clip: { x: 0, y: 120, width: 700, height: 200 } })
  out.push(['patch', JSON.stringify((await serverLog(page)).filter((x) => x.method === 'PATCH').map((x) => x.body))])
  // 2) 編集して保存中にスクロールで遠くへ行って戻る
  await clickCell(page, 2, 'note')
  await page.keyboard.type('hello note')
  await page.keyboard.press('Enter')
  await page.mouse.move(700, 400)
  for (let i = 0; i < 10; i++) { await page.mouse.wheel(0, 4000); await page.waitForTimeout(30) }
  await page.waitForTimeout(600)
  const farFirst = await page.evaluate(() => document.querySelector('.ssg-body-row:not([data-skeleton-row])')?.getAttribute('data-row-index'))
  for (let i = 0; i < 10; i++) { await page.mouse.wheel(0, -4000); await page.waitForTimeout(30) }
  await page.waitForTimeout(1500)
  out.push(['after scroll', farFirst, await cell(page, 2, 'note').textContent(), await cell(page, 1, 'name').textContent()])
  // 3) 編集中(エディタを開いたまま)にスクロール
  await clickCell(page, 3, 'email', { dbl: true })
  await page.waitForTimeout(200)
  await page.keyboard.press('End')
  await page.keyboard.type('.jp')
  const editorBefore = await page.evaluate(() => !!document.querySelector('.ssg-root input:focus, .ssg-root textarea:focus'))
  await page.mouse.move(700, 400)
  await page.mouse.wheel(0, 3000)
  await page.waitForTimeout(500)
  const editorDuring = await page.evaluate(() => ({ focused: document.activeElement?.tagName + '.' + document.activeElement?.className, editors: document.querySelectorAll('.ssg-root input.ssg-cell-editor, .ssg-editor, [class*="editor"] input').length }))
  await page.screenshot({ path: 'shot-edit-scroll.png' })
  await page.mouse.wheel(0, -3000)
  await page.waitForTimeout(500)
  await page.screenshot({ path: 'shot-edit-scroll-back.png' })
  await page.keyboard.press('Enter')
  await page.waitForTimeout(1500)
  out.push(['edit+scroll', editorBefore, JSON.stringify(editorDuring), await cell(page, 3, 'email').textContent()])
  // 4) 保存失敗 → ロールバック
  await chaos(page, { patchFailRate: 1 })
  const before = await cell(page, 4, 'name').textContent()
  await clickCell(page, 4, 'name')
  await page.keyboard.type('Will Fail')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(150)
  out.push(['fail optimistic', await cell(page, 4, 'name').textContent()])
  await page.waitForTimeout(1200)
  out.push(['fail after', before, await cell(page, 4, 'name').textContent(), await cellHtml(page, 4, 'name')])
  out.push(['bars', await texts(page, '.ssg-root [role="alert"], .ssg-root [role="status"], .ssg-ssrm-bar, [class*="error-bar"], [class*="save-error"]')])
  out.push(['app error', await page.locator('[data-testid="last-error"]').textContent().catch(() => null)])
  await page.screenshot({ path: 'shot-fail.png' })
  // 5) 複数セルの貼り付け → PATCH 1 回
  await chaos(page, { patchFailRate: 0 })
  await clearLog(page)
  await page.evaluate(() => navigator.clipboard.writeText('admin\tactive\nviewer\tsuspended\neditor\tinvited'))
  await clickCell(page, 5, 'role')
  await page.keyboard.press('Control+V')
  await page.waitForTimeout(1500)
  out.push(['paste', JSON.stringify((await serverLog(page)).filter((x) => x.method === 'PATCH').map((x) => x.body)), [5, 6, 7].map(async () => 0) && await texts(page, '.ssg-body-row[data-row-index="5"] [data-ssg-col-key="role"], .ssg-body-row[data-row-index="6"] [data-ssg-col-key="status"]')])
  // 6) Delete で email を空に(検査は mark)
  await clearLog(page)
  await clickCell(page, 8, 'email')
  await page.keyboard.press('Delete')
  await page.waitForTimeout(1500)
  out.push(['delete email', await cellHtml(page, 8, 'email'), JSON.stringify((await serverLog(page)).filter((x) => x.method === 'PATCH').map((x) => x.body))])
  // 7) name を空にする(reject)
  await clearLog(page)
  await clickCell(page, 8, 'name')
  await page.keyboard.press('Delete')
  await page.waitForTimeout(1200)
  out.push(['delete name (reject)', await cell(page, 8, 'name').textContent(), JSON.stringify((await serverLog(page)).filter((x) => x.method === 'PATCH').map((x) => x.body))])
  // 8) undo は serverSide では無効
  await page.keyboard.press('Control+Z')
  await page.waitForTimeout(800)
  out.push(['undo', await cell(page, 8, 'email').textContent()])
  for (const o of out) console.log(JSON.stringify(o))
  console.log(logs.join('\n'))
  await browser.close()
})()

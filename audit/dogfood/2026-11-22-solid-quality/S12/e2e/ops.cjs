// 20 回/秒でほかの人のカーソルが動く中での編集・コピー・スクロールと、列の追加 / 削除 / 固定 / 並べ替えの後の選択とフォーカス
const { open, shot } = require('./lib.cjs')
;(async () => {
  const base = process.argv[2] || 'http://localhost:5512/'
  const mode = process.argv[3] || 'jsx'
  const { browser, page, logs } = await open(`${base}?peer=${mode}`)
  const out = []
  const g = (fn, arg) => page.evaluate(fn, arg)
  const cellAt = (rowKey, colKey) =>
    g(({ rowKey, colKey }) => {
      const h = window.__app.grid
      const r = h.getViewRowIndex(rowKey)
      const c = h.getColIndex(colKey)
      const root = document.querySelector('[aria-label="生産計画"]').closest('.ssg-root')
      const el = root.querySelector(`[role="row"][aria-rowindex="${r + 2}"] [role="gridcell"][aria-colindex="${c + 2}"]`)
      if (!el) return null
      const b = el.getBoundingClientRect()
      return { x: b.left + b.width / 2, y: b.top + b.height / 2, text: el.textContent }
    }, { rowKey, colKey })
  const act = () => g(() => { const a = document.activeElement; return `${a?.tagName}.${(a?.className || '').toString().slice(0, 40)}` })
  const state = () => g(() => { const h = window.__app.grid; const a = h.getActiveCell(); const cols = window.__app.columns(); return { active: a, sel: h.getSelection(), activeKey: document.querySelector('[data-testid=remove-col]').disabled ? null : 'enabled', keyAtActive: a ? (() => { for (const c of cols) if (h.getColIndex(c.key) === a.col) return c.key; return '?' })() : null } })

  // 編集: F2 で開いて 1 秒待つ(その間 20 回カーソルが動く)→ 打ち続けて Enter
  let c = await cellAt(3, 'm201105')
  await page.mouse.click(c.x, c.y)
  await page.keyboard.press('F2')
  await page.keyboard.press('End')
  await page.keyboard.type('1')
  await page.waitForTimeout(1000)
  out.push(['editor after 1s ticking', await g(() => { const i = document.querySelector('.ssg-cell-editor input'); return i && { value: i.value, focused: document.activeElement === i } })])
  await page.keyboard.type('2')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  out.push(['value after edit', await g(() => window.__app.rows()[2].v[4]), await act()])
  // 打ち始めで編集(文字キー)→ ticking 中に Tab で確定
  c = await cellAt(5, 'm201107')
  await page.mouse.click(c.x, c.y)
  await page.keyboard.type('777')
  await page.waitForTimeout(500)
  await page.keyboard.press('Tab')
  await page.waitForTimeout(200)
  out.push(['type+tab', await g(() => window.__app.rows()[4].v[6]), await state()])
  // コピー(範囲)
  const a1 = await cellAt(2, 'm201101'), a2 = await cellAt(4, 'm201103')
  await page.mouse.move(a1.x, a1.y); await page.mouse.down(); await page.mouse.move(a2.x, a2.y, { steps: 6 }); await page.mouse.up()
  await page.keyboard.press('Control+c')
  await page.waitForTimeout(200)
  out.push(['copied', JSON.stringify(await g(() => navigator.clipboard.readText()))])
  out.push(['expected', JSON.stringify(await g(() => window.__app.rows().slice(1, 4).map((r) => r.v.slice(0, 3).join('\t')).join('\n')))])
  // 貼り付け
  c = await cellAt(10, 'm201110')
  await page.mouse.click(c.x, c.y)
  await page.keyboard.press('Control+v')
  await page.waitForTimeout(300)
  out.push(['pasted', await g(() => window.__app.rows().slice(9, 12).map((r) => r.v.slice(9, 12)))])
  // ホイールで縦にスクロール
  for (let i = 0; i < 20; i++) { await page.mouse.wheel(0, 400); await page.waitForTimeout(30) }
  await page.waitForTimeout(300)
  out.push(['after wheel', await g(() => ({ range: window.__app.grid.getVisibleRowRange(), marks: document.querySelectorAll('.peer').length, blank: [...document.querySelectorAll('[aria-label="生産計画"] [role=gridcell]')].filter((e) => e.textContent === '').length }))])
  await shot(page, 'ops-scrolled')
  await page.evaluate(() => window.__app.grid.scrollToTop())
  await page.waitForTimeout(300)

  // 列の追加(アクティブセルの列の後ろ)
  c = await cellAt(3, 'm201106')
  await page.mouse.click(c.x, c.y)
  await page.waitForTimeout(100)
  const s0 = await state()
  await page.click('[data-testid=add-col]')
  await page.waitForTimeout(300)
  out.push(['add col', s0, await state(), await act(), await g(() => window.__app.columns().map((c) => c.key).slice(8, 12))])
  // グリッドを押し直さずに矢印 → 効かない(フォーカスはボタン)。focus() してから
  await page.keyboard.press('ArrowRight')
  out.push(['arrow on button', (await state()).active])
  await page.evaluate(() => window.__app.grid.focus())
  await page.keyboard.press('ArrowRight')
  await page.waitForTimeout(100)
  out.push(['arrow after focus()', await state()])
  // 足した列に打って確定
  await page.keyboard.type('メモ')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  out.push(['extra value', await g(() => window.__app.rows()[2].extra1)])
  // 列の削除(アクティブセルの列)
  c = await cellAt(5, 'm201108')
  await page.mouse.click(c.x, c.y)
  const s1 = await state()
  await page.click('[data-testid=remove-col]')
  await page.waitForTimeout(300)
  out.push(['remove col', s1, await state(), await g(() => window.__app.columns().some((c) => c.key === 'm201108'))])
  // 範囲を選んだまま、範囲の中の列を消す
  const b1 = await cellAt(5, 'm201101'), b2 = await cellAt(7, 'm201104')
  await page.mouse.move(b1.x, b1.y); await page.mouse.down(); await page.mouse.move(b2.x, b2.y, { steps: 6 }); await page.mouse.up()
  const s2 = await state()
  await page.click('[data-testid=remove-col]')
  await page.waitForTimeout(300)
  out.push(['remove col in range', s2, await state()])
  // 左に固定
  c = await cellAt(6, 'm201112')
  await page.mouse.click(c.x, c.y)
  const s3 = await state()
  await page.click('[data-testid=pin-col]')
  await page.waitForTimeout(300)
  out.push(['pin left', s3, await state(), await g(() => window.__app.grid.getColIndex('m201112'))])
  await shot(page, 'ops-pinned')
  // 列見出しのドラッグで並べ替え(live): 2011/02 を 2011/05 の後ろへ
  const hdr = (key) => g((key) => { const root = document.querySelector('[aria-label="生産計画"]').closest('.ssg-root'); const h = [...root.querySelectorAll('[role=columnheader]')].find((e) => e.getAttribute('aria-colindex') == window.__app.grid.getColIndex(key) + 2); const b = h.getBoundingClientRect(); return { x: b.left + b.width / 2, y: b.top + b.height / 2, l: b.left, r: b.right } }, key)
  c = await cellAt(4, 'm201102')
  await page.mouse.click(c.x, c.y)
  const s4 = await state()
  const h1 = await hdr('m201102'), h2 = await hdr('m201105')
  await page.mouse.move(h1.x, h1.y)
  await page.waitForTimeout(150)
  const grip = await g(() => { const e = document.querySelector('.ssg-header-grip, [class*=grip]'); const b = e?.getBoundingClientRect(); return b && b.width ? { x: b.left + b.width / 2, y: b.top + b.height / 2, cls: e.className } : null })
  out.push(['grip', grip])
  if (grip) {
    await page.mouse.move(grip.x, grip.y)
    await page.mouse.down()
    await page.mouse.move(h2.r - 5, h2.y, { steps: 12 })
    await page.waitForTimeout(100)
    await page.mouse.up()
    await page.waitForTimeout(500)
  }
  out.push(['reorder', s4, await state(), await g(() => window.__app.columns().map((c) => c.key).filter((k) => k.startsWith('m2011')).slice(0, 6))])
  for (const o of out) console.log(JSON.stringify(o))
  console.log('--- logs')
  console.log([...new Set(logs.filter((l) => !l.includes('[vite]') && !l.includes('what it means') && !l.includes('agent repair') && !l.includes('deeper evidence') && !l.startsWith('  ')).map((l) => l.slice(0, 300)))].join('\n'))
  await browser.close()
})()

// 列の並べ替え(見出しのドラッグ / 列メニューの固定)の後のアクティブセル・選択・フォーカス
const { open, shot } = require('./lib.cjs')
;(async () => {
  const base = process.argv[2] || 'http://localhost:5512/'
  const tag = process.argv[3] || 'solid'
  const { browser, page, logs } = await open(`${base}?peer=jsx`)
  const out = []; process.on("unhandledRejection", (e) => { for (const o of out) console.log(JSON.stringify(o)); console.log("ERR", e.message.split("\n")[0]); process.exit(1) })
  const g = (fn, arg) => page.evaluate(fn, arg)
  const cellAt = (rowKey, colKey) =>
    g(({ rowKey, colKey }) => {
      const h = window.__app.grid
      const r = h.getViewRowIndex(rowKey)
      const c = h.getColIndex(colKey)
      const root = document.querySelector('[aria-label="生産計画"]').closest('.ssg-root')
      const el = root.querySelector(`[role="row"][aria-rowindex="${r + 2}"] [role="gridcell"][aria-colindex="${c + 2}"]`)
      if (!el) return null
      const b = el.getBoundingClientRect()
      return { x: b.left + b.width / 2, y: b.top + b.height / 2, text: el.textContent }
    }, { rowKey, colKey })
  const hdr = (key) => g((key) => { const root = document.querySelector('[aria-label="生産計画"]').closest('.ssg-root'); const h = [...root.querySelectorAll('[role=columnheader]')].find((e) => e.getAttribute('aria-colindex') == window.__app.grid.getColIndex(key) + 2); const b = h.getBoundingClientRect(); return { x: b.left + b.width / 2, y: b.top + b.height / 2, l: b.left, r: b.right } }, key)
  const act = () => g(() => { const a = document.activeElement; return `${a?.tagName}.${(a?.className || '').toString().slice(0, 40)}` })
  const state = () => g(() => { const h = window.__app.grid; const a = h.getActiveCell(); const cols = window.__app.columns(); const keyAt = (i) => { for (const c of cols) if (h.getColIndex(c.key) === i) return c.key; return '?' }; const s = h.getSelection(); return { active: a && `${a.row}:${a.col}=${keyAt(a.col)}`, sel: s && JSON.stringify(s.range ?? s), selKeys: s?.range ? `${keyAt(s.range.start.col)}..${keyAt(s.range.end.col)}` : null } })
  const order = () => g(() => window.__app.columns().map((c) => c.key + (c.pinned ? '@' + c.pinned[0] : '')).slice(0, 9).join(' '))

  // 1. 見出しのドラッグ: 2011/02 を 2011/05 の後ろへ(アクティブセルは 2011/02)
  let c = await cellAt(4, 'm201102')
  await page.mouse.click(c.x, c.y)
  out.push(['before drag', await state(), await order()])
  const h1 = await hdr('m201102'), h2 = await hdr('m201105')
  await page.mouse.move(h1.x, h1.y)
  await page.waitForTimeout(200)
  const grip = await g(({ x, y }) => { const h = document.elementFromPoint(x, y)?.closest('[role=columnheader]'); const e = h?.querySelector('.ssg-header-grip'); const b = e?.getBoundingClientRect(); return b && b.width ? { x: b.left + b.width / 2, y: b.top + b.height / 2 } : null }, h1)
  await page.mouse.move(grip.x, grip.y)
  await page.mouse.down()
  await page.mouse.move(h2.r - 8, h2.y, { steps: 15 })
  await page.waitForTimeout(150)
  await shot(page, `drag-live-${tag}`)
  await page.mouse.up()
  await page.waitForTimeout(600)
  out.push(['after drag', await state(), await order(), await act()])
  await page.keyboard.press('ArrowRight')
  await page.waitForTimeout(100)
  out.push(['arrow after drag', await state()])
  // 2. 範囲を選んで見出しのドラッグ
  const a1 = await cellAt(3, 'm201103'), a2 = await cellAt(5, 'm201104')
  await page.mouse.move(a1.x, a1.y); await page.mouse.down(); await page.mouse.move(a2.x, a2.y, { steps: 5 }); await page.mouse.up()
  out.push(['range before drag', await state()])
  const h3 = await hdr('m201107'), h4 = await hdr('m201101')
  await page.mouse.move(h3.x, h3.y); await page.waitForTimeout(200)
  const grip2 = await g(({ x, y }) => { const h = document.elementFromPoint(x, y)?.closest('[role=columnheader]'); const e = h?.querySelector('.ssg-header-grip'); const b = e?.getBoundingClientRect(); return b && b.width ? { x: b.left + b.width / 2, y: b.top + b.height / 2 } : null }, h3)
  await page.mouse.move(grip2.x, grip2.y); await page.mouse.down(); await page.mouse.move(h4.l + 5, h4.y, { steps: 15 }); await page.waitForTimeout(100); await page.mouse.up()
  await page.waitForTimeout(600)
  out.push(['range after drag', await state(), await order()])
  // 3. 列メニューで「列の固定 → 左」(アクティブセルの列)
  c = await cellAt(6, 'm201106')
  await page.mouse.click(c.x, c.y)
  out.push(['before pin', await state(), await order()])
  await page.keyboard.press('Alt+ArrowDown')
  await page.waitForTimeout(300)
  const items = await g(() => [...document.querySelectorAll('[role=menu] [role^=menuitem]')].map((e) => e.textContent))
  out.push(['menu items', items])
  await page.click('[role=menu] [role=menuitem]:has-text("列の固定")')
  await page.waitForTimeout(250)
  const sub = await g(() => [...document.querySelectorAll('[role=menu]')].map((m) => [...m.querySelectorAll('[role=menuitemradio]')].map((e) => e.textContent)).filter((x) => x.length))
  out.push(['submenu', sub])
  await page.click('[role=menuitemradio]:has-text("左")')
  await page.waitForTimeout(400)
  out.push(['after pin', await state(), await order(), await act()])
  await shot(page, `pin-menu-${tag}`)
  await page.keyboard.press('ArrowDown')
  await page.waitForTimeout(100)
  out.push(['arrow after pin', await state()])
  for (const o of out) console.log(JSON.stringify(o))
  console.log('--- logs')
  console.log([...new Set(logs.filter((l) => !l.includes('[vite]') && !l.includes('what it means') && !l.includes('agent repair') && !l.includes('deeper evidence') && !l.startsWith('  ')).map((l) => l.slice(0, 300)))].join('\n'))
  await browser.close()
})()

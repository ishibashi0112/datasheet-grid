const { open, clickCell, getCell, activeInfo, setSettings, sleep } = require('./lib.cjs')
const [saveMode = 'onFlush', gap = '200'] = process.argv.slice(2)
;(async () => {
  const { browser, page, logs } = await open()
  await setSettings(page, { loadMode: 'memo', saveMode, fill: process.env.FILL !== '0' })
  await page.goto('http://localhost:5507/projects/web?minDelay=800&maxDelay=800&loadFail=0&saveFail=0')
  await page.waitForSelector('[role=grid][aria-label="タスク"] [data-row-key="web-1"]')
  const st = async (label) => {
    const a = await activeInfo(page, 'タスク')
    const f = await page.evaluate(() => { const e = document.activeElement; return e ? e.tagName + '.' + e.className + (e.value !== undefined ? ' value=' + e.value : '') : null })
    console.log(label, JSON.stringify({ e2: await getCell(page, 'タスク', 'web-2', 'estimate'), e3: await getCell(page, 'タスク', 'web-3', 'estimate'), active: a.active, editor: a.editor, editorValue: a.editorValue, focus: f, saving: await page.evaluate(() => !!document.querySelector('[data-testid=saving]')) }))
  }
  await clickCell(page, 'タスク', 'web-2', 'estimate')
  await page.keyboard.type('1')
  await st('typed 1')
  await page.keyboard.press('Enter')
  await st('enter')
  await sleep(Number(gap))
  await st('after gap')
  await page.keyboard.type('2')
  await st('typed 2')
  await sleep(100)
  await st('typed 2 +100')
  await page.keyboard.press('Enter')
  await st('enter 2')
  await sleep(3000)
  await st('end')
  console.log(await page.evaluate(() => window.__api.log))
  console.log(logs.filter((l) => !l.includes('[vite]')).join('\n'))
  await browser.close()
})()

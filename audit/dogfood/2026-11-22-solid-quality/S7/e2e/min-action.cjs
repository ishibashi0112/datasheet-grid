const { open, sleep } = require('./lib.cjs')
const [qs = 'v=unrelated', how = 'type', base = 'http://localhost:5507'] = process.argv.slice(2)
  const v = new URLSearchParams(qs).get('v')
;(async () => {
  const { browser, page, logs } = await open({ origin: base })
  await page.goto(`${base}/min-action.html?${qs}`)
  await page.waitForSelector('[data-row-key="3"] [data-ssg-col-key="name"]')
  const cell = async (k, c) => page.$eval(`[data-row-key="${k}"] [data-ssg-col-key="${c}"]`, (e) => e.textContent)
  const st = async (label) => console.log(label, JSON.stringify(await page.evaluate(() => ({ focus: document.activeElement?.tagName + '.' + document.activeElement?.className, editor: document.querySelector('.ssg-cell-editor input')?.value ?? null, busy: document.querySelector('#busy').textContent }))), await cell(3, 'name'), await cell(4, 'name'))
  const box = async (k, c) => (await page.$(`[data-row-key="${k}"] [data-ssg-col-key="${c}"]`)).boundingBox()
  if (v === 'rows') {
    const b = await box(2, 'name'); await page.mouse.click(b.x + 20, b.y + 10)
    await page.keyboard.type('first'); await page.keyboard.press('Enter')
  } else {
    await page.click('#work')
    const b = await box(3, 'name'); await page.mouse.click(b.x + 20, b.y + 10)
  }
  await sleep(300)
  await st('action 中')
  if (how === 'type') await page.keyboard.type('X')
  else if (how === 'f2') await page.keyboard.press('F2')
  else if (how === 'dbl') { const b = await box(3, 'name'); await page.mouse.dblclick(b.x + 20, b.y + 10) }
  await sleep(100)
  await st(`${how} の後`)
  await page.keyboard.type('yz')
  await page.keyboard.press('Enter')
  await st('Enter の後')
  await sleep(2500)
  await st('action の後')
  await page.keyboard.type('Q'); await page.keyboard.press('Enter')
  await st('action の後にもう一度 Q + Enter')
  console.log(logs.filter((l) => !l.includes('[vite]')).join('\n'))
  await browser.close()
})()

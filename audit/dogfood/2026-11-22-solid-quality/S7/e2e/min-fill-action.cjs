// 1 つ目のセルを打って Enter(保存が始まる)→ 300ms 後に次のセルで文字を打つ → Enter → 3 秒待つ
const { chromium } = require('playwright')
const [qs = '', base = 'http://localhost:5507'] = process.argv.slice(2)
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 700, height: 500 }, deviceScaleFactor: 1 })
  const logs = []
  page.on('pageerror', (e) => logs.push('[pageerror] ' + e.message))
  page.on('console', (m) => { if (!m.text().includes('[vite]')) logs.push(`[${m.type()}] ` + m.text().split('\n')[0]) })
  await page.goto(`${base}/min-fill-action.html?${qs}`)
  await page.waitForSelector('[data-row-key="3"] [data-ssg-col-key="name"]')
  const state = () => page.evaluate(() => ({ focus: document.activeElement?.tagName + '.' + document.activeElement?.className, editor: document.querySelector('.ssg-cell-editor input')?.value ?? null, row2: document.querySelector('[data-row-key="2"] [data-ssg-col-key="name"]')?.textContent, row3: document.querySelector('[data-row-key="3"] [data-ssg-col-key="name"]')?.textContent, error: document.querySelector('#error')?.textContent ?? null }))
  const b = await (await page.$('[data-row-key="2"] [data-ssg-col-key="name"]')).boundingBox()
  await page.mouse.click(b.x + 20, b.y + 10)
  await page.keyboard.type('A'); await page.keyboard.press('Enter')
  await new Promise((r) => setTimeout(r, 300))
  await page.keyboard.type('B')
  await new Promise((r) => setTimeout(r, 100))
  console.log('保存中に B を打った', JSON.stringify(await state()))
  await page.keyboard.press('Enter')
  await new Promise((r) => setTimeout(r, 3000))
  console.log('Enter して 3 秒後  ', JSON.stringify(await state()))
  console.log(logs.join('\n'))
  await browser.close()
})()

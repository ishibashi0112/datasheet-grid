const { open, sleep } = require('./lib.cjs')
const [v = 'refresh', col = 'name', base = 'http://localhost:5507', file = 'min-action2.html', first = '7', second = '8'] = process.argv.slice(2)
;(async () => {
  const { browser, page, logs } = await open({ origin: base })
  await page.goto(`${base}/${file}?v=${v}`)
  await page.waitForSelector('[data-row-key="3"] [data-ssg-col-key="name"]')
  const cell = async (k, c) => page.$eval(`[data-row-key="${k}"] [data-ssg-col-key="${c}"]`, (e) => e.textContent)
  const st = async (label) => console.log(label, JSON.stringify(await page.evaluate(() => ({ focus: document.activeElement?.tagName + '.' + document.activeElement?.className, editor: document.querySelector('.ssg-cell-editor input')?.value ?? null, busy: document.querySelector('#busy')?.textContent }))), await cell(2, col), await cell(3, col), await cell(4, col))
  const box = async (k, c) => (await page.$(`[data-row-key="${k}"] [data-ssg-col-key="${c}"]`)).boundingBox()
  const b = await box(2, col); await page.mouse.click(b.x + 20, b.y + 10)
  await page.keyboard.type(first); await page.keyboard.press('Enter')
  await sleep(300)
  await st('action 中')
  await page.keyboard.type(second)
  await sleep(100)
  await st('8 を打った後')
  await page.keyboard.press('Enter')
  await st('Enter の後')
  await sleep(2500)
  await st('action の後')
  console.log(logs.filter((l) => !l.includes('[vite]')).join('\n'))
  await browser.close()
})()

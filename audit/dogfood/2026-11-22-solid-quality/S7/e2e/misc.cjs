// 右クリックメニューの操作・CSV・保存中の Ctrl+Z・フィルハンドル
const { open, clickCell, getCell, activeInfo, setSettings, shot, sleep } = require('./lib.cjs')
const fs = require('fs')
;(async () => {
  const { browser, page, logs } = await open({ context: { acceptDownloads: true } })
  await setSettings(page, { loadMode: 'deferred', saveMode: 'onFlush', fill: true })
  await page.goto('http://localhost:5507/projects/web?minDelay=700&maxDelay=700&loadFail=0&saveFail=0')
  await page.waitForSelector('[role=grid][aria-label="タスク"] [data-row-key="web-1"]')
  const canUndo = () => page.evaluate(() => window.__tasksGrid?.canUndo())
  // 1. 右クリック → 完了にする
  const cb = await (await page.$('[role=grid][aria-label="タスク"] [data-row-key="web-2"] [data-ssg-col-key="title"]')).boundingBox()
  await page.mouse.click(cb.x + 30, cb.y + 10, { button: 'right' }); await sleep(200)
  await page.click('[role=menu] >> text=完了にする'); await sleep(100)
  console.log('完了にする 直後', await getCell(page, 'タスク', 'web-2', 'status'), 'canUndo', await canUndo())
  await sleep(2000)
  console.log('完了にする 後', await getCell(page, 'タスク', 'web-2', 'status'), await page.evaluate(() => window.__db.tasks.get('web')[1].status), 'canUndo', await canUndo())
  // 2. 保存中の Ctrl+Z
  await clickCell(page, 'タスク', 'web-5', 'estimate'); await page.keyboard.type('1'); await page.keyboard.press('Enter')
  await sleep(150)
  console.log('保存中 canUndo', await canUndo())
  await page.keyboard.press('Control+z'); await sleep(150)
  console.log('保存中に Ctrl+Z', await getCell(page, 'タスク', 'web-5', 'estimate'))
  await sleep(3500)
  console.log('落ち着いた', await getCell(page, 'タスク', 'web-5', 'estimate'), 'db', await page.evaluate(() => window.__db.tasks.get('web')[4].estimate), 'api', await page.evaluate(() => window.__api.log.slice(-6).join(',')))
  // 3. フィルハンドルで下へ 3 行
  await clickCell(page, 'タスク', 'web-8', 'priority')
  await sleep(200)
  const h = await page.$('.ssg-fill-handle')
  const hb = await h.boundingBox()
  await page.mouse.move(hb.x + hb.width / 2, hb.y + hb.height / 2); await page.mouse.down()
  await page.mouse.move(hb.x + hb.width / 2, hb.y + 36 * 3, { steps: 6 }); await page.mouse.up()
  await sleep(150)
  console.log('フィル 直後', await getCell(page, 'タスク', 'web-9', 'priority'), await getCell(page, 'タスク', 'web-10', 'priority'), await getCell(page, 'タスク', 'web-11', 'priority'))
  await sleep(2500)
  console.log('フィル 後', await page.evaluate(() => window.__db.tasks.get('web').slice(7, 11).map((t) => t.priority).join(',')))
  // 4. CSV
  const [dl] = await Promise.all([page.waitForEvent('download'), page.click('button:has-text("CSV")')])
  const p = await dl.path(); const csv = fs.readFileSync(p, 'utf8')
  console.log('CSV', dl.suggestedFilename(), csv.split('\r\n').slice(0, 3).join(' / '))
  console.log('--- console'); console.log(logs.filter((l) => !l.includes('[vite]')).map((l) => l.split('\n')[0]).join('\n'))
  await browser.close()
})()

const { open, clickCell, getCell, activeInfo, setSettings, sleep } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open()
  await setSettings(page, { loadMode: 'deferred', saveMode: 'onFlush', fill: false })
  await page.goto('http://localhost:5507/projects/web?minDelay=300&maxDelay=300&loadFail=0&saveFail=0')
  await page.waitForSelector('[role=grid][aria-label="タスク"] [data-row-key="web-1"]')
  await clickCell(page, 'タスク', 'web-7', 'title')
  await page.keyboard.type('最後')
  console.log('typed', JSON.stringify(await activeInfo(page, 'タスク')))
  await page.keyboard.press('Enter')
  await sleep(1500)
  console.log('enter', JSON.stringify(await activeInfo(page, 'タスク')), await getCell(page, 'タスク', 'web-7', 'title'))
  await browser.close()
})()

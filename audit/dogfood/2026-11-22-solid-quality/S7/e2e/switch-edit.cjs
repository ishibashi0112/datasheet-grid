// 取り直しの間(createDeferred)に古い行のセルを編集し、新しい行が届いてから確定する
const { open, clickCell, getCell, activeInfo, setSettings, shot, sleep } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open()
  await setSettings(page, { loadMode: 'deferred', saveMode: 'onFlush', fill: false })
  await page.goto('http://localhost:5507/projects/web?minDelay=1500&maxDelay=1500&loadFail=0&saveFail=0')
  await page.waitForSelector('[role=grid][aria-label="タスク"] [data-row-key="web-1"]', { timeout: 15000 })
  await page.click('a[data-project=app]')
  await sleep(100)
  await clickCell(page, 'タスク', 'web-2', 'title', { double: true })
  await page.keyboard.press('End')
  await page.keyboard.type('(編集)')
  const a1 = await activeInfo(page, 'タスク')
  console.log('取り直し中に編集', JSON.stringify({ editor: a1.editorValue, focus: a1.focus }))
  await sleep(2000)
  const a2 = await activeInfo(page, 'タスク')
  console.log('新しい行が届いた', JSON.stringify({ editor: a2.editorValue, focus: a2.focus, row2: await page.evaluate(() => document.querySelector('[role=grid][aria-label="タスク"] [data-row-index="1"]')?.getAttribute('data-row-key')) }))
  await shot(page, 'switch-edit-during')
  await page.keyboard.press('Enter')
  await sleep(2500)
  console.log('確定した', JSON.stringify({ app2: await getCell(page, 'タスク', 'app-2', 'title'), events: await page.evaluate(() => window.__events), api: await page.evaluate(() => window.__api.log), dbApp2: await page.evaluate(() => window.__db.tasks.get('app').find((t) => t.id === 'app-2').title), dbAppHasWeb: await page.evaluate(() => window.__db.tasks.get('app').some((t) => t.id.startsWith('web'))) }))
  console.log(logs.filter((l) => !l.includes('[vite]')).join('\n'))
  await browser.close()
})()

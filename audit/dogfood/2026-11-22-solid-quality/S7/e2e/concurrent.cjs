// 保存中に別のセルを編集 / 元に戻す / 貼り付け
const { open, clickCell, getCell, activeInfo, setSettings, shot, dumpLogs, sleep } = require('./lib.cjs')
const [loadMode = 'memo', saveMode = 'onFlush'] = process.argv.slice(2)
;(async () => {
  const { browser, page, logs } = await open()
  await setSettings(page, { loadMode, saveMode, fill: process.env.FILL !== '0' })
  await page.goto('http://localhost:5507/projects/web?minDelay=800&maxDelay=800&loadFail=0&saveFail=0')
  await page.waitForSelector('[role=grid][aria-label="タスク"] [data-row-key="web-1"]')
  const read = async () => ({ e2: await getCell(page, 'タスク', 'web-2', 'estimate'), e3: await getCell(page, 'タスク', 'web-3', 'estimate'), e4: await getCell(page, 'タスク', 'web-4', 'estimate'), saving: await page.evaluate(() => !!document.querySelector('[data-testid=saving]')), msg: await page.evaluate(() => document.querySelector('[data-testid=save-message]')?.textContent ?? null), active: (await activeInfo(page, 'タスク')).active })
  console.log('start', await read())
  await clickCell(page, 'タスク', 'web-2', 'estimate')
  await page.keyboard.type('1')
  await page.keyboard.press('Enter') // → E3
  await sleep(200)
  await page.keyboard.type('2')
  await page.keyboard.press('Enter') // → E4
  await sleep(100)
  console.log('2 つ打った直後', await read())
  await sleep(1000)
  console.log('1 つ目の保存が終わる頃', await read())
  await sleep(2500)
  console.log('両方終わった', await read(), await page.evaluate(() => window.__api.log))
  const db = await page.evaluate(() => window.__db.tasks.get('web').filter((t) => ['web-2', 'web-3'].includes(t.id)).map((t) => t.estimate))
  console.log('db', db)
  // 元に戻す
  await page.keyboard.press('Control+z')
  await sleep(150)
  console.log('Ctrl+Z の直後', await read())
  await sleep(2500)
  console.log('Ctrl+Z の後', await read(), await page.evaluate(() => window.__db.tasks.get('web').filter((t) => ['web-2', 'web-3'].includes(t.id)).map((t) => t.estimate)))
  // 貼り付け(3 行)
  await page.evaluate(() => navigator.clipboard.writeText('3\n4\n5'))
  await clickCell(page, 'タスク', 'web-2', 'estimate')
  await page.keyboard.press('Control+v')
  await sleep(150)
  console.log('貼り付け直後', await read())
  await sleep(2500)
  console.log('貼り付けの後', await read(), await page.evaluate(() => window.__db.tasks.get('web').filter((t) => ['web-2', 'web-3', 'web-4'].includes(t.id)).map((t) => t.estimate)))
  await page.keyboard.press('Control+z')
  await sleep(2500)
  console.log('貼り付けを Ctrl+Z', await read())
  await shot(page, `concurrent-${saveMode}`)
  console.log('--- console'); console.log(logs.filter((l) => !l.includes('[vite]')).join('\n'))
  await browser.close()
})()

const { chromium } = require('playwright')
const [qs = 'v=norefresh&fh=1&sync=1&nob=1', col = 'name', file = 'min-action2.html', base = 'http://localhost:5507'] = process.argv.slice(2)
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1000, height: 700 }, deviceScaleFactor: 1 })
  page.on('pageerror', (e) => console.log('[pageerror]', e.stack))
  page.on('console', (m) => { if (!m.text().includes('[vite]')) console.log(`[${m.type()}]`, m.text().slice(0, 1500)) })
  await page.goto(`${base}/${file}?${qs}`)
  await page.waitForSelector('[data-row-key="3"] [data-ssg-col-key="name"]')
  const box = async (k, c) => (await page.$(`[data-row-key="${k}"] [data-ssg-col-key="${c}"]`)).boundingBox()
  const b = await box(2, col); await page.mouse.click(b.x + 20, b.y + 10)
  await page.keyboard.type('7'); await page.keyboard.press('Enter')
  await new Promise((r) => setTimeout(r, 300))
  console.log('--- typing 8')
  await page.keyboard.type('8')
  await new Promise((r) => setTimeout(r, 2500))
  console.log(await page.evaluate(() => ({ focus: document.activeElement?.className, editor: document.querySelector('.ssg-cell-editor input')?.value ?? null })))
  await browser.close()
})()

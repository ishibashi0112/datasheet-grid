const { chromium } = require('playwright')
const [qs = 'v=norefresh&fh=1&sync=1', col = 'name', file = 'min-action2.html', base = 'http://localhost:5507'] = process.argv.slice(2)
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 700, height: 500 }, deviceScaleFactor: 1 })
  page.on('pageerror', (e) => console.log('[pageerror]', e.stack))
  page.on('console', (m) => { if (!m.text().includes('[vite]')) console.log(`[${m.type()}]`, m.text().slice(0, 600)) })
  await page.goto(`${base}/${file}?${qs}`)
  await page.waitForSelector('[data-row-key="3"] [data-ssg-col-key="name"]')
  const box = async (k, c) => (await page.$(`[data-row-key="${k}"] [data-ssg-col-key="${c}"]`)).boundingBox()
  const b = await box(2, col); await page.mouse.click(b.x + 20, b.y + 10)
  await page.keyboard.type('7'); await page.keyboard.press('Enter')
  await new Promise((r) => setTimeout(r, 300))
  await page.keyboard.type('8')
  await new Promise((r) => setTimeout(r, 200))
  await page.screenshot({ path: __dirname + '/shots/min-fill-during.png' })
  await new Promise((r) => setTimeout(r, 2500))
  await page.screenshot({ path: __dirname + '/shots/min-fill-after.png' })
  console.log(await page.evaluate(() => ({ text: document.body.innerText.slice(0, 200), handles: document.querySelectorAll('.ssg-fill-handle').length, editors: document.querySelectorAll('.ssg-cell-editor').length })))
  // 押して戻れるか
  const b2 = await box(5, col); await page.mouse.click(b2.x + 20, b2.y + 10)
  await new Promise((r) => setTimeout(r, 300))
  console.log('別のセルを押した後', await page.evaluate(() => ({ focus: document.activeElement?.className, editor: document.querySelector('.ssg-cell-editor input')?.value ?? null, bar: document.querySelector('.ssg-bar--bottom')?.textContent })))
  await page.keyboard.type('9'); await page.keyboard.press('Enter')
  await new Promise((r) => setTimeout(r, 300))
  console.log('9 + Enter', await page.evaluate(() => ({ focus: document.activeElement?.className, editor: document.querySelector('.ssg-cell-editor input')?.value ?? null, c5: document.querySelector('[data-row-key="5"] [data-ssg-col-key="name"]').textContent })))
  await browser.close()
})()

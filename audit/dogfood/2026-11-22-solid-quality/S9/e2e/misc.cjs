const { open, cell, clickCell, rows, shot, ime } = require('./lib.cjs')
;(async () => {
  const url = process.argv[2] || 'http://localhost:5509/'
  const { browser, page, logs, cdp } = await open(url)
  const out = []
  const dlg = () => page.evaluate(() => document.querySelector('dialog').open)
  // custom エディタを開いたまま表をスクロール → 閉じる
  for (let i = 0; i < 6; i++) { await page.click('[data-testid=add-row]'); await page.waitForTimeout(80); await page.keyboard.press('Escape') }
  await page.evaluate(() => window.__grid.scrollToTop()); await page.waitForTimeout(200)
  const a = await cell(page, 1, 'account')
  await page.mouse.dblclick(a.x, a.y)
  await page.waitForTimeout(300)
  out.push(['custom open', await page.evaluate(() => !!document.querySelector('[data-testid=account-list]'))])
  await page.mouse.wheel(0, 200)
  await page.waitForTimeout(300)
  out.push(['after wheel', await page.evaluate(() => ({ list: !!document.querySelector('[data-testid=account-list]'), editor: !!document.querySelector('[data-testid=account-editor]') })), (await rows(page))[1].account])
  // 右クリックメニューで行を削除 → 元に戻す
  await page.evaluate(() => window.__grid.scrollToTop()); await page.waitForTimeout(200)
  const before = (await rows(page)).length
  const m = await cell(page, 2, 'memo')
  await page.mouse.click(m.x, m.y, { button: 'right' })
  await page.waitForTimeout(250)
  out.push(['ctx menu', await page.evaluate(() => [...document.querySelectorAll('[role=menu] [role=menuitem]')].map((e) => e.textContent))])
  await page.click('[role=menu] [role=menuitem]:has-text("この行を削除")')
  await page.waitForTimeout(250)
  out.push(['after delete', before, (await rows(page)).length, (await rows(page))[2].memo])
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(250)
  out.push(['after undo', (await rows(page)).length, (await rows(page))[2].memo])
  // ダイアログの中の custom エディタで Escape → 編集だけ取り消し、ダイアログは開いたまま
  await page.click('[data-testid=confirm]')
  await page.waitForTimeout(400)
  const dg = '[aria-label="確認する明細"]'
  const c = await cell(page, 0, 'account', dg)
  await page.mouse.dblclick(c.x, c.y)
  await page.waitForTimeout(300)
  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)
  out.push(['esc in custom (dialog)', await dlg(), await page.evaluate(() => !!document.querySelector('[data-testid=account-editor]'))])
  // select の候補(ダイアログの中の表は税区分を編集できないので、本体の表で開いてから確認するのは別)
  // 範囲を選んで Escape → 選択を外すだけでダイアログは開いたまま
  const s1 = await cell(page, 0, 'date', dg); const s2 = await cell(page, 2, 'amount', dg)
  await page.mouse.move(s1.x, s1.y); await page.mouse.down(); await page.mouse.move(s2.x, s2.y, { steps: 4 }); await page.mouse.up()
  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)
  out.push(['esc range (dialog)', await dlg(), await page.evaluate(() => window.__dialogGrid.getSelection())])
  // Ctrl+C → Escape(コピー範囲の点線を消す)→ 開いたまま
  await page.keyboard.press('Control+c')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(150)
  out.push(['esc copy range (dialog)', await dlg()])
  await page.keyboard.press('Escape')
  await page.waitForTimeout(150)
  out.push(['esc single (dialog)', await dlg()])
  // 送信時にだけ印を出す(レシピ)
  await page.goto(new URL('?marksOnSubmit', url).href)
  await page.waitForSelector('.ssg-body-cell')
  await clickCell(page, 0, 'amount'); await page.keyboard.type('0.5'); await page.keyboard.press('Enter'); await page.waitForTimeout(200)
  out.push(['mark before submit', (await cell(page, 0, 'amount')).invalid])
  await page.click('[data-testid=confirm]'); await page.waitForTimeout(400)
  await page.click('[data-testid=dialog-close]'); await page.waitForTimeout(200)
  out.push(['mark after submit', (await cell(page, 0, 'amount')).invalid, (await cell(page, 0, 'amount')).desc])
  for (const o of out) console.log(JSON.stringify(o))
  console.log('--- logs')
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('what it means') && !l.includes('agent repair') && !l.includes('deeper evidence') && !l.startsWith('  ') && !l.includes('React DevTools')).join('\n'))
  await browser.close()
})()

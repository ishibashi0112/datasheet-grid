const { open, cell, clickCell, rows, shot } = require('./lib.cjs')
;(async () => {
  const url = process.argv[2] || 'http://localhost:5509/'
  const { browser, page, logs } = await open(url)
  const out = []
  const tsv = [
    ['2026/11/14', '旅費交通費', '¥1,200', '課税 10%', '99', '　', '新幹線 東京→新大阪', 'TRUE'],
    ['2026/11/15', '会議費', '１２，０００', '課税 10%', '', '5', '"会議室\nレンタル"', 'FALSE'],
    ['2026/11/16', '消耗品費', '(1,200)', '軽減 8%', '', '', '文具', ''],
    ['', '雑費', '1200円', '不課税', '', '100', '"=HYPERLINK(""http://x"")"', '1'],
  ].map((r) => r.join('\t')).join('\r\n') + '\r\n'
  await page.evaluate((t) => navigator.clipboard.writeText(t), tsv)
  await clickCell(page, 4, 'date')
  await page.keyboard.press('Control+v')
  await page.waitForTimeout(400)
  const r = await rows(page)
  out.push(['count', r.length])
  for (const x of r.slice(4)) out.push(['row', x])
  out.push(['skipped', await page.evaluate(() => window.__skipped)])
  out.push(['toast', await page.evaluate(() => document.querySelector('.toast')?.textContent)])
  out.push(['selection', await page.evaluate(() => window.__grid.getSelection())])
  out.push(['invalid', await page.evaluate(() => window.__grid.getInvalidCells())])
  await shot(page, 'paste-after')
  // 元に戻す 1 回で貼り付け前へ(足した行も)
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(300)
  const r2 = await rows(page)
  out.push(['after undo count', r2.length, r2[4].date, r2[4].amount, r2[5].account])
  out.push(['after undo active', await page.evaluate(() => [window.__grid.getActiveCell(), window.__grid.getSelection()])])
  await page.keyboard.press('Control+y')
  await page.waitForTimeout(300)
  out.push(['after redo count', (await rows(page)).length])
  // 1 セルを範囲に貼る(範囲いっぱい)
  await page.evaluate(() => navigator.clipboard.writeText('１，０００\r\n'))
  const a = await cell(page, 0, 'amount')
  const b = await cell(page, 2, 'amount')
  await page.mouse.move(a.x, a.y)
  await page.mouse.down()
  await page.mouse.move(b.x, b.y, { steps: 5 })
  await page.mouse.up()
  await page.keyboard.press('Control+v')
  await page.waitForTimeout(300)
  out.push(['fill paste', (await rows(page)).slice(0, 3).map((x) => x.amount)])
  // 空のセルだけの貼り付け(Excel で空のセルを 1 つコピー = "\r\n")
  await clickCell(page, 0, 'memo')
  await page.evaluate(() => navigator.clipboard.writeText('\r\n'))
  await page.keyboard.press('Control+v')
  await page.waitForTimeout(300)
  out.push(['empty paste memo', JSON.stringify((await rows(page))[0].memo)])
  // 貼り付けで人数(reject)を空にしようとする(会議費の行)
  await clickCell(page, 1, 'people')
  await page.evaluate(() => navigator.clipboard.writeText('\r\n'))
  await page.keyboard.press('Control+v')
  await page.waitForTimeout(300)
  out.push(['empty paste people(reject)', (await rows(page))[1].people, await page.evaluate(() => window.__skipped)])
  // Delete でも空にできない
  await page.keyboard.press('Delete')
  await page.waitForTimeout(200)
  out.push(['delete people(reject)', (await rows(page))[1].people])
  for (const o of out) console.log(JSON.stringify(o))
  console.log('--- logs')
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('what it means') && !l.includes('agent repair') && !l.includes('deeper evidence') && !l.startsWith('  ')).join('\n'))
  await browser.close()
})()

const { open, cell, clickCell, rows, shot, ime } = require('./lib.cjs')
;(async () => {
  const url = process.argv[2] || 'http://localhost:5509/'
  const { browser, page, logs, cdp } = await open(url)
  const out = []
  const active = () => page.evaluate(() => ({ tag: document.activeElement?.tagName, ime: document.activeElement?.hasAttribute('data-ssg-ime-input'), cls: document.activeElement?.className }))
  // a. 摘要(複数行 text)へ IME で打ち始める
  await clickCell(page, 0, 'memo')
  out.push(['focus after click', await active()])
  await ime(cdp, page, 'こうつうひ', '交通費')
  out.push(['editor after ime', await page.evaluate(() => { const e = document.querySelector('.ssg-cell-editor textarea, .ssg-cell-editor input'); return e && { tag: e.tagName, value: e.value, focused: document.activeElement === e } })])
  await shot(page, 'ime-memo-editing')
  await page.keyboard.type('(精算)')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  out.push(['memo row0', (await rows(page))[0].memo])
  out.push(['active after enter', await page.evaluate(() => window.__grid.getActiveCell())])
  out.push(['focus after enter', await active()])
  // a2. 変換中にセル上へ文字が見えるか
  await clickCell(page, 1, 'memo')
  await cdp.send('Input.imeSetComposition', { text: 'うちあわせ', selectionStart: 5, selectionEnd: 5 })
  await page.waitForTimeout(150)
  await shot(page, 'ime-memo-composing')
  out.push(['composing overlay', await page.evaluate(() => { const i = document.querySelector('[data-ssg-ime-input]'); const b = i.getBoundingClientRect(); return { value: i.value, opacity: getComputedStyle(i).opacity, color: getComputedStyle(i).color, w: b.width, h: b.height } })])
  await cdp.send('Input.imeSetComposition', { text: '', selectionStart: 0, selectionEnd: 0 })
  await page.keyboard.press('Escape')
  await page.waitForTimeout(150)
  out.push(['after cancel composition', await page.evaluate(() => !!document.querySelector('.ssg-cell-editor'))])
  // b. 金額(number)に全角の数字を IME で
  await clickCell(page, 1, 'amount')
  await ime(cdp, page, '１２，３４０', '１２，３４０')
  out.push(['amount editor', await page.evaluate(() => { const e = document.querySelector('.ssg-cell-editor input'); return e && { type: e.type, value: e.value } })])
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  out.push(['amount row1', (await rows(page))[1].amount, typeof (await rows(page))[1].amount])
  // c. 「ー」→ 5 → -5(範囲外 = 印)
  await clickCell(page, 2, 'amount')
  await ime(cdp, page, 'ー', 'ー')
  out.push(['minus editor', await page.evaluate(() => { const e = document.querySelector('.ssg-cell-editor input'); return e && { type: e.type, value: e.value, inputmode: e.inputMode } })])
  await page.keyboard.type('5')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  out.push(['amount row2', (await rows(page))[2].amount])
  out.push(['row2 amount cell', await cell(page, 2, 'amount')])
  // c2. かなの変換は捨てる
  await clickCell(page, 3, 'amount')
  await ime(cdp, page, 'あいう', '藍宇')
  out.push(['kana on number', await page.evaluate(() => !!document.querySelector('.ssg-cell-editor')), (await rows(page))[3].amount])
  // d. 科目(custom + imeDirectInput)へ かな で打ち始め
  await clickCell(page, 4, 'account')
  await ime(cdp, page, 'つうしん', 'つうしん')
  await page.waitForTimeout(200)
  out.push(['account editor', await page.evaluate(() => { const e = document.querySelector('[data-testid=account-editor] input'); const l = document.querySelector('[data-testid=account-list]'); return e && { value: e.value, focused: document.activeElement === e, list: l && [...l.querySelectorAll('li')].map((x) => x.textContent), listParent: l?.parentElement?.tagName } })])
  await shot(page, 'ime-account')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  out.push(['account row4', (await rows(page))[4].account])
  // d2. 漢字で打ち始め
  await clickCell(page, 5, 'account')
  await ime(cdp, page, 'ざっぴ', '雑費')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  out.push(['account row5', (await rows(page))[5].account])
  // e. date の列に IME → 捨てる
  await clickCell(page, 0, 'date')
  await ime(cdp, page, 'きょう', '今日')
  out.push(['date ime', await page.evaluate(() => !!document.querySelector('.ssg-cell-editor')), (await rows(page))[0].date])
  // f. select の列: IME で確定 → 捨てる(直接入力の対象外)。開いてから IME
  await clickCell(page, 0, 'taxType')
  await ime(cdp, page, 'けいげん', '軽減')
  out.push(['select ime direct', await page.evaluate(() => !!document.querySelector('.ssg-cell-editor'))])
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  out.push(['select opened', await page.evaluate(() => { const i = document.querySelector('.ssg-cell-editor input'); return i && { value: i.value, role: i.getAttribute('role') } })])
  const focusedInSelect = await page.evaluate(() => document.activeElement?.outerHTML.slice(0, 120))
  out.push(['focus in select', focusedInSelect])
  await ime(cdp, page, 'けいげん', '軽減')
  await page.waitForTimeout(150)
  out.push(['select highlighted', await page.evaluate(() => [...document.querySelectorAll('[role=option]')].filter((o) => o.getAttribute('aria-selected') === 'true' || o.className.includes('active') || o.className.includes('highlight')).map((o) => o.textContent + '|' + o.className))])
  await shot(page, 'ime-select')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  out.push(['taxType row0', (await rows(page))[0].taxType])
  // g. 人数(reject)に 100
  await clickCell(page, 1, 'people')
  await ime(cdp, page, '１００', '１００')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  out.push(['people reject', await page.evaluate(() => { const e = document.querySelector('.ssg-cell-editor input'); const a = document.querySelector('[role=alert]'); return { editorOpen: !!e, value: e?.value, invalid: e?.getAttribute('aria-invalid'), alert: a?.textContent } }), (await rows(page))[1].people])
  await shot(page, 'ime-people-reject')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(150)
  out.push(['after escape', await page.evaluate(() => !!document.querySelector('.ssg-cell-editor')), (await rows(page))[1].people])
  for (const o of out) console.log(JSON.stringify(o))
  console.log('--- logs')
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('what it means') && !l.includes('agent repair') && !l.includes('deeper evidence')).join('\n'))
  await browser.close()
})()

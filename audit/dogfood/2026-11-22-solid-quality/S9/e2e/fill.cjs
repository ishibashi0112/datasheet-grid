const { open, cell, clickCell, rows, shot } = require('./lib.cjs')
;(async () => {
  const url = process.argv[2] || 'http://localhost:5509/'
  const { browser, page, logs } = await open(url)
  const out = []
  // 行を 4 つ足す(行を追加 → 日付の編集が始まる → Escape)
  for (let i = 0; i < 4; i++) {
    await page.click('[data-testid=add-row]')
    await page.waitForTimeout(150)
    out.push(['add editing', await page.evaluate(() => ({ editor: !!document.querySelector('.ssg-cell-editor'), active: window.__grid.getActiveCell(), focus: document.activeElement?.tagName + '.' + document.activeElement?.className }))])
    await page.keyboard.press('Escape')
  }
  out.push(['rows', (await rows(page)).length])
  // 日付: 6 行目(index 5)の 2026-11-13 から下へ 4 行フィル(連続データ = 1 日ずつ)
  await clickCell(page, 5, 'date')
  await page.waitForTimeout(150)
  const h = await page.evaluate(() => { const e = document.querySelector('.ssg-fill-handle'); const b = e?.getBoundingClientRect(); return b && { x: b.left + b.width / 2, y: b.top + b.height / 2 } })
  out.push(['handle', h])
  const target = await cell(page, 9, 'date')
  await page.mouse.move(h.x, h.y)
  await page.mouse.down()
  await page.mouse.move(h.x, target.y, { steps: 8 })
  await page.waitForTimeout(150)
  out.push(['tooltip', await page.evaluate(() => document.querySelector('.ssg-fill-tooltip')?.textContent)])
  await shot(page, 'fill-drag')
  await page.mouse.up()
  await page.waitForTimeout(300)
  out.push(['dates', (await rows(page)).map((r) => r.date)])
  // オプションのボタン → セルのコピー
  const opt = await page.evaluate(() => { const e = document.querySelector('.ssg-fill-options'); const b = e?.getBoundingClientRect(); return b && { x: b.left + b.width / 2, y: b.top + b.height / 2, label: e.getAttribute('aria-label') } })
  out.push(['options btn', opt])
  if (opt) {
    await page.mouse.click(opt.x, opt.y)
    await page.waitForTimeout(200)
    out.push(['menu', await page.evaluate(() => [...document.querySelectorAll('.ssg-fill-menu [role=menuitemradio]')].map((e) => e.textContent + ':' + e.getAttribute('aria-checked')))])
    await shot(page, 'fill-menu')
    const copy = await page.evaluate(() => { const e = [...document.querySelectorAll('.ssg-fill-menu [role=menuitemradio]')].find((x) => x.textContent.includes('コピー')); const b = e.getBoundingClientRect(); return { x: b.left + 10, y: b.top + b.height / 2 } })
    await page.mouse.click(copy.x, copy.y)
    await page.waitForTimeout(300)
    out.push(['dates after copy', (await rows(page)).map((r) => r.date)])
  }
  // 元に戻す 1 回でフィル前へ
  await page.click('[data-testid=undo]')
  await page.waitForTimeout(300)
  out.push(['dates after undo', (await rows(page)).map((r) => r.date)])
  out.push(['undo state', await page.evaluate(() => ({ u: document.querySelector('[data-testid=undo]').disabled, r: document.querySelector('[data-testid=redo]').disabled }))])
  await page.evaluate(() => window.__grid.scrollToTop()); await page.waitForTimeout(200)
  // 科目(custom)をフィル = コピー。金額 2 つ(1240, 3300)→ 連続データ
  const a = await cell(page, 0, 'amount')
  const b = await cell(page, 1, 'amount')
  await page.mouse.move(a.x, a.y); await page.mouse.down(); await page.mouse.move(b.x, b.y, { steps: 3 }); await page.mouse.up()
  await page.waitForTimeout(150)
  out.push(['sel before h2', await page.evaluate(() => window.__grid.getSelection()), await page.evaluate(() => document.querySelectorAll('.ssg-fill-handle').length)])
  for (const o of out) console.log(JSON.stringify(o)); out.length = 0
  await shot(page, 'fill-h2')
  const h2 = await page.evaluate(() => { const e = document.querySelector('.ssg-fill-handle'); const b = e?.getBoundingClientRect(); return b && { x: b.left + b.width / 2, y: b.top + b.height / 2 } })
  const t2 = await cell(page, 3, 'amount')
  await page.mouse.move(h2.x, h2.y); await page.mouse.down(); await page.mouse.move(h2.x, t2.y, { steps: 6 }); await page.mouse.up()
  await page.waitForTimeout(300)
  out.push(['amount series', (await rows(page)).slice(0, 4).map((r) => r.amount)])
  // Ctrl を押しながら = コピー
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(200)
  await page.mouse.move(a.x, a.y); await page.mouse.down(); await page.mouse.move(b.x, b.y, { steps: 3 }); await page.mouse.up()
  await page.waitForTimeout(150)
  await page.mouse.move(h2.x, h2.y); await page.mouse.down(); await page.keyboard.down('Control'); await page.mouse.move(h2.x, t2.y, { steps: 6 }); await page.mouse.up(); await page.keyboard.up('Control')
  await page.waitForTimeout(300)
  out.push(['amount ctrl copy', (await rows(page)).slice(0, 4).map((r) => r.amount)])
  // 消費税(編集できない列)のフィルは飛ばす / 人数(reject)へ 0 を含む series
  for (const o of out) console.log(JSON.stringify(o))
  console.log('--- logs')
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('what it means') && !l.includes('agent repair') && !l.includes('deeper evidence') && !l.startsWith('  ')).join('\n'))
  await browser.close()
})()

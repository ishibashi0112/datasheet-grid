const { open, cell, clickCell, rows, shot, ime } = require('./lib.cjs')
;(async () => {
  const url = process.argv[2] || 'http://localhost:5509/'
  const { browser, page, logs, cdp } = await open(url)
  const out = []
  const act = () => page.evaluate(() => { const a = document.activeElement; return `${a?.tagName}.${a?.className}${a?.closest('dialog') ? ' (in dialog)' : ''}` })
  // 誤りを 2 つ作る: 3 行目の金額 12.5、4 行目(18,700 円)の摘要を空に
  await clickCell(page, 2, 'amount'); await page.keyboard.type('12.5'); await page.keyboard.press('Enter'); await page.waitForTimeout(150)
  await clickCell(page, 3, 'memo'); await page.keyboard.press('Delete'); await page.waitForTimeout(150)
  await page.click('[data-testid=confirm]')
  await page.waitForTimeout(400)
  out.push(['invalid list', await page.evaluate(() => [...document.querySelectorAll('[data-testid=invalid-list] li')].map((l) => l.textContent))])
  // ダイアログの中で摘要を直す(IME)
  const dg = '[aria-label="確認する明細"]'
  const c = await cell(page, 3, 'memo', dg)
  await page.mouse.click(c.x, c.y)
  await page.waitForTimeout(150)
  out.push(['dialog grid focus', await act()])
  await page.keyboard.press('F2')
  await page.waitForTimeout(150)
  await ime(cdp, page, 'かいしょく', '会食')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(250)
  out.push(['memo fixed in dialog', (await rows(page))[3].memo, await act(), await page.evaluate(() => document.querySelector('dialog').open)])
  // 一覧の 1 つ目(3 行目 金額)へ飛ぶ
  const btns = await page.$$('[data-testid=invalid-list] button')
  out.push(['buttons', btns.length])
  await btns[0].click()
  await page.waitForTimeout(400)
  out.push(['jump', await page.evaluate(() => document.querySelector('dialog').open), await page.evaluate(() => window.__grid.getActiveCell()), await act()])
  await shot(page, 'jump')
  await page.keyboard.type('1250')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  out.push(['fixed amount', (await rows(page))[2].amount])
  // body へポータルする書き方(ドキュメントの例)だとダイアログの後ろに隠れるか
  await page.goto(new URL('?bodyportal', url).href)
  await page.waitForSelector('.ssg-body-cell')
  await page.click('[data-testid=confirm]')
  await page.waitForTimeout(400)
  const c2 = await cell(page, 0, 'account', dg)
  await page.mouse.dblclick(c2.x, c2.y)
  await page.waitForTimeout(300)
  out.push(['body portal', await page.evaluate(() => { const l = document.querySelector('[data-testid=account-list]'); if (!l) return null; const b = l.getBoundingClientRect(); const top = document.elementFromPoint(b.left + 20, b.top + 12); return { parent: l.parentElement.tagName, hit: top?.closest('[data-testid=account-list]') ? 'list' : top?.tagName + '.' + top?.className } })])
  await shot(page, 'dialog-bodyportal')
  for (const o of out) console.log(JSON.stringify(o))
  console.log('--- logs')
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('what it means') && !l.includes('agent repair') && !l.includes('deeper evidence') && !l.startsWith('  ') && !l.includes('STRICT_READ')).join('\n'))
  await browser.close()
})()

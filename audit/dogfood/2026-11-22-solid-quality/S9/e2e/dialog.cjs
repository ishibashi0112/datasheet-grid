const { open, cell, clickCell, rows, shot, ime } = require('./lib.cjs')
;(async () => {
  const url = process.argv[2] || 'http://localhost:5509/'
  const { browser, page, logs, cdp } = await open(url)
  const out = []
  const act = () => page.evaluate(() => { const a = document.activeElement; return `${a?.tagName}.${a?.className}${a?.name ? '[' + a.name + ']' : ''}${a?.closest('dialog') ? ' (in dialog)' : ''}` })
  // フォーム → グリッド → フォーム
  await page.click('input[name=name]')
  await ime(cdp, page, 'やまだ', '山田')
  out.push(['name', await page.inputValue('input[name=name]')])
  await clickCell(page, 0, 'memo')
  await ime(cdp, page, 'てすと', 'テスト')
  out.push(['editing memo', await act()])
  await page.click('input[name=name]')
  await page.waitForTimeout(250)
  out.push(['after click form while editing', await act(), (await rows(page))[0].memo])
  await ime(cdp, page, 'たろう', '太郎')
  out.push(['name2', await page.inputValue('input[name=name]')])
  // Tab の順: 目的 → ボタン … → グリッド
  await page.click('input[name=purpose]')
  const seq = []
  for (let i = 0; i < 8; i++) { await page.keyboard.press('Tab'); seq.push(await act()) }
  out.push(['tab seq', seq])
  await page.keyboard.press('ArrowDown')
  await page.waitForTimeout(100)
  out.push(['arrow in grid', await page.evaluate(() => window.__grid.getActiveCell()), await act()])
  // 確認のダイアログ
  await page.evaluate(() => window.__grid.setActiveCell(null))
  await page.click('[data-testid=confirm]')
  await page.waitForTimeout(400)
  out.push(['dialog open', await page.evaluate(() => document.querySelector('dialog').open), await act()])
  out.push(['invalid list', await page.evaluate(() => [...document.querySelectorAll('[data-testid=invalid-list] li')].map((l) => l.textContent))])
  await shot(page, 'dialog-open')
  // ダイアログの中のグリッド: 摘要をダブルクリックで編集 → Escape → ダイアログは開いたまま
  const dg = '[aria-label="確認する明細"]'
  const c1 = await cell(page, 1, 'memo', dg)
  await page.mouse.dblclick(c1.x, c1.y)
  await page.waitForTimeout(200)
  out.push(['dialog edit', await act()])
  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)
  out.push(['after esc edit', await page.evaluate(() => document.querySelector('dialog').open), await act()])
  // 1 セルだけ選んで Escape → ダイアログへ届いて閉じる
  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)
  out.push(['after esc single', await page.evaluate(() => document.querySelector('dialog').open), await act()])
  // 開き直して、科目の custom エディタ(候補はダイアログの中へ)
  await page.click('[data-testid=confirm]')
  await page.waitForTimeout(400)
  const c2 = await cell(page, 0, 'account', dg)
  await page.mouse.dblclick(c2.x, c2.y)
  await page.waitForTimeout(300)
  const list = await page.evaluate(() => { const l = document.querySelector('[data-testid=account-list]'); if (!l) return null; const b = l.getBoundingClientRect(); const top = document.elementFromPoint(b.left + 20, b.top + 12); return { parent: l.parentElement.tagName, hit: top?.closest('[data-testid=account-list]') ? 'list' : top?.tagName + '.' + top?.className, x: b.left + 20, y: b.top + 40 } })
  out.push(['custom list in dialog', list])
  await shot(page, 'dialog-custom')
  if (list) {
    await page.mouse.click(list.x, list.y)
    await page.waitForTimeout(300)
  }
  out.push(['account after click', (await rows(page))[0].account, await act()])
  // 列メニュー(⋮)
  const menuBtn = await page.evaluate((dg) => { const root = document.querySelector(dg).closest('.ssg-root'); const b = root.querySelector('[aria-label="金額(税込) の列メニュー"]'); const r = b?.getBoundingClientRect(); return r && { x: r.left + r.width / 2, y: r.top + r.height / 2 } }, dg)
  const hdr = await page.evaluate((dg) => { const root = document.querySelector(dg).closest('.ssg-root'); const h = [...root.querySelectorAll('[role=columnheader]')].find((e) => e.textContent.includes('金額')); const r = h.getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.height / 2 } }, dg)
  await page.mouse.move(hdr.x, hdr.y)
  await page.waitForTimeout(200)
  const menuBtn2 = await page.evaluate((dg) => { const root = document.querySelector(dg).closest('.ssg-root'); const b = root.querySelector('[aria-label="金額(税込) の列メニュー"]'); const r = b?.getBoundingClientRect(); return r && { x: r.left + r.width / 2, y: r.top + r.height / 2 } }, dg)
  if (menuBtn2) await page.mouse.click(menuBtn2.x, menuBtn2.y)
  await page.waitForTimeout(300)
  out.push(['col menu', await page.evaluate(() => { const m = document.querySelector('[role=menu]'); if (!m) return null; const b = m.getBoundingClientRect(); const hit = document.elementFromPoint(b.left + 20, b.top + 20); return { inDialog: !!m.closest('dialog'), hit: !!hit?.closest('[role=menu]'), items: [...m.querySelectorAll('[role^=menuitem]')].map((x) => x.textContent).slice(0, 4) } })])
  await shot(page, 'dialog-colmenu')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)
  out.push(['after esc menu', await page.evaluate(() => document.querySelector('dialog').open)])
  // 誤りの一覧から「直す」へ飛ぶ
  const firstInvalid = await page.$('[data-testid=invalid-list] button')
  if (firstInvalid) {
    await firstInvalid.click()
    await page.waitForTimeout(300)
    out.push(['jump', await page.evaluate(() => document.querySelector('dialog').open), await page.evaluate(() => window.__grid.getActiveCell()), await act()])
    await ime(cdp, page, 'ないよう', '内容')
    out.push(['typing after jump', await page.evaluate(() => document.querySelector('.ssg-cell-editor textarea, .ssg-cell-editor input')?.value)])
  } else out.push(['no invalid'])
  for (const o of out) console.log(JSON.stringify(o))
  console.log('--- logs')
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('what it means') && !l.includes('agent repair') && !l.includes('deeper evidence') && !l.startsWith('  ')).join('\n'))
  await browser.close()
})()

const { open, shot } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open({ clipboard: true, viewport: { width: 1000, height: 600 } })
  await page.goto('http://localhost:5511/frame.html')
  await page.waitForTimeout(1500)
  const cell = (r, c) => page.locator(`[data-pane="center"][role="row"][data-row-index="${r}"] [role="gridcell"]`).nth(c)
  const b = await cell(2, 1).boundingBox()
  console.log('box', b)
  await page.mouse.click(b.x + 20, b.y + 10, { button: 'right' })
  await page.waitForTimeout(500)
  console.log('menus', await page.evaluate(() => [...document.querySelectorAll('[role=menu]')].map((m) => m.textContent.slice(0, 60))))
  await shot(page, 'frame-top-ctx')
  await page.keyboard.press('Escape')
  const t = await cell(1, 0).boundingBox()
  await page.mouse.move(t.x + 40, t.y + 10); await page.waitForTimeout(300); await page.mouse.move(t.x + 45, t.y + 12); await page.waitForTimeout(1200)
  console.log('tooltip', await page.evaluate(() => { const el = document.querySelector('.ssg-tooltip'); return el ? el.outerHTML.slice(0, 200) : 'なし' }))
  await shot(page, 'frame-top-tip')
  console.log(logs.join('\n'))
  await browser.close()
})()

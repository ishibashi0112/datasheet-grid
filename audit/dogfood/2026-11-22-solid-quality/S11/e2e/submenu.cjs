// 列メニューの「列の固定」の小メニューと、右クリック →「フィルターを管理…」のツールパネル(Shadow の中)
const { open, shot } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open()
  await page.goto('http://localhost:5511/' + (process.env.Q ?? '?popup=shadow&noframe=1'))
  await page.waitForTimeout(2000)
  const W = 'stock-widget'
  const where = (sel) => page.evaluate((sel) => {
    const sr = document.querySelector('stock-widget').shadowRoot
    const els = [...sr.querySelectorAll(sel)].map((e) => ['shadow', e]).concat([...document.querySelectorAll(sel)].map((e) => ['document', e]))
    return els.length ? els.map(([w, e]) => { const r = e.getBoundingClientRect(); return `${w} ${Math.round(r.x)},${Math.round(r.y)} ${Math.round(r.width)}x${Math.round(r.height)}` }).join(' / ') : 'なし'
  }, sel)
  const deepFocus = () => page.evaluate(() => { const deep = (d) => d.activeElement?.shadowRoot ? deep(d.activeElement.shadowRoot) : d.activeElement; const a = deep(document); return a?.tagName + '.' + String(a?.className).split(' ')[0] + ' ' + (a?.textContent?.trim().slice(0, 20) ?? '') })
  await page.locator(`${W} [role=columnheader][data-ssg-col-key="price"]`).hover()
  await page.locator(`${W} button[aria-label="単価 の列メニュー"]`).click(); await page.waitForTimeout(400)
  console.log('列メニューの項目', await page.locator(`${W} [role=menu] [role^=menuitem]`).allTextContents())
  const pin = page.locator(`${W} [role=menu] [role^=menuitem]`, { hasText: '列の固定' }).first()
  await pin.hover(); await page.waitForTimeout(500)
  console.log('小メニュー hover →', await where('[role=menu]'))
  await pin.click(); await page.waitForTimeout(400)
  console.log('小メニュー click →', await where('[role=menu]'), 'focus', await deepFocus())
  const left = page.locator(`${W} [role=menu] [role^=menuitem]`, { hasText: '左' }).last()
  console.log('左の項目', await left.count(), await left.textContent().catch(() => ''))
  await shot(page, 'submenu-shadow')
  await left.click(); await page.waitForTimeout(400)
  const pinned = await page.evaluate(() => [...document.querySelector('stock-widget').shadowRoot.querySelectorAll('[data-pane="left"] [role=columnheader][data-ssg-col-key]')].map((e) => e.dataset.ssgColKey))
  console.log('左に固定した列', pinned, 'メニュー', await where('[role=menu]'))
  // キーボード: 列メニューを Alt+↓ で開いて、矢印で動かして Escape
  await page.locator(`${W} [data-pane="center"][role="row"][data-row-index="2"] [role="gridcell"]`).nth(1).click({ position: { x: 20, y: 14 } })
  await page.keyboard.press('Alt+ArrowDown'); await page.waitForTimeout(400)
  console.log('Alt+↓', await where('[role=menu]'), 'focus', await deepFocus())
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown'); await page.waitForTimeout(100)
  console.log('↓↓ focus', await deepFocus())
  await page.keyboard.press('Escape'); await page.waitForTimeout(300)
  console.log('Escape', await where('[role=menu]'), 'focus', await deepFocus())
  // Shift+F10 で右クリックメニュー → フィルターを管理…
  await page.keyboard.press('Shift+F10'); await page.waitForTimeout(400)
  console.log('Shift+F10', await where('[role=menu]'), 'focus', await deepFocus())
  await page.locator(`${W} [role=menu] [role^=menuitem]`, { hasText: 'フィルターを管理' }).click(); await page.waitForTimeout(800)
  console.log('ツールパネル', await where('[role=dialog]'), 'focus', await deepFocus())
  await shot(page, 'toolpanel-shadow')
  await page.keyboard.press('Escape'); await page.waitForTimeout(400)
  console.log('Escape 後 ツールパネル', await where('.ssg-tool-panel, [role=dialog]'), 'focus', await deepFocus())
  console.log(logs.filter((l) => !/HUGE_FAN_OUT|subscribers|in <|at http/.test(l)).join('\n'))
  await browser.close()
})()

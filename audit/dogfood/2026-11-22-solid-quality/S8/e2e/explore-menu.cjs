const { open, shot } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open()
  await page.goto('http://localhost:3508/?date=today')
  await page.waitForTimeout(1500)
  const hdr = page.locator('[role=columnheader][data-ssg-col-key="date"]')
  await hdr.hover()
  await page.locator('button[aria-label="日付 の列メニュー"]').click()
  await page.waitForTimeout(400)
  console.log(await page.evaluate(() => [...document.querySelectorAll('[role=menu] [role^=menuitem]')].map((e) => e.textContent.trim())))
  await shot(page, 'explore-menu')
  const item = page.locator('[role=menu] [role^=menuitem]', { hasText: 'フィルター' }).first()
  await item.click()
  await page.waitForTimeout(600)
  console.log(await page.evaluate(() => [...document.querySelectorAll('body > *')].map((e) => e.tagName + '.' + e.className + ' ' + (e.getAttribute('role') ?? '')).join('\n')))
  await shot(page, 'explore-filter')
  const pop = await page.evaluate(() => { const p = document.querySelector('[role=dialog]'); return p ? p.outerHTML.slice(0, 3000) : null })
  console.log(pop)
  console.log(logs.filter((l) => !l.includes('vite')).join('\n'))
  await browser.close()
})()

const { open, click, text, shot, cell } = require('./lib.cjs')
;(async () => {
  const tab = process.argv[2] || 'signal'
  const { browser, page, logs } = await open(`${process.env.BASE || "http://localhost:5501/"}?tab=${tab}`)
  const st = (l) => page.evaluate((l) => JSON.stringify({ l, active: window.__grid.getActiveCell(), sel: window.__grid.getSelection(), n: window.__getRows().length, changes: window.__rowsChangeCount, focus: document.activeElement.className || document.activeElement.tagName }), l)
  // まずセル(行 3 品名)を選ぶ
  await click(page, 4, 3)
  console.log(await st('select r3'))
  // 行 2 の「確定」ボタン(状態列 aria 11)
  const btn = page.locator('[role="row"][aria-rowindex="3"] [aria-colindex="11"] [data-testid="toggle-status"]').first()
  await btn.click()
  await page.waitForTimeout(200)
  console.log(await st('after toggle-status btn'), 'status r2 =', await page.evaluate(() => window.__getRows()[1].status), 'btn text', await btn.innerText())
  // 確定した行は編集できない: 品名にタイプ
  await click(page, 3, 3)
  await page.keyboard.type('x')
  await page.waitForTimeout(150)
  console.log('typing in confirmed row editor?', (await page.$('.ssg-cell-editor')) !== null)
  await page.keyboard.press('Escape')
  await page.keyboard.press('Delete')
  await page.waitForTimeout(100)
  console.log('after Delete in confirmed row', await text(page, 3, 3))
  // もう一度押して戻す(連打)
  await btn.click()
  await page.waitForTimeout(150)
  console.log('status r2 after 2nd click', await page.evaluate(() => window.__getRows()[1].status))
  // 削除ボタン(行 4 = P-00004)
  const del = page.locator('[role="row"][aria-rowindex="5"] [aria-colindex="12"] [data-testid="delete-row"]').first()
  await del.click()
  await page.waitForTimeout(200)
  console.log(await st('after delete btn'), 'row ids head', await page.evaluate(() => window.__getRows().slice(0, 5).map((r) => r.id).join(',')))
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(200)
  console.log(await st('after ctrl+z'), 'row ids head', await page.evaluate(() => window.__getRows().slice(0, 5).map((r) => r.id).join(',')))
  // ハンドル: focus / startEditing
  await page.click('#add-name')
  await page.click('#btn-focus')
  await page.waitForTimeout(100)
  console.log('after focus()', await st('focus'))
  await page.keyboard.press('ArrowDown')
  await page.waitForTimeout(100)
  console.log('after ArrowDown', await st('down'))
  await page.click('#btn-edit')
  await page.waitForTimeout(150)
  console.log('after startEditing()', await st('edit'), 'editor', (await page.$('.ssg-cell-editor')) !== null)
  await page.keyboard.type('Z')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(150)
  console.log('after type Z enter', await st('typed'))
  // 1000 行目へ
  await page.click('#btn-scroll')
  await page.waitForTimeout(300)
  console.log('visible range', await page.evaluate(() => JSON.stringify(window.__grid.getVisibleRowRange())))
  await shot(page, `t7-scroll-${tab}`)
  console.log('LOGS:\n' + logs.filter((l) => !l.includes('[vite]')).join('\n'))
  await browser.close()
})()

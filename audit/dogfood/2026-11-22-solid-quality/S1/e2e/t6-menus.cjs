const { open, click, text, shot, cell } = require('./lib.cjs')
;(async () => {
  const tab = process.argv[2] || 'signal'
  const { browser, page, logs } = await open(`${process.env.BASE || "http://localhost:5501/"}?tab=${tab}`)
  const hdr = (i) => page.locator(`[role="columnheader"][aria-colindex="${i}"]`).first()
  // 列メニュー(区分)
  await hdr(4).hover()
  await page.waitForTimeout(150)
  const menuBtn = hdr(4).locator('button, [role="button"]').last()
  await menuBtn.click()
  await page.waitForTimeout(250)
  const items = await page.$$eval('[role="menu"] [role^="menuitem"]', (els) => els.map((e) => e.textContent.trim()))
  console.log('column menu items', items)
  await shot(page, `t6-colmenu-${tab}`)
  // フィルター… を開く
  await page.getByRole('menuitem', { name: /フィルター/ }).first().click()
  await page.waitForTimeout(500)
  await shot(page, `t6-filter-${tab}`)
  const popText = await page.evaluate(() => {
    const d = document.querySelector('.ssg-filter-popover, [role="dialog"]')
    return d ? d.textContent.slice(0, 200) : null
  })
  console.log('filter popover', popText)
  // set フィルター: 「食品」だけ外す
  const cb = page.getByRole('checkbox', { name: /食品/ })
  if (await cb.count()) {
    await cb.first().click()
    await page.waitForTimeout(100)
    const apply = page.getByRole('button', { name: /適用|OK/ })
    if (await apply.count()) await apply.first().click()
  }
  await page.keyboard.press('Escape')
  await page.waitForTimeout(400)
  console.log('state after filter', await page.evaluate(() => JSON.stringify(window.__grid.getState().filters)))
  console.log('top bar', await page.$eval('.ssg-top-bar, [class*="top-bar"]', (e) => e.textContent).catch(() => 'n/a'))
  await shot(page, `t6-filtered-${tab}`)
  // ツールパネル(フィルターチップ)
  await page.evaluate(() => window.__grid.openFilterManager())
  await page.waitForTimeout(500)
  await shot(page, `t6-toolpanel-${tab}`)
  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)
  // 状態の保存 → クリア → 復元
  await page.click('#btn-save-state')
  await page.evaluate(() => window.__grid.applyState({ filters: { globalText: '', columnFilters: {} } }))
  await page.waitForTimeout(200)
  console.log('cleared', await page.evaluate(() => JSON.stringify(window.__grid.getState().filters)))
  await page.click('#btn-restore-state')
  await page.waitForTimeout(200)
  console.log('restored', await page.evaluate(() => JSON.stringify(window.__grid.getState().filters)))
  // 右クリックメニュー
  await click(page, 5, 3, { button: 'right' })
  await page.waitForTimeout(200)
  console.log('ctx menu', await page.$$eval('[role="menu"] [role^="menuitem"]', (els) => els.map((e) => e.textContent.trim())))
  await shot(page, `t6-ctxmenu-${tab}`)
  await page.keyboard.press('Escape')
  // 検索 Ctrl+F
  await click(page, 3, 3)
  await page.keyboard.press('Control+f')
  await page.waitForTimeout(200)
  await page.keyboard.type('ドライヤー')
  await page.waitForTimeout(500)
  console.log('find bar', await page.evaluate(() => { const b = document.querySelector('.ssg-find-bar, [class*="find"]'); return b ? b.textContent : null }))
  console.log('marks', await page.$$eval('mark.ssg-find-mark', (e) => e.length))
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  console.log('active after find enter', await page.evaluate(() => JSON.stringify(window.__grid.getActiveCell())))
  await shot(page, `t6-find-${tab}`)
  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)
  console.log('focus after find esc', await page.evaluate(() => document.activeElement.className))
  console.log('LOGS:\n' + logs.filter((l) => !l.includes('[vite]')).join('\n'))
  await browser.close()
})()

// HMR: グリッドの隣の部品(Toolbar.tsx)だけを書き換えたとき、グリッドの状態と編集中のエディタは残るか
const fs = require('fs')
const path = require('path')
const { open, click } = require('./lib.cjs')
const TB = path.join(__dirname, '..', 'src', 'Toolbar.tsx')
const orig = fs.readFileSync(TB, 'utf8')
const restore = () => fs.writeFileSync(TB, orig)
process.on('exit', restore)
;(async () => {
  const { browser, page, logs, context } = await open('http://localhost:5501/?tab=signal')
  const cdp = await context.newCDPSession(page)
  const win = async () => (await cdp.send('DOMDebugger.getEventListeners', { objectId: (await cdp.send('Runtime.evaluate', { expression: 'window' })).result.objectId })).listeners.length
  const st = async (l) => ({ l, win: await win(), ...(await page.evaluate(() => ({ r2: window.__getRows()[1].name, canUndo: window.__grid.canUndo(), editor: !!document.querySelector('.ssg-cell-editor'), ev: document.querySelector('.ssg-cell-editor input,.ssg-cell-editor textarea')?.value ?? null, undoBtn: document.getElementById('btn-undo')?.textContent, focus: document.activeElement?.className?.slice?.(0, 40) }))) })
  await click(page, 3, 3, { clickCount: 2 }); await page.keyboard.press('Control+a'); await page.keyboard.type('編集済み'); await page.keyboard.press('Enter'); await page.waitForTimeout(200)
  console.log(JSON.stringify(await st('edited')))
  await click(page, 4, 3, { clickCount: 2 }); await page.keyboard.press('Control+a'); await page.keyboard.type('打ちかけ'); await page.waitForTimeout(150)
  console.log(JSON.stringify(await st('editing')))
  fs.writeFileSync(TB, orig.replace('>\n        元に戻す\n', '>\n        元に戻す(HMR)\n'))
  await page.waitForTimeout(1500)
  console.log(JSON.stringify(await st('after HMR Toolbar.tsx')))
  await page.keyboard.type('X'); await page.keyboard.press('Enter'); await page.waitForTimeout(200)
  console.log(JSON.stringify(await st('typed X enter')), await page.evaluate(() => window.__getRows()[2].name))
  await page.click('#btn-undo'); await page.waitForTimeout(200)
  console.log(JSON.stringify(await st('undo via HMR-ed toolbar')), await page.evaluate(() => window.__getRows()[2].name))
  console.log('LOGS', logs.filter((l) => !/\[vite\]/.test(l)).join('\n'))
  await browser.close()
})().catch((e) => { console.error(e); process.exit(1) })

const { open, click, text, shot, cell } = require('./lib.cjs')
;(async () => {
  const tab = process.argv[2] || 'signal'
  const { browser, page, logs } = await open(`${process.env.BASE || "http://localhost:5501/"}?tab=${tab}`)
  const st = (l) => page.evaluate((l) => JSON.stringify({ l, active: window.__grid.getActiveCell(), editing: !!document.querySelector('.ssg-cell-editor'), n: window.__getRows().length, changes: window.__rowsChangeCount, focus: (document.activeElement.id || document.activeElement.className || document.activeElement.tagName).slice(0, 40), log: window.__log.slice(-1)[0] }), l)
  await click(page, 4, 3)
  await page.click('#add-name')
  await page.click('#btn-edit')
  await page.waitForTimeout(150)
  console.log(await st('startEditing() from button'))
  await page.keyboard.type('X')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(150)
  console.log(await st('typed X + Enter'), await text(page, 4, 3))
  // 編集中にフォームを押す → 確定・フォーカスはフォームのまま
  await click(page, 5, 3, { clickCount: 2 })
  await page.keyboard.press('End')
  await page.keyboard.type('★')
  await page.click('#add-name')
  await page.waitForTimeout(300)
  console.log(await st('clicked form while editing'), 'r4 name =', await page.evaluate(() => window.__getRows()[3].name))
  // フォームで入力・Tab・Enter
  await page.keyboard.type('新しい品目')
  await page.keyboard.press('Tab')
  await page.waitForTimeout(50)
  console.log('focus after Tab in form', await page.evaluate(() => document.activeElement.id))
  await page.keyboard.press('Tab')
  await page.keyboard.press('Control+a')
  await page.keyboard.type('25')
  const before = await page.evaluate(() => window.__grid.getActiveCell())
  await page.keyboard.press('Enter') // フォームを送信 → 行を追加 → flush() → startEditing(数量)
  await page.waitForTimeout(400)
  console.log(await st('form submitted'), 'active before', JSON.stringify(before))
  const last = await page.evaluate(() => window.__getRows().slice(-1)[0])
  console.log('last row', JSON.stringify(last))
  await shot(page, `t8-after-add-${tab}`)
  await page.keyboard.type('30')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  console.log(await st('typed 30 enter'), 'last qty', await page.evaluate(() => window.__getRows().slice(-1)[0].qty))
  // 追加は元に戻せない(setRows で直接) → 履歴が消えるか
  console.log('canUndo', await page.evaluate(() => window.__grid.canUndo()))
  console.log('LOGS:\n' + logs.filter((l) => !l.includes('[vite]')).join('\n'))
  await browser.close()
})()

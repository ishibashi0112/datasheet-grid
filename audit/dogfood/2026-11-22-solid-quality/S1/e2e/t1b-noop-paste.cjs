const { open, click, text } = require('./lib.cjs')
;(async () => {
  const tab = process.argv[2] || 'signal'
  const { browser, page, logs } = await open(`http://localhost:5501/?tab=${tab}`)
  const st = async (label) => console.log(label, await page.evaluate(() => JSON.stringify({ changes: window.__rowsChangeCount, canUndo: window.__grid.canUndo(), r3: window.__getRows()[2].name, r6: window.__getRows()[5].name, active: window.__grid.getActiveCell() })))
  await click(page, 4, 3)
  await page.evaluate((t) => navigator.clipboard.writeText(t), '貼り付け品A')
  await page.keyboard.press('Control+v')
  await page.waitForTimeout(200)
  await st('after paste r3')
  await click(page, 7, 3)
  await page.evaluate((t) => navigator.clipboard.writeText(t), 'これは入らない\t文具\t1')
  await page.keyboard.press('Control+v')
  await page.waitForTimeout(200)
  await st('after paste to confirmed r6')
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(200)
  await st('after undo 1')
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(200)
  await st('after undo 2')
  console.log('LOGS:\n' + logs.filter((l) => !l.includes('[vite]')).join('\n'))
  await browser.close()
})()

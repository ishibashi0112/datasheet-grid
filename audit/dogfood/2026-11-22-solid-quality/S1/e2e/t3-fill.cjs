const { open, click, text, shot, cell } = require('./lib.cjs')
;(async () => {
  const tab = process.argv[2] || 'signal'
  const { browser, page, logs } = await open(`${process.env.BASE || "http://localhost:5501/"}?tab=${tab}`)
  const rows = () => page.evaluate(() => window.__getRows().slice(0, 12).map((r) => [r.id, r.qty, r.due, r.status]))
  // 数量: 行 2,3(P-00002, P-00003)を 1,2 にしてから下へフィル
  await click(page, 3, 5)
  await page.keyboard.type('1')
  await page.keyboard.press('Enter')
  await page.keyboard.type('2')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(150)
  // 範囲選択 qty r2..r3 + due r2..r3(Shift+クリック)
  await click(page, 3, 5)
  await page.keyboard.down('Shift')
  await click(page, 4, 8)
  await page.keyboard.up('Shift')
  await page.waitForTimeout(150)
  const h = await page.$('.ssg-fill-handle')
  const hb = h && (await h.boundingBox())
  console.log('handle', JSON.stringify(hb))
  const target = await (await cell(page, 9, 8)).boundingBox() // 行 8(P-00008)まで
  await page.mouse.move(hb.x + hb.width / 2, hb.y + hb.height / 2)
  await page.mouse.down()
  await page.mouse.move(hb.x + 2, hb.y + 40, { steps: 4 })
  await page.mouse.move(target.x + target.width / 2, target.y + target.height / 2, { steps: 10 })
  await page.waitForTimeout(100)
  const tip = await page.$eval('.ssg-fill-tooltip', (e) => e.textContent).catch(() => null)
  console.log('tooltip', tip)
  await shot(page, `t3-fill-drag-${tab}`)
  await page.mouse.up()
  await page.waitForTimeout(200)
  console.log('after fill', JSON.stringify(await rows()))
  console.log('selection', await page.evaluate(() => JSON.stringify(window.__grid.getSelection())))
  await shot(page, `t3-fill-done-${tab}`)
  // 埋めたあとのボタン → セルのコピー
  const opt = await page.$('.ssg-fill-options')
  if (opt) {
    await opt.click()
    await page.waitForTimeout(150)
    const items = await page.$$eval('.ssg-fill-menu [role="menuitemradio"]', (els) => els.map((e) => e.textContent + ':' + e.getAttribute('aria-checked')))
    console.log('fill menu', items)
    await page.click('.ssg-fill-menu [role="menuitemradio"]:nth-child(2)')
    await page.waitForTimeout(200)
    console.log('after copy', JSON.stringify(await rows()))
  } else console.log('no fill options button')
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(200)
  console.log('after undo', JSON.stringify(await rows()))
  console.log('LOGS:\n' + logs.filter((l) => !l.includes('[vite]')).join('\n'))
  await browser.close()
})()

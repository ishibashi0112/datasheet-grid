const { chromium } = require('playwright')
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1000, height: 700 }, deviceScaleFactor: 1 })
  const logs = []; page.on('console', (m) => logs.push(m.type() + ' ' + m.text().split('\n')[0])); page.on('pageerror', (e) => logs.push('pageerror ' + e.message))
  await page.goto(process.argv[2]); await page.waitForTimeout(500)
  await page.click('#tb'); await page.waitForTimeout(50)
  const f1 = await page.evaluate(() => ({ rows: document.querySelectorAll('[data-pane="center"].ssg-body-row').length, cells: document.querySelectorAll('[data-pane="center"] .ssg-body-cell').length }))
  await page.waitForTimeout(400)
  const f2 = await page.evaluate(() => ({ rows: document.querySelectorAll('[data-pane="center"].ssg-body-row').length, cells: document.querySelectorAll('[data-pane="center"] .ssg-body-cell').length, qtyW: document.querySelector('[role="columnheader"][data-ssg-col-key="qty"]')?.getBoundingClientRect().width }))
  await page.screenshot({ path: process.argv[3] })
  console.log(process.argv[2], 'after show 50ms', JSON.stringify(f1), '450ms', JSON.stringify(f2), logs.filter((l) => !l.includes('vite') && !l.includes('React DevTools')))
  await browser.close()
})()

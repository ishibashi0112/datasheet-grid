const { open, click, text, shot, cell } = require('./lib.cjs')
;(async () => {
  const BASE = process.env.BASE || 'http://localhost:5501/'
  const { browser, page, logs } = await open(`${BASE}?tab=signal`)
  await page.click('#btn-dark')
  await page.waitForTimeout(200)
  const h = page.locator('[role="columnheader"][aria-colindex="5"]').first()
  await h.hover(); await page.waitForTimeout(100)
  await h.locator('button, [role="button"]').last().click()
  await page.waitForTimeout(250)
  await shot(page, 'dark-colmenu')
  await page.getByRole('menuitem', { name: /フィルター/ }).first().click()
  await page.waitForTimeout(500)
  await shot(page, 'dark-filter')
  await page.keyboard.press('Escape'); await page.waitForTimeout(200)
  await click(page, 4, 3, { button: 'right' }); await page.waitForTimeout(200)
  await shot(page, 'dark-ctx')
  await page.keyboard.press('Escape')
  // ツールチップ(検査 NG のセル)
  await click(page, 3, 3); await page.keyboard.press('Delete'); await page.waitForTimeout(100)
  const b = await (await cell(page, 3, 3)).boundingBox()
  await page.mouse.move(b.x + 20, b.y + 10); await page.waitForTimeout(600)
  await shot(page, 'dark-tooltip')
  // 行の選択 → 削除
  const cb = (r) => page.locator(`[role="row"][aria-rowindex="${r}"] [role="checkbox"]`).first()
  await cb(5).click(); await cb(6).click(); await page.waitForTimeout(100)
  console.log('selected keys', await page.evaluate(() => JSON.stringify(window.__grid.getSelectedRowKeys())))
  await page.click('#btn-delete-selected'); await page.waitForTimeout(200)
  console.log('after delete ids', await page.evaluate(() => window.__getRows().slice(0, 6).map((r) => r.id).join(',')), 'selection after', await page.evaluate(() => JSON.stringify(window.__grid.getSelectedRowKeys())))
  await page.click('#btn-undo'); await page.waitForTimeout(200)
  console.log('after undo btn ids', await page.evaluate(() => window.__getRows().slice(0, 6).map((r) => r.id).join(',')))
  console.log('LOGS:\n' + logs.filter((l) => !l.includes('[vite]')).join('\n'))
  await browser.close()
})()

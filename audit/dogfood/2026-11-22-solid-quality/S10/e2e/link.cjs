// 列の幅と並びをそろえる(getState / applyState)
const { open, clickCell, shot, sleep } = require('./lib.cjs')
const [qs = '?link=1'] = process.argv.slice(2)
const widths = (page, label) => page.evaluate((label) => Object.fromEntries([...document.querySelectorAll(`[role=grid][aria-label="${label}"] [role=columnheader][data-ssg-col-key]`)].map((h) => [h.getAttribute('data-ssg-col-key'), Math.round(h.getBoundingClientRect().width)])), label)
const order = (page, label) => page.evaluate((label) => [...document.querySelectorAll(`[role=grid][aria-label="${label}"] [role=columnheader][data-ssg-col-key]`)].sort((a, b) => a.getBoundingClientRect().x - b.getBoundingClientRect().x).map((h) => h.getAttribute('data-ssg-col-key')).join(','), label)
async function resize(page, label, key, dx) {
  const h = await page.$(`[role=grid][aria-label="${label}"] [role=columnheader][data-ssg-col-key=${key}] .ssg-header-resize`)
  const b = await h.boundingBox()
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2)
  await page.mouse.down()
  for (let i = 1; i <= 10; i++) await page.mouse.move(b.x + b.width / 2 + (dx * i) / 10, b.y + b.height / 2)
  await page.mouse.up()
  await sleep(300)
}
async function drag(page, label, key, toKey, side = 'right') {
  const g = await page.$(`[role=grid][aria-label="${label}"] [role=columnheader][data-ssg-col-key=${key}] .ssg-header-grip`)
  const t = await page.$(`[role=grid][aria-label="${label}"] [role=columnheader][data-ssg-col-key=${toKey}]`)
  const gb = await g.boundingBox(); const tb = await t.boundingBox()
  await page.mouse.move(gb.x + gb.width / 2, gb.y + gb.height / 2)
  await page.mouse.down()
  const tx = side === 'right' ? tb.x + tb.width - 5 : tb.x + 5
  for (let i = 1; i <= 15; i++) await page.mouse.move(gb.x + (tx - gb.x) * i / 15, gb.y + gb.height / 2)
  await sleep(100)
  await page.mouse.up()
  await sleep(600)
}
;(async () => {
  const { browser, page, logs } = await open({ viewport: { width: 1400, height: 800 } })
  await page.goto('http://localhost:5510/' + qs)
  await page.waitForSelector('[role=grid][aria-label="Orders"] [data-row-key="O00001"]')
  await clickCell(page, 'Orders', 'O00001', 'customer')
  await page.waitForSelector('[role=grid][aria-label="Lines"] [data-row-key="O00001-1"]')
  console.log('init top', JSON.stringify(await widths(page, 'Orders'))); console.log('init bot', JSON.stringify(await widths(page, 'Lines')))
  await resize(page, 'Orders', 'date', 60)
  console.log('after top date +60: top', (await widths(page, 'Orders')).date, 'bottom', (await widths(page, 'Lines')).date)
  await resize(page, 'Lines', 'qty', 40)
  console.log('after bottom qty +40: top', (await widths(page, 'Orders')).qty, 'bottom', (await widths(page, 'Lines')).qty)
  console.log('state top', JSON.stringify(await page.evaluate(() => window.__top.getState().columnWidths)))
  console.log('state bot', JSON.stringify(await page.evaluate(() => window.__bottom.getState().columnWidths)))
  // 上で注文を変えても下の幅は残るか(swap)
  await page.keyboard.press('ArrowDown'); await sleep(300)
  console.log('after switching order: bottom date/qty', (await widths(page, 'Lines')).date, (await widths(page, 'Lines')).qty)
  // 並び: 上の status を qty の右へ
  console.log('order top', await order(page, 'Orders')); console.log('order bot', await order(page, 'Lines'))
  await drag(page, 'Orders', 'status', 'amount', 'right')
  console.log('after drag top status → after amount'); console.log(' top', await order(page, 'Orders')); console.log(' bot', await order(page, 'Lines'))
  await drag(page, 'Lines', 'qty', 'status', 'right')
  console.log('after drag bottom qty → after status'); console.log(' top', await order(page, 'Orders')); console.log(' bot', await order(page, 'Lines'))
  await shot(page, 'link')
  console.log('log', JSON.stringify(await page.evaluate(() => window.__log.filter((l) => !l.startsWith('active')))))
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('RELAY_TEAR')).join('\n'))
  await browser.close()
})()

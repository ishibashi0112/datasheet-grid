// bottom=remount: 注文ごとに下の表を作り直し、getState → initialState / restoreColumnsFromState で見え方を引き継ぐ
const { open, clickCell, getCell, activeInfo, shot, sleep } = require('./lib.cjs')
const [qs = '?bottom=remount'] = process.argv.slice(2)
const widths = (page, label) => page.evaluate((label) => Object.fromEntries([...document.querySelectorAll(`[role=grid][aria-label="${label}"] [role=columnheader][data-ssg-col-key]`)].map((h) => [h.getAttribute('data-ssg-col-key'), Math.round(h.getBoundingClientRect().width)])), label)
const firstKeys = (page) => page.evaluate(() => [...document.querySelectorAll('[role=grid][aria-label="Lines"] [role=row][data-row-key]:not([data-pane=left])')].sort((a, b) => a.getBoundingClientRect().y - b.getBoundingClientRect().y).slice(0, 4).map((x) => x.getAttribute('data-row-key') + '=' + x.querySelector('[data-ssg-col-key=qty]')?.textContent).join(','))
;(async () => {
  const { browser, page, logs } = await open({ viewport: { width: 1400, height: 800 } })
  await page.goto('http://localhost:5510/' + qs)
  await page.waitForSelector('[role=grid][aria-label="Orders"] [data-row-key="O00001"]')
  await clickCell(page, 'Orders', 'O00001', 'customer')
  await page.waitForSelector('[role=grid][aria-label="Lines"] [data-row-key="O00001-1"]')
  // 下で幅を変え、qty で降順に並べ、status 列を隠す(列メニュー)
  const h = await page.$('[role=grid][aria-label="Lines"] [role=columnheader][data-ssg-col-key=product] .ssg-header-resize')
  const b = await h.boundingBox()
  await page.mouse.move(b.x + 2, b.y + 10); await page.mouse.down(); await page.mouse.move(b.x + 52, b.y + 10, { steps: 8 }); await page.mouse.up(); await sleep(200)
  await page.evaluate(() => window.__bottom.applyState({ sort: [{ columnKey: 'qty', direction: 'desc' }] }))
  await sleep(200)
  console.log('O00001 before switch: widths', JSON.stringify(await widths(page, 'Lines')), 'first', await firstKeys(page))
  await page.keyboard.press('ArrowDown') // 上は O00001 にフォーカスがない(下を触った)ので上をクリックし直す
  await clickCell(page, 'Orders', 'O00002', 'customer')
  await page.waitForSelector('[role=grid][aria-label="Lines"] [data-row-key="O00002-1"]')
  await sleep(300)
  console.log('O00002 after remount: widths', JSON.stringify(await widths(page, 'Lines')), 'first', await firstKeys(page), 'state', JSON.stringify(await page.evaluate(() => { const s = window.__bottom.getState(); return { w: s.columnWidths, sort: s.sort } })))
  // 上で ↓ を 5 回(作り直しが続く)
  const t0 = Date.now()
  for (let i = 0; i < 10; i++) await page.keyboard.press('ArrowDown')
  await sleep(300)
  console.log('10 ArrowDown with remount', Date.now() - t0, 'ms; header', await page.$eval('.bottom h2', (e) => e.textContent.slice(0, 20)), 'first', await firstKeys(page))
  console.log('grids in DOM', await page.$$eval('[role=grid]', (g) => g.length), 'portals', await page.$$eval('body > *', (e) => e.map((x) => x.className || x.tagName).join('|')))
  await shot(page, 'remount')
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('RELAY_TEAR')).map((l) => l.split('\n')[0]).join('\n'))
  await browser.close()
})()

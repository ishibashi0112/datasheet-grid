// 2 つの表の間のフォーカスの移り方(Tab / クリック / F6 = ハンドルの focus() / ボタン)
const { open, clickCell, activeInfo, shot, sleep } = require('./lib.cjs')
const [qs = ''] = process.argv.slice(2)
const where = (page) => page.evaluate(() => {
  const a = document.activeElement
  const grid = a?.closest('[data-grid]')?.getAttribute('data-grid') ?? null
  return `${grid ?? '-'}:${a?.tagName}.${(a?.className || '').toString().split(' ')[0]}${a?.textContent && a.tagName === 'BUTTON' ? '(' + a.textContent.trim() + ')' : ''}`
})
;(async () => {
  const { browser, page, logs } = await open()
  await page.goto('http://localhost:5510/' + qs)
  await page.waitForSelector('[role=grid][aria-label="Orders"] [data-row-key="O00001"]')
  await clickCell(page, 'Orders', 'O00003', 'customer')
  await page.waitForSelector('[role=grid][aria-label="Lines"] [data-row-key="O00003-1"]')
  console.log('1 click top', await where(page), (await activeInfo(page, 'Orders')).active)
  // F6 → 下(下はまだアクティブセルなし)
  await page.keyboard.press('F6'); await sleep(150)
  console.log('2 F6', await where(page), 'bottom active', (await activeInfo(page, 'Lines')).active)
  await page.keyboard.press('ArrowDown'); await sleep(150)
  console.log('3 ArrowDown in bottom', await where(page), 'bottom', (await activeInfo(page, 'Lines')).active, 'top', (await activeInfo(page, 'Orders')).active)
  await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowRight'); await sleep(100)
  console.log('4 → → in bottom', (await activeInfo(page, 'Lines')).active)
  // F6 → 上へ戻る: 上のアクティブセルは残っているか、↓ で次の注文へ
  await page.keyboard.press('F6'); await sleep(150)
  console.log('5 F6 back', await where(page), 'top', (await activeInfo(page, 'Orders')).active)
  await page.keyboard.press('ArrowDown'); await sleep(200)
  console.log('6 ArrowDown top', (await activeInfo(page, 'Orders')).active, 'header', await page.$eval('.bottom h2', (e) => e.textContent.slice(0, 18)), 'bottom active', (await activeInfo(page, 'Lines')).active)
  // F6 で下 → 下のアクティブセルは前の注文の位置のまま?
  await page.keyboard.press('F6'); await sleep(150)
  console.log('7 F6 to bottom again', await where(page), 'bottom', (await activeInfo(page, 'Lines')).active)
  // Tab を何度も押して下の表の外へ、上の表の外へ
  await clickCell(page, 'Orders', 'O00004', 'note')
  await page.keyboard.press('Tab'); await sleep(100)
  console.log('8 Tab from last col of top', await where(page))
  await page.keyboard.press('Tab'); await sleep(100)
  console.log('9 Tab again', await where(page))
  await page.keyboard.press('Tab'); await sleep(100)
  console.log('10 Tab again', await where(page))
  await page.keyboard.press('Shift+Tab'); await page.keyboard.press('Shift+Tab'); await sleep(100)
  console.log('11 Shift+Tab x2', await where(page))
  // ボタン「Go to lines」
  await page.click('text=Go to lines'); await sleep(150)
  console.log('12 button', await where(page), 'bottom', (await activeInfo(page, 'Lines')).active)
  await page.keyboard.type('x'); await sleep(150)
  console.log('13 type x', await activeInfo(page, 'Lines'))
  await page.keyboard.press('Escape')
  // 下のクリック → 上のクリック
  await clickCell(page, 'Lines', 'O00004-2', 'product')
  console.log('14 click bottom', await where(page))
  await page.keyboard.press('Shift+Tab'); await sleep(100)
  console.log('15 Shift+Tab in bottom first data col?', await where(page), (await activeInfo(page, 'Lines')).active)
  await clickCell(page, 'Lines', 'O00004-2', 'code')
  await page.keyboard.press('Shift+Tab'); await sleep(100)
  console.log('16 Shift+Tab from first col of bottom', await where(page))
  await shot(page, 'focus')
  console.log('log', JSON.stringify(await page.evaluate(() => window.__log.filter((l) => l.startsWith('F6')))))
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('RELAY_TEAR')).map((l) => l.split('\n')[0]).join('\n'))
  await browser.close()
})()

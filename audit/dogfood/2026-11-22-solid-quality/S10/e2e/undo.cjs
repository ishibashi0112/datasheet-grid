// 下の表で編集 → 上で注文を変える → 下で Ctrl+Z。どの注文の明細が変わるか、選択と履歴
const { open, clickCell, getCell, activeInfo, shot, sleep } = require('./lib.cjs')
const [qs = ''] = process.argv.slice(2)
;(async () => {
  const { browser, page, logs } = await open()
  await page.goto('http://localhost:5510/' + qs)
  await page.waitForSelector('[role=grid][aria-label="Orders"] [data-row-key="O00001"]')
  await clickCell(page, 'Orders', 'O00001', 'customer')
  await page.waitForSelector('[role=grid][aria-label="Lines"] [data-row-key="O00001-1"]')
  const st = () => page.evaluate(() => ({ canUndo: window.__bottom?.canUndo?.(), canRedo: window.__bottom?.canRedo?.(), sel: JSON.stringify(window.__bottom?.getSelection?.() ?? null), topUndo: window.__top?.canUndo?.() }))
  const qtyBefore = await getCell(page, 'Lines', 'O00001-1', 'qty')
  const topQty1 = await getCell(page, 'Orders', 'O00001', 'qty')
  // 下の qty を編集
  await clickCell(page, 'Lines', 'O00001-1', 'qty')
  await page.keyboard.type('77')
  await page.keyboard.press('Enter')
  await sleep(300)
  console.log('after edit', await getCell(page, 'Lines', 'O00001-1', 'qty'), 'top qty', topQty1, '->', await getCell(page, 'Orders', 'O00001', 'qty'), await st())
  // 下で範囲を選んでおく
  await clickCell(page, 'Lines', 'O00001-2', 'product')
  await page.keyboard.press('Shift+ArrowDown')
  await page.keyboard.press('Shift+ArrowDown')
  console.log('bottom active/bar', await activeInfo(page, 'Lines'), await st())
  // 上で O00002 へ
  await clickCell(page, 'Orders', 'O00002', 'customer')
  await page.waitForSelector('[role=grid][aria-label="Lines"] [data-row-key="O00002-1"]')
  await sleep(300)
  console.log('switched: bottom', await activeInfo(page, 'Lines'), await st())
  const o2qty = await getCell(page, 'Lines', 'O00002-1', 'qty')
  const o2count = await page.$$eval('[role=grid][aria-label="Lines"] [role=row][data-row-key]', (e) => e.length)
  // 下をクリックして Ctrl+Z
  await clickCell(page, 'Lines', 'O00002-1', 'note')
  await page.keyboard.press('Control+z')
  await sleep(300)
  console.log('after ctrl+z on O00002: O00002-1 qty', o2qty, '->', await getCell(page, 'Lines', 'O00002-1', 'qty'), 'rows', o2count, '->', await page.$$eval('[role=grid][aria-label="Lines"] [role=row][data-row-key]', (e) => e.length))
  console.log('first rows', await page.$$eval('[role=grid][aria-label="Lines"] [data-pane=left][data-row-key], [role=grid][aria-label="Lines"] [role=row][data-row-key]', (e) => [...new Set(e.map((x) => x.getAttribute('data-row-key')))].slice(0, 5)))
  console.log('log', JSON.stringify(await page.evaluate(() => window.__log.filter((l) => !l.startsWith('active')))))
  console.log('top O00001 qty', await getCell(page, 'Orders', 'O00001', 'qty'), 'O00002 qty', await getCell(page, 'Orders', 'O00002', 'qty'), await st())
  await shot(page, 'undo')
  // 元へ戻って O00001 の qty
  await clickCell(page, 'Orders', 'O00001', 'customer')
  await sleep(300)
  console.log('back to O00001: qty', await getCell(page, 'Lines', 'O00001-1', 'qty'), 'rows', await page.$$eval('[role=grid][aria-label="Lines"] [role=row][data-row-key]', (e) => [...new Set(e.map((x) => x.getAttribute('data-row-key')))].length), await st())
  console.log(logs.filter((l) => !l.includes('[vite]')).map((l) => l.split('\n')[0]).join('\n'))
  await browser.close()
})()

const { open, sleep, cell, val, activeRef, center } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open('http://127.0.0.1:5503/')
  await page.waitForSelector('.ssg-body-cell', { timeout: 15000 })
  await sleep(800)
  await cell(page, 'P00003', 'price').click({ button: 'right' }); await sleep(400)
  console.log('main ctx items', (await page.locator('.ssg-menu-panel').allInnerTexts()).join('|').replace(/\s+/g, ' '))
  await page.screenshot({ path: __dirname + '/shots/t9-ctx.png' })
  await page.locator('.ssg-menu-panel .ssg-menu-item', { hasText: 'この行を複製' }).click(); await sleep(400)
  console.log('log', await page.locator('[data-testid=log]').innerText())
  const order = () => page.evaluate(() => [...document.querySelectorAll('.ssg-body-row[data-pane=left]')].sort((a, b) => +a.dataset.rowIndex - +b.dataset.rowIndex).slice(0, 6).map((r) => r.dataset.rowKey ?? 'LABEL').join(','))
  console.log('order', await order())
  await page.keyboard.press('Control+z'); await sleep(300)
  console.log('after undo order', await order())
  // Shift+F10
  await cell(page, 'P00002', 'name').click()
  await page.keyboard.press('Shift+F10'); await sleep(300)
  console.log('Shift+F10 menu', (await page.locator('.ssg-menu-panel').allInnerTexts()).join('|').replace(/\s+/g, ' '), 'focus', await page.evaluate(() => document.activeElement.className))
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter'); await sleep(300)
  console.log('after keyboard select log', (await page.locator('[data-testid=log]').innerText()).split('\n')[0], 'order', await order())
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('HUGE_FAN')).join('\n'))
  await browser.close()
})()

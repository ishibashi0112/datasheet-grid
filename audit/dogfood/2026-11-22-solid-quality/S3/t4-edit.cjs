const { open, sleep, cell, val, activeRef, drag, center } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open('http://127.0.0.1:5503/')
  await page.waitForSelector('.ssg-body-cell', { timeout: 15000 })
  await sleep(800)
  // custom: マウスで候補
  await cell(page, 'P00004', 'supplier').dblclick()
  await sleep(400)
  console.log('dblclick initial input =', await page.locator('[data-testid=supplier-editor] input').inputValue())
  const opt = page.locator('[data-testid=supplier-list] li').nth(3)
  const optText = (await opt.innerText()).replace(/\s+/g, ' ')
  await opt.click()
  await sleep(300)
  console.log('click option', optText, '-> P00004 =', await val(page, 'P00004', 'supplier'), 'editor', await page.locator('.ssg-cell-editor').count(), 'active', await activeRef(page), 'focus', await page.evaluate(() => document.activeElement.className))
  // Tab
  await cell(page, 'P00006', 'supplier').click()
  await page.keyboard.press('Enter')
  await sleep(400)
  console.log('Enter opens editor', await page.locator('.ssg-cell-editor').count(), 'input', await page.locator('[data-testid=supplier-editor] input').inputValue())
  await page.keyboard.type('東京')
  await sleep(100)
  await page.keyboard.press('Tab')
  await sleep(300)
  console.log('after Tab P00006 =', await val(page, 'P00006', 'supplier'), 'active', await activeRef(page))
  // Escape
  await cell(page, 'P00007', 'supplier').dblclick()
  await sleep(400)
  await page.keyboard.type('福岡')
  await page.keyboard.press('Escape')
  await sleep(300)
  console.log('after Esc P00007 =', await val(page, 'P00007', 'supplier'), 'editor', await page.locator('.ssg-cell-editor').count(), 'list', await page.locator('[data-testid=supplier-list]').count(), 'active', await activeRef(page))
  // ArrowDown で次のセルへ(エディタが閉じていればグリッドが動く)
  await page.keyboard.press('ArrowDown')
  console.log('ArrowDown -> active', await activeRef(page))
  // Undo / Redo
  await page.keyboard.press('Control+z')
  await sleep(200)
  console.log('undo -> P00006 =', await val(page, 'P00006', 'supplier'))
  await page.keyboard.press('Control+y')
  await sleep(200)
  console.log('redo -> P00006 =', await val(page, 'P00006', 'supplier'))

  // select エディタ(ブランド 240 件): ダブルクリック → タイプアヘッド → Enter
  await cell(page, 'P00003', 'brand').dblclick()
  await sleep(400)
  const popover = page.locator('.ssg-select-editor-popover')
  console.log('select popover', await popover.count(), 'options', await popover.locator('[role=option]').count())
  await page.screenshot({ path: __dirname + '/shots/t4-select.png' })
  await page.keyboard.type('ミナト')
  await sleep(200)
  await page.keyboard.press('Enter')
  await sleep(300)
  console.log('brand after typeahead =', await val(page, 'P00003', 'brand'))

  // 検査: 商品名を空にして確定 → reject
  await cell(page, 'P00008', 'name').dblclick()
  await sleep(200)
  await page.keyboard.press('Control+a')
  await page.keyboard.press('Delete')
  await page.keyboard.press('Enter')
  await sleep(300)
  console.log('reject: editor still open', await page.locator('.ssg-cell-editor').count(), 'bubble', await page.evaluate(() => document.body.innerText.includes('商品名は必須です')))
  await page.screenshot({ path: __dirname + '/shots/t4-reject.png' })
  await page.keyboard.press('Escape')
  await sleep(200)
  console.log('after esc name =', await val(page, 'P00008', 'name'))
  // Delete キーで空クリアもスキップ
  await cell(page, 'P00008', 'name').click()
  await page.keyboard.press('Delete')
  await sleep(200)
  console.log('Delete on reject column -> name =', await val(page, 'P00008', 'name'))
  // JAN: mark
  await cell(page, 'P00009', 'jan').dblclick()
  await page.keyboard.press('Control+a')
  await page.keyboard.type('12345')
  await page.keyboard.press('Enter')
  await sleep(300)
  const janCls = await cell(page, 'P00009', 'jan').getAttribute('class')
  console.log('JAN mark class:', janCls.includes('invalid'))
  // number min/integer
  await cell(page, 'P00010', 'stock').click()
  await page.keyboard.type('-3')
  await page.keyboard.press('Enter')
  await sleep(200)
  console.log('stock -3 class invalid:', (await cell(page, 'P00010', 'stock').getAttribute('class')).includes('invalid'), 'value', await val(page, 'P00010', 'stock'))
  await cell(page, 'P00010', 'stock').hover()
  await sleep(600)
  console.log('tooltip text', await page.evaluate(() => document.querySelector('.ssg-tooltip')?.textContent))
  await page.screenshot({ path: __dirname + '/shots/t4-mark.png' })
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('HUGE_FAN')).join('\n'))
  await browser.close()
})()

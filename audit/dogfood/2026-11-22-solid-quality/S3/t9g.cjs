const { open, sleep } = require('./lib.cjs')
;(async () => {
  const { browser, page } = await open('http://127.0.0.1:5503/?nomain=1')
  await page.waitForSelector('[data-testid=open-dialog]'); await sleep(800)
  await page.click('[data-testid=open-dialog]')
  await page.waitForSelector('[data-testid=dialog-grid] .ssg-body-cell', { timeout: 10000 }); await sleep(1000)
  await page.evaluate(() => {
    window.__ev = []
    for (const ev of ['pointerdown', 'pointerup', 'mouseup', 'click', 'contextmenu', 'auxclick'])
      window.addEventListener(ev, (e) => window.__ev.push(`${ev} btn=${e.button} target=${e.target.className?.toString().slice(0, 40)} xy=${e.clientX},${e.clientY}`), true)
    new MutationObserver(() => { const p = document.querySelector('.ssg-menu-panel'); if (p) { const r = p.getBoundingClientRect(); window.__ev.push(`panel at ${Math.round(r.x)},${Math.round(r.y)} ${Math.round(r.width)}x${Math.round(r.height)}`) } else window.__ev.push('panel gone') }).observe(document.querySelector('dialog'), { childList: true })
  })
  const c = page.locator(`[data-testid=dialog] .ssg-body-row[data-pane="center"][data-row-key="P00003"] [data-ssg-col-key="price"]`)
  const b = await c.boundingBox()
  await page.mouse.move(b.x + 20, b.y + 10)
  await page.mouse.down({ button: 'right' })
  await sleep(200)
  console.log('after down: panels', await page.locator('.ssg-menu-panel').count())
  await page.mouse.up({ button: 'right' })
  await sleep(300)
  console.log('after up: panels', await page.locator('.ssg-menu-panel').count())
  console.log((await page.evaluate(() => window.__ev)).join('\n'))
  await browser.close()
})()

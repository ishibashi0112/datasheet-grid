// 使い方: node perf-logs.cjs <ラベル> [url]  — ログ 100 万行の操作の時間とメモリ
const { chromium } = require('playwright')
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const label = process.argv[2]
const url = process.argv[3] ?? 'http://127.0.0.1:5505/'
;(async () => {
  const browser = await chromium.launch()
  const context = await browser.newContext({ viewport: { width: 1400, height: 900 }, deviceScaleFactor: 1 })
  const page = await context.newPage()
  const logs = []
  page.on('console', (m) => logs.push(`[${m.type()}] ${m.text()}`))
  page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`))
  const cdp = await context.newCDPSession(page)
  await cdp.send('Performance.enable')
  const heap = async () => { await cdp.send('HeapProfiler.collectGarbage'); const m = await cdp.send('Performance.getMetrics'); return (m.metrics.find((x) => x.name === 'JSHeapUsedSize').value / 1048576).toFixed(0) + 'MB' }
  const out = {}
  const t0 = Date.now()
  await page.goto(url)
  await page.waitForSelector('.ssg-body-cell', { timeout: 120000 })
  out.firstCell = Date.now() - t0
  out.gen = Math.round(await page.evaluate(() => window.__genMs))
  await sleep(1500)
  out.heapLoad = await heap()
  await page.evaluate(() => { window.__lt = []; new PerformanceObserver((l) => { for (const e of l.getEntries()) window.__lt.push(e.duration) }).observe({ type: 'longtask', buffered: false }) })
  const topBar = () => page.evaluate(() => document.querySelector('.ssg-bar--top')?.innerText.replace(/\s+/g, ' '))
  // 待つ: 条件が真になるまでの時間(ページの中で rAF で見る)
  const until = (fnSrc, timeout = 60000) => page.evaluate(async ([fnSrc, timeout]) => {
    const fn = new Function('return (' + fnSrc + ')()')
    const s = window.__t0 ?? performance.now()
    while (!fn()) { if (performance.now() - s > timeout) return -1; await new Promise((r) => requestAnimationFrame(r)) }
    return Math.round(performance.now() - s)
  }, [fnSrc, timeout])
  const mark = () => page.evaluate(() => { window.__t0 = performance.now() })

  // 1) Ctrl+F で検索(100 万行)
  await page.locator('.ssg-body-row[data-pane=center] .ssg-body-cell').first().click()
  await page.keyboard.press('Control+f'); await sleep(300)
  await mark()
  await page.keyboard.insertText('timeout')
  out.find = await until(`() => { const t = document.querySelector('.ssg-find-bar')?.innerText || ''; const m = t.match(/\\/\\s*([\\d,]+)/); window.__fc = t; return m && !/検索中|…/.test(t) && Number(m[1].replace(/,/g,'')) > 1000 }`)
  await sleep(1500)
  out.findText = (await page.evaluate(() => document.querySelector('.ssg-find-bar')?.innerText.replace(/\s+/g, ' ')))
  await mark(); await page.keyboard.press('Enter')
  out.findNext = await until(`() => document.querySelector('.ssg-find-mark--current') !== null`, 10000)
  await page.keyboard.press('Escape'); await sleep(300)

  // 2) グローバルフィルター
  const gf = page.locator('.ssg-bar--top input').first()
  await gf.click()
  await mark()
  await gf.pressSequentially('502', { delay: 50 })
  out.globalFilter = await until(`() => { const t = document.querySelector('.ssg-bar--top')?.innerText || ''; return /行 [\\d,]+ \\/ 1000000/.test(t.replace(/\\s+/g,' ')) && !/行 1000000 \\/ 1000000/.test(t.replace(/\\s+/g,' ')) && !document.querySelector('.ssg-loading-overlay, [class*=overlay][class*=filter]') }`)
  await sleep(1500)
  out.globalFilterBar = await topBar()
  await gf.fill(''); await sleep(2500)

  // 3) 列フィルター(レベル = ERROR)
  const hdr = page.locator('.ssg-header-cell', { hasText: 'レベル' })
  await hdr.hover(); await hdr.locator('.ssg-icon-btn').last().click(); await sleep(300)
  await page.locator('.ssg-menu-panel .ssg-menu-item', { hasText: 'フィルター…' }).first().click()
  await page.waitForSelector('.ssg-filter-popover input', { timeout: 10000 }); await sleep(300)
  await page.locator('.ssg-filter-popover input').first().fill('ERROR'); await sleep(300)
  await mark(); await page.keyboard.press('Enter')
  out.colFilter = await until(`() => /行 [\\d,]+ \\/ 1000000/.test((document.querySelector('.ssg-bar--top')?.innerText||'').replace(/\\s+/g,' ')) && !/行 1000000 \\//.test((document.querySelector('.ssg-bar--top')?.innerText||'').replace(/\\s+/g,' '))`)
  await sleep(800)
  out.colFilterBar = await topBar()
  out.detailToggles = await page.locator('[aria-expanded]').count()

  // 4) ソート(時刻 降順)— フィルター中
  const th = page.locator('.ssg-header-cell', { hasText: '時刻' })
  await th.hover(); await th.locator('.ssg-icon-btn').last().click(); await sleep(300)
  await mark(); await page.locator('.ssg-menu-panel .ssg-menu-item', { hasText: '降順' }).first().click()
  out.sortFiltered = await until(`() => /並び替え: (?!なし)/.test((document.querySelector('.ssg-bar--top')?.innerText||''))`)
  await sleep(800)
  // フィルターを外す(全件ソート)
  await page.evaluate(() => window.__logGrid.applyState({ filters: { columnFilters: {} } }))
  await mark()
  out.unfilterSorted = await until(`() => /行 1000000 \\/ 1000000/.test((document.querySelector('.ssg-bar--top')?.innerText||'').replace(/\\s+/g,' '))`)
  await sleep(800)
  out.heapAfterSort = await heap()
  // 5) 遠くへ(Ctrl+End → Ctrl+Home)
  await page.locator('.ssg-body-row[data-pane=center] .ssg-body-cell').first().click()
  await mark(); await page.keyboard.press('Control+End')
  out.ctrlEnd = await until(`() => (document.querySelector('.ssg-bar--bottom')?.innerText||'').includes('1000000')`, 20000)
  await sleep(500)
  out.bottomBar = await page.evaluate(() => document.querySelector('.ssg-bar--bottom')?.innerText.replace(/\s+/g, ' '))
  await mark(); await page.evaluate(() => window.__logGrid.scrollToRow(500000, { align: 'center' }))
  out.scrollToRow = await until(`() => [...document.querySelectorAll('.ssg-body-row[data-pane=left] .ssg-row-header-cell')].some((c) => c.textContent === '500001')`, 20000)
  // ホイールで 30 回スクロール(フレーム時間)
  const b = await page.locator('.ssg-scroll-container').boundingBox()
  await page.mouse.move(b.x + 400, b.y + 300)
  const fr = await page.evaluate(async () => { const ts = []; let last = performance.now(); let run = true; const loop = () => { const n = performance.now(); ts.push(n - last); last = n; if (run) requestAnimationFrame(loop) }; requestAnimationFrame(loop); window.__stopFr = () => { run = false; return ts }; })
  for (let i = 0; i < 30; i++) { await page.mouse.wheel(0, 400); await sleep(30) }
  const frames = await page.evaluate(() => window.__stopFr())
  frames.sort((a, b) => a - b)
  out.scrollFrames = `p50 ${frames[Math.floor(frames.length * 0.5)].toFixed(1)}ms p95 ${frames[Math.floor(frames.length * 0.95)].toFixed(1)}ms max ${frames[frames.length - 1].toFixed(1)}ms n=${frames.length}`
  out.heapEnd = await heap()
  const lt = await page.evaluate(() => window.__lt)
  out.longTasks = `${lt.length} 件, 最大 ${Math.round(Math.max(0, ...lt))}ms, 合計 ${Math.round(lt.reduce((a, b) => a + b, 0))}ms`
  await page.screenshot({ path: __dirname + `/shots/perf-${label}.png` })
  console.log(label, JSON.stringify(out, null, 1))
  const errs = logs.filter((l) => /error|warn/i.test(l) && !l.includes('[vite]'))
  if (errs.length) console.log(errs.join('\n'))
  await browser.close()
})()

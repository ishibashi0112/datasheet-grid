const { open, shot, wait, clickVisible, startJank, stopJank } = require('./lib.cjs')
;(async () => {
  const url = process.argv[2] ?? 'http://localhost:5407/'
  const tag = process.argv[3] ?? 'dev'
  const { browser, page, logs } = await open(url)
  await wait(800)
  const readClip = () => page.evaluate(() => navigator.clipboard.readText())
  // 1) 行番号を押して 1 行を選ぶ → Ctrl+C
  const rh = await page.evaluate(() => {
    const sc = document.querySelector('.ssg-scroll-container').getBoundingClientRect()
    const hdr = document.querySelector('[role=columnheader]').getBoundingClientRect()
    const cells = [...document.querySelectorAll('[role=rowheader]')].map((c) => ({ c, b: c.getBoundingClientRect() })).filter(({ b }) => b.top > hdr.bottom && b.bottom < sc.bottom).sort((a, b) => a.b.top - b.b.top)
    return cells.slice(0, 6).map(({ c, b }) => ({ no: c.textContent, x: b.left + b.width / 2, y: b.top + b.height / 2 }))
  })
  await page.mouse.click(rh[2].x, rh[2].y)
  await wait(200)
  console.log('row select', JSON.stringify(await page.evaluate(() => window.__grid.getSelection())))
  await page.keyboard.press('Control+c')
  await wait(200)
  console.log('copy 1 row:', JSON.stringify(await readClip()))
  // 2) Shift+行番号で 3 行
  await page.keyboard.down('Shift')
  await page.mouse.click(rh[4].x, rh[4].y)
  await page.keyboard.up('Shift')
  await page.keyboard.press('Control+c')
  await wait(200)
  const c3 = await readClip()
  console.log('copy 3 rows lines:', c3.split('\n').length, JSON.stringify(c3.slice(0, 200)))
  await shot(page, `copy-${tag}-rows`)
  // 3) 複数行のメッセージを含む行(ERROR の Unhandled exception)を探してコピー → 引用符
  await page.evaluate(() => window.__grid.applyState({ filters: { globalText: 'Unhandled exception' } }))
  await wait(6000)
  await clickVisible(page, 0, 'center', 2)
  await page.keyboard.press('Control+c')
  await wait(200)
  console.log('copy multiline cell:', JSON.stringify(await readClip()))
  await page.evaluate(() => window.__grid.applyState({ filters: { globalText: '' } }))
  await wait(1500)
  // 4) 右クリック → 行を JSON でコピー
  const info = await clickVisible(page, 1, 'center', 2, { button: 'right' })
  await wait(300)
  const items = await page.locator('.ssg-menu-panel .ssg-menu-item').allInnerTexts().catch(() => [])
  console.log('context menu items', items)
  await shot(page, `copy-${tag}-context`)
  await page.locator('.ssg-menu-panel .ssg-menu-item', { hasText: '行を JSON でコピー' }).click()
  await wait(200)
  console.log('json:', await readClip())
  // 5) Ctrl+A → Ctrl+C(100 万行)
  await clickVisible(page, 0, 'center', 1)
  await page.keyboard.press('Control+a')
  await wait(300)
  console.log('bar after Ctrl+A', (await page.locator('.ssg-bar--bottom').innerText()).replace(/\s+/g, ' '))
  await startJank(page)
  const t = Date.now()
  await page.keyboard.press('Control+c')
  let len = 0
  for (let i = 0; i < 120; i++) { len = await page.evaluate(() => navigator.clipboard.readText().then((s) => s.length)); if (len > 1000) break; await wait(250) }
  console.log('Ctrl+A Ctrl+C: clipboard length', len, 'ms', Date.now() - t, JSON.stringify(await stopJank(page)))
  const mem = await page.evaluate(() => performance.memory ? Math.round(performance.memory.usedJSHeapSize / 1e6) : null)
  console.log('heap MB', mem)
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('DevTools') && !l.includes('auto-height')).slice(0, 30).join('\n'))
  await browser.close()
})()

const { open, wait, waitCountChange, clickVisible } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open('http://localhost:5407/')
  await wait(800)
  await page.locator('.toolbar button', { hasText: 'ERROR 以上' }).click()
  await waitCountChange(page, 1000000)
  await wait(300)
  await clickVisible(page, 1, 'center', 2)
  await page.locator('[data-pane="left"].ssg-body-row [aria-expanded]').nth(1).click()
  await wait(300)
  await page.locator('.ssg-detail-card button', { hasText: 'JSON をコピー' }).first().focus()
  console.log('focus in card:', await page.evaluate(() => document.activeElement?.textContent))
  // ホイールで遠くへ
  const sc = await page.locator('.ssg-scroll-container').boundingBox()
  await page.mouse.move(sc.x + 700, sc.y + 300)
  for (let i = 0; i < 15; i++) { await page.mouse.wheel(0, 800); await wait(40) }
  await wait(500)
  console.log('after scroll: activeElement', await page.evaluate(() => `${document.activeElement?.tagName}.${document.activeElement?.className}`), 'cards', await page.locator('.ssg-detail-card').count())
  const before = await page.evaluate(() => window.__grid.getActiveCell())
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Control+c')
  await wait(200)
  console.log('ArrowDown/Ctrl+C after card unmounted: active', JSON.stringify(before), '→', JSON.stringify(await page.evaluate(() => window.__grid.getActiveCell())))
  await browser.close()
})()

const { open, shot, wait, rowCount } = require('./lib.cjs')
;(async () => {
  const { browser, page } = await open('http://localhost:5407/')
  await wait(1000)
  const input = page.locator('.ssg-bar--top input')
  await input.fill('u-31337')
  await page.waitForFunction(() => /行\s*137381/.test(document.querySelector('.ssg-bar--bottom').innerText), null, { timeout: 60000 })
  await input.fill('')
  await page.waitForFunction(() => /行\s*1000000/.test(document.querySelector('.ssg-bar--bottom').innerText), null, { timeout: 60000 })
  await wait(500)
  await input.fill('Unhandled exception')
  await wait(500)
  await shot(page, 'global-stale')
  console.log(await rowCount(page))
  await browser.close()
})()

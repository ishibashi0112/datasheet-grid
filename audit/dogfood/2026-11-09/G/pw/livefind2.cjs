const { open, wait, clickVisible } = require('./lib.cjs')
;(async () => {
  const { browser, page } = await open((process.argv[2] ?? 'http://localhost:5407/') + '?live=1')
  await wait(1500)
  await page.locator('.toolbar input[type=checkbox]').nth(1).uncheck()
  await clickVisible(page, 2, 'center', 1)
  await page.keyboard.press('Control+f')
  await page.locator('.ssg-find-bar input').fill('d73eb438a907d090') // 1 件だけ(先頭付近の行の traceId)
  await wait(3000)
  const a = await page.evaluate(() => window.__grid.getActiveCell())
  await page.keyboard.press('Enter')
  await wait(500)
  const b = await page.evaluate(() => window.__grid.getActiveCell())
  console.log('bar', (await page.locator('.ssg-find-bar').innerText()).replace(/\s+/g, ' '), 'active before Enter', JSON.stringify(a), 'after', JSON.stringify(b), 'marks', await page.locator('.ssg-find-mark').count())
  await page.locator('.toolbar input[type=checkbox]').nth(0).uncheck()
  const t = Date.now()
  await page.waitForFunction(() => !document.querySelector('.ssg-find-bar').innerText.includes('検索中'), null, { timeout: 60000 })
  console.log('after stopping live: scan finished in', Date.now() - t, 'ms; bar', (await page.locator('.ssg-find-bar').innerText()).replace(/\s+/g, ' '))
  await browser.close()
})()

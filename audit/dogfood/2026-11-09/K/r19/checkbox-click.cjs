// チェックボックス列: セルの端(チェックボックスの外)を押したとき / Space / チェックボックスを押したときに切り替わるか
const { chromium } = require('playwright')
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1400, height: 800 }, deviceScaleFactor: 1 })
  await page.goto('http://localhost:5411/', { waitUntil: 'networkidle' })
  await page.waitForSelector('[data-pane="center"].ssg-body-row')
  const cell = page.locator('.ssg-body-row[data-row-index="0"] [data-ssg-col-key="discontinued"]').first()
  const box = cell.getByRole('checkbox')
  const state = () => box.getAttribute('aria-checked')
  const r = await cell.boundingBox()
  const cb = await box.boundingBox()
  const res = { cell: r, checkbox: cb, before: await state() }
  await page.mouse.click(r.x + 4, r.y + r.height / 2)
  await page.waitForTimeout(150)
  res.afterEdgeClick = await state()
  res.active = await page.evaluate(() => document.querySelector('.ssg-shell')?.getAttribute('aria-activedescendant'))
  await page.keyboard.press('Space')
  await page.waitForTimeout(150)
  res.afterSpace = await state()
  await box.click()
  await page.waitForTimeout(150)
  res.afterBoxClick = await state()
  await page.mouse.dblclick(r.x + 4, r.y + r.height / 2)
  await page.waitForTimeout(150)
  res.afterEdgeDblClick = await state()
  console.log(JSON.stringify(res))
  await browser.close()
})()

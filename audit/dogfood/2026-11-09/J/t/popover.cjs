const { open, shot } = require('./lib.cjs')
const popOpen = (page) => page.evaluate(() => !!document.querySelector('[data-testid=quick-popover]'))
const cell = (page, r, c) => page.evaluate(([r, c]) => { const e = document.querySelector(`[data-testid=quick-popover] [role=row][aria-rowindex="${r + 2}"] [role=gridcell][aria-colindex="${c + 2}"]`); const b = e.getBoundingClientRect(); return { x: b.x + b.width / 2, y: b.y + b.height / 2, text: e.textContent } }, [r, c])
async function reopen(page) { if (!(await popOpen(page))) { await page.click('[data-testid=quick-trigger]'); await page.locator('[data-testid=quick-popover] .ssg-root').waitFor(); await page.waitForTimeout(300) } }
;(async () => {
  const { browser, page, logs } = await open()
  await reopen(page)
  await shot(page, 'popover-grid')
  // select エディタの候補をクリック
  const c = await cell(page, 0, 1)
  await page.mouse.dblclick(c.x, c.y)
  await page.waitForTimeout(300)
  const ob = await page.locator('[role=option]', { hasText: '福岡' }).first().boundingBox()
  await page.mouse.click(ob.x + 10, ob.y + 5)
  await page.waitForTimeout(300)
  console.log('select click: popover', await popOpen(page), 'value', (await popOpen(page)) ? (await cell(page, 0, 1)).text : '-')
  await reopen(page)
  // 列メニュー
  const mb = await page.locator('[data-testid=quick-popover] [aria-label="倉庫 の列メニュー"]').boundingBox()
  await page.mouse.move(mb.x + 2, mb.y + 2); await page.mouse.click(mb.x + mb.width / 2, mb.y + mb.height / 2)
  await page.waitForTimeout(300)
  const it = await page.locator('.ssg-menu-item', { hasText: '降順で並び替え' }).first().boundingBox()
  await page.mouse.click(it.x + 20, it.y + it.height / 2)
  await page.waitForTimeout(300)
  console.log('menu sort click: popover', await popOpen(page))
  await reopen(page)
  // 右クリックメニュー
  const c2 = await cell(page, 1, 0)
  await page.mouse.click(c2.x, c2.y, { button: 'right' })
  await page.waitForTimeout(300)
  const it2 = await page.locator('.ssg-menu-item', { hasText: '発注する' }).first().boundingBox()
  await page.mouse.click(it2.x + 20, it2.y + it2.height / 2)
  await page.waitForTimeout(300)
  console.log('ctx click: popover', await popOpen(page), 'logged', logs.some((l) => l.includes('発注')))
  await reopen(page)
  // 編集中 Esc
  const c3 = await cell(page, 2, 2)
  await page.mouse.click(c3.x, c3.y)
  await page.keyboard.type('5')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  console.log('edit Esc: popover', await popOpen(page))
  await browser.close()
})()

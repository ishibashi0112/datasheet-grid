const { open, shot } = require('./lib.cjs')
const { cellPos } = require('./dlib.cjs')
const ORD = '[data-testid=orders-wrap]'
;(async () => {
  const { browser, page, logs } = await open()
  await page.locator('[data-testid=split-section]').scrollIntoViewIfNeeded()
  await page.waitForTimeout(300)
  const y0 = await page.evaluate(() => scrollY)
  const a = await cellPos(page, 1, '顧客', ORD)
  const sc = await page.locator(`${ORD} .ssg-scroll-container`).boundingBox()
  await page.mouse.move(a.x, a.y); await page.mouse.down()
  await page.mouse.move(a.x, sc.y + sc.height + 30, { steps: 5 })
  await page.waitForTimeout(800)
  await page.mouse.up()
  const r = await page.evaluate(() => ({ y: scrollY, gridTop: document.querySelector('[data-testid=orders-wrap] .ssg-scroll-container').scrollTop, bar: document.querySelector('[data-testid=orders-wrap] .ssg-bar--bottom').textContent.match(/範囲\s*\S+/)?.[0] }))
  console.log('drag below grid: page', y0, '→', r.y, 'grid scrollTop', r.gridTop, r.bar)
  // cross hover after panel resize
  const h = await page.locator('[data-testid=split-handle]').boundingBox()
  await page.mouse.move(h.x + 4, h.y + 100); await page.mouse.down(); await page.mouse.move(h.x - 180, h.y + 100, { steps: 10 }); await page.mouse.up()
  await page.waitForTimeout(300)
  const c = await cellPos(page, 3, '担当', ORD)
  await page.mouse.move(c.x, c.y)
  await page.waitForTimeout(300)
  const ov = await page.evaluate(() => { const o = document.querySelector('[data-testid=orders-wrap] .ssg-col-hover-overlay'); const h = [...document.querySelectorAll('[data-testid=orders-wrap] [role=columnheader]')].find((x) => x.textContent.includes('担当')); if (!o) return 'no overlay'; const a = o.getBoundingClientRect(), b = h.getBoundingClientRect(); return { ov: [a.left, a.width].map(Math.round), head: [b.left, b.width].map(Math.round) } })
  console.log('cross hover overlay vs header', JSON.stringify(ov))
  await shot(page, 'cross-hover')
  await browser.close()
})()

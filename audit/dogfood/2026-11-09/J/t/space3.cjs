const { open } = require('./lib.cjs')
;(async () => {
  const { browser, page } = await open()
  const top = await page.evaluate(() => document.querySelector('[data-testid=orders-wrap]').getBoundingClientRect().top + window.scrollY)
  await page.evaluate((y) => window.scrollTo(0, y), top - 700)
  await page.waitForTimeout(300)
  const cell = await page.evaluate(() => { const r = document.querySelector('[data-testid=orders-wrap] [role=row][aria-rowindex="3"]'); const b = r.getBoundingClientRect(); return { x: b.x + 200, y: b.y + 18 } })
  await page.mouse.click(cell.x, cell.y)
  await page.waitForTimeout(200)
  const info = async () => page.evaluate(() => { const a = document.querySelector('[data-testid=orders-wrap] .ssg-shell'); const id = a.getAttribute('aria-activedescendant'); const c = id && document.getElementById(id); return { y: Math.round(scrollY), activeCellText: c?.textContent, colindex: c?.getAttribute('aria-colindex'), editing: !!document.querySelector('.ssg-cell-editor'), activeEl: document.activeElement.className } })
  console.log('clicked', JSON.stringify(await info()))
  for (let i = 0; i < 6; i++) await page.keyboard.press('ArrowDown')
  await page.waitForTimeout(200)
  console.log('6 down', JSON.stringify(await info()))
  await page.keyboard.press('PageDown')
  await page.waitForTimeout(300)
  console.log('PageDown', JSON.stringify(await info()))
  await page.keyboard.press('Space')
  await page.waitForTimeout(300)
  console.log('Space', JSON.stringify(await info()))
  await browser.close()
})()

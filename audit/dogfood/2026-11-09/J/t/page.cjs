const { open, shot } = require('./lib.cjs')
const sy = (page) => page.evaluate(() => Math.round(window.scrollY))
const gst = (page, label) => page.evaluate((label) => { const sc = document.querySelector(`[aria-label="${label}"].ssg-scroll-container`); return sc.scrollTop }, label)
;(async () => {
  const { browser, page, logs } = await open()
  // 受注一覧の上端を画面の下の方(y=700)に置く
  const top = await page.evaluate(() => document.querySelector('[data-testid=orders-wrap]').getBoundingClientRect().top + window.scrollY)
  await page.evaluate((y) => window.scrollTo(0, y), top - 700)
  await page.waitForTimeout(300)
  const s0 = await sy(page)
  console.log('page scrollY', s0)
  // 見えているセルをクリック(上端から 4 行目くらい)
  const cell = await page.evaluate(() => { const r = document.querySelector('[data-testid=orders-wrap] [role=row][aria-rowindex="3"]'); const b = r.getBoundingClientRect(); return { x: b.x + 200, y: b.y + 18, vis: b.y < innerHeight } })
  console.log('cell', JSON.stringify(cell))
  await page.mouse.click(cell.x, cell.y)
  await page.waitForTimeout(300)
  console.log('after click scrollY', await sy(page), '(before', s0, ')')
  // ArrowDown を何回か(画面の外の行へ)
  for (let i = 0; i < 6; i++) await page.keyboard.press('ArrowDown')
  await page.waitForTimeout(300)
  const act = await page.evaluate(() => { const a = document.querySelector('[data-testid=orders-wrap] [aria-selected=true][role=gridcell]'); const b = a?.getBoundingClientRect(); return b && { top: Math.round(b.top), bottom: Math.round(b.bottom), inWindow: b.bottom <= innerHeight } })
  console.log('after 6x ArrowDown scrollY', await sy(page), 'grid scrollTop', await gst(page, '受注一覧'), 'active cell', JSON.stringify(act))
  await shot(page, 'page-after-arrows')
  // PageDown
  const s1 = await sy(page)
  await page.keyboard.press('PageDown')
  await page.waitForTimeout(300)
  console.log('PageDown: scrollY', s1, '→', await sy(page), 'grid', await gst(page, '受注一覧'))
  // Space(チェックボックス列以外)
  const s2 = await sy(page)
  await page.keyboard.press('Space')
  await page.waitForTimeout(300)
  console.log('Space: scrollY', s2, '→', await sy(page))
  await page.keyboard.press('Escape')
  // Ctrl+End
  const s3 = await sy(page)
  await page.keyboard.press('Control+End')
  await page.waitForTimeout(300)
  console.log('Ctrl+End: scrollY', s3, '→', await sy(page), 'grid', await gst(page, '受注一覧'))
  await page.keyboard.press('Control+Home')
  await page.waitForTimeout(300)
  console.log('Ctrl+Home: scrollY →', await sy(page), 'grid', await gst(page, '受注一覧'))
  // ホイール: グリッドの上でホイール → グリッドが先に動き、端で page へ
  const wb = await page.locator('[data-testid=orders-wrap] .ssg-scroll-container').boundingBox()
  const s4 = await sy(page)
  await page.mouse.move(wb.x + 200, Math.min(wb.y + 100, 880))
  await page.mouse.wheel(0, 300)
  await page.waitForTimeout(300)
  console.log('wheel over grid: page', s4, '→', await sy(page), 'grid', await gst(page, '受注一覧'))
  // 列メニューを開いてページをスクロール
  await page.evaluate(() => window.scrollTo(0, document.querySelector('[data-testid=orders-wrap]').getBoundingClientRect().top + window.scrollY - 200))
  await page.waitForTimeout(300)
  const mb = await page.locator('[data-testid=orders-wrap] [aria-label="担当 の列メニュー"]').boundingBox()
  await page.mouse.move(mb.x + 2, mb.y + 2)
  await page.mouse.click(mb.x + mb.width / 2, mb.y + mb.height / 2)
  await page.waitForTimeout(300)
  const m1 = await page.evaluate(() => { const m = document.querySelector('.ssg-menu-panel'); return m && Math.round(m.getBoundingClientRect().top) })
  await page.mouse.move(1300, 100)
  await page.mouse.wheel(0, 120)
  await page.waitForTimeout(400)
  const mb2 = await page.locator('[data-testid=orders-wrap] [aria-label="担当 の列メニュー"]').boundingBox()
  const m2 = await page.evaluate(() => { const m = document.querySelector('.ssg-menu-panel'); return m && Math.round(m.getBoundingClientRect().top) })
  console.log('menu top', m1, 'btn bottom', Math.round(mb.y + mb.height), '→ after page wheel: menu', m2, 'btn bottom', Math.round(mb2.y + mb2.height))
  await shot(page, 'page-menu-after-scroll')
  const l = logs.filter((x) => !x.includes('React DevTools'))
  if (l.length) console.log('logs:', l.join('\n'))
  await browser.close()
})()

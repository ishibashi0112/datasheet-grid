const { open, shot } = require('./lib.cjs')
const { cellPos } = require('./dlib.cjs')
;(async () => {
  const { browser, page, logs } = await open('?dlg=w2')
  await page.click('[data-testid=dark-toggle]')
  await page.waitForTimeout(400)
  await shot(page, 'dark-top')
  // 売上の列メニュー(ダーク)
  const mb = await page.locator('[aria-label="状態 の列メニュー"]').first().boundingBox()
  await page.mouse.move(mb.x + 2, mb.y + 2)
  await page.mouse.click(mb.x + mb.width / 2, mb.y + mb.height / 2)
  await page.waitForTimeout(300)
  await shot(page, 'dark-menu')
  await page.keyboard.press('Escape')
  // Dialog(ダーク)+ 列フィルター
  await page.click('[data-testid=dialog-open]')
  await page.locator('[data-testid=dialog] .ssg-root').waitFor()
  await page.waitForTimeout(300)
  const hb = await page.locator('[data-testid=dialog] [aria-label="地域 の列メニュー"]').boundingBox()
  await page.mouse.move(hb.x + 2, hb.y + 2)
  await page.mouse.click(hb.x + hb.width / 2, hb.y + hb.height / 2)
  await page.waitForTimeout(300)
  const it = await page.locator('.ssg-menu-item', { hasText: 'フィルター…' }).first().boundingBox()
  await page.mouse.click(it.x + 20, it.y + it.height / 2)
  await page.waitForTimeout(500)
  await shot(page, 'dark-dialog-filter')
  // ライトへ戻す(フィルターを開いたまま)
  await page.evaluate(() => document.documentElement.classList.remove('dark'))
  await page.waitForTimeout(300)
  await shot(page, 'dark-to-light-filter-open')
  console.log(logs.filter((x) => !x.includes('DevTools')).join('\n'))
  await browser.close()
})()

const { open, shot } = require('./lib.cjs')
const { cellPos, cellText } = require('./dlib.cjs')
const SALES = '[data-testid=sales-wrap]', ORD = '[data-testid=orders-wrap]'
;(async () => {
  const { browser, page, logs } = await open()
  let p = await cellPos(page, 2, '備考', SALES)
  await page.mouse.click(p.x, p.y)
  await page.keyboard.type('test')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  console.log('sales 備考[2]', await cellText(page, 2, '備考', SALES))
  await page.locator(ORD).scrollIntoViewIfNeeded()
  p = await cellPos(page, 1, '顧客', ORD)
  await page.mouse.click(p.x, p.y)
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(200)
  console.log('Ctrl+Z in orders → sales 備考[2]', await cellText(page, 2, '備考', SALES), 'orders 顧客[1]', await cellText(page, 1, '顧客', ORD))
  await page.keyboard.press('Control+c')
  await page.waitForTimeout(200)
  console.log('Ctrl+C in orders clip', JSON.stringify(await page.evaluate(() => navigator.clipboard.readText())))
  await page.keyboard.press('Control+f')
  await page.waitForTimeout(300)
  console.log('Ctrl+F in orders: find bars', await page.evaluate(() => document.querySelectorAll('.ssg-find-bar').length))
  await page.locator(SALES).scrollIntoViewIfNeeded()
  p = await cellPos(page, 2, '備考', SALES)
  await page.mouse.click(p.x, p.y)
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(200)
  console.log('Ctrl+Z in sales → 備考[2]', JSON.stringify(await cellText(page, 2, '備考', SALES)))
  await page.keyboard.press('Control+f')
  await page.waitForTimeout(300)
  console.log('Ctrl+F in sales: find bars', await page.evaluate(() => [...document.querySelectorAll('.ssg-find-bar')].map((b) => b.closest('[data-testid]')?.getAttribute('data-testid'))))
  await page.keyboard.type('東邦')
  await page.waitForTimeout(500)
  await page.keyboard.press('Enter')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(400)
  const fb = await page.evaluate(() => document.querySelector('.ssg-find-bar')?.textContent)
  console.log('find bar', fb, 'marks', await page.evaluate(() => document.querySelectorAll('mark.ssg-find-mark').length))
  await shot(page, 'multi-find', { clip: { x: 0, y: 150, width: 1440, height: 560 } })
  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)
  console.log('after Esc find bars', await page.evaluate(() => document.querySelectorAll('.ssg-find-bar').length), 'active', await page.evaluate(() => document.activeElement.className))
  // 範囲選択 → 集計
  await page.keyboard.press('Control+Home')
  await page.waitForTimeout(300)
  p = await cellPos(page, 0, '数量', SALES)
  const q = await cellPos(page, 4, '単価', SALES)
  await page.mouse.move(p.x, p.y); await page.mouse.down(); await page.mouse.move(q.x, q.y, { steps: 8 }); await page.mouse.up()
  await page.waitForTimeout(400)
  console.log('aggregates', await page.evaluate(() => document.querySelector('[data-testid=sales-wrap] .ssg-bar--bottom')?.textContent))
  const l = logs.filter((x) => !x.includes('React DevTools'))
  if (l.length) console.log('logs:', l.join('\n'))
  await browser.close()
})()

const { open } = require('./lib.cjs')
;(async () => {
  const { browser, page } = await open()
  const top = await page.evaluate(() => document.querySelector('[data-testid=orders-wrap]').getBoundingClientRect().top + window.scrollY)
  await page.evaluate((y) => window.scrollTo(0, y), top - 700)
  await page.waitForTimeout(300)
  const cell = await page.evaluate(() => { const r = document.querySelector('[data-testid=orders-wrap] [role=row][aria-rowindex="3"]'); const b = r.getBoundingClientRect(); return { x: b.x + 200, y: b.y + 18 } })
  await page.mouse.click(cell.x, cell.y)
  await page.waitForTimeout(300)
  console.log(await page.evaluate(() => [...document.querySelectorAll('.ssg-scroll-container')].map((e) => e.getAttribute('aria-label') + '|' + e.className)))
  for (let i = 0; i < 6; i++) await page.keyboard.press('ArrowDown')
  await page.waitForTimeout(300)
  console.log(await page.evaluate(() => [...document.querySelectorAll('.ssg-scroll-container')].map((e) => e.getAttribute('aria-label') + '|' + e.className)), await page.evaluate(() => document.activeElement.outerHTML.slice(0, 150)))
  await browser.close()
})()

const { open, shot } = require('./lib.cjs')
const S = '[data-testid=scale-section]'
const rect = (page, sel) => page.evaluate((sel) => { const e = document.querySelector(sel); if (!e) return null; const r = e.getBoundingClientRect(); return { x: +r.x.toFixed(1), y: +r.y.toFixed(1), w: +r.width.toFixed(1), h: +r.height.toFixed(1) } }, sel)
async function cellRect(page, rowIdx, colTitle) {
  return page.evaluate(({ rowIdx, colTitle }) => {
    const root = document.querySelector('[data-testid=scale-section] .ssg-root')
    const h = [...root.querySelectorAll('[role=columnheader]')].find((x) => x.textContent.replace('⋮', '').trim() === colTitle)
    const ci = h.getAttribute('aria-colindex')
    const c = root.querySelector(`[role=row][aria-rowindex="${rowIdx + 2}"] [role=gridcell][aria-colindex="${ci}"]`)
    const r = c.getBoundingClientRect()
    return { x: r.x, y: r.y, w: r.width, h: r.height, cx: r.x + r.width / 2, cy: r.y + r.height / 2, text: c.textContent, hx: h.getBoundingClientRect().right, hy: h.getBoundingClientRect().y + h.getBoundingClientRect().height / 2, hw: h.getBoundingClientRect().width }
  }, { rowIdx, colTitle })
}
const status = (page) => page.evaluate(() => document.querySelector('[data-testid=scale-section] .ssg-root').querySelector('[class*=status], .ssg-bottom-bar, [class*=bottom]')?.textContent)
;(async () => {
  const scale = process.argv[2] || '0.8'
  const { browser, page, logs } = await open('?scale=' + scale)
  await page.locator(S).scrollIntoViewIfNeeded()
  await page.waitForTimeout(400)
  // 1) クリック
  const c = await cellRect(page, 2, '実績')
  await page.mouse.click(c.cx, c.cy)
  await page.waitForTimeout(200)
  const act = await rect(page, `${S} .ssg-active-cell-overlay, ${S} [class*=active-cell]`)
  console.log('click cell', JSON.stringify({ cell: [c.x, c.y, c.w, c.h].map((v) => +v.toFixed(1)), overlay: act }), 'status', await status(page))
  // 2) ドラッグ範囲選択 実績(2) → 件数(5)
  const d = await cellRect(page, 5, '件数')
  await page.mouse.move(c.cx, c.cy)
  await page.mouse.down()
  for (let i = 1; i <= 10; i++) await page.mouse.move(c.cx + (d.cx - c.cx) * i / 10, c.cy + (d.cy - c.cy) * i / 10)
  await page.mouse.up()
  await page.waitForTimeout(200)
  console.log('drag select status', await status(page), 'sel overlay', JSON.stringify(await rect(page, `${S} .ssg-selection-overlay, ${S} [class*=selection-overlay]`)))
  await shot(page, `scale-${scale}-select`, { clip: { x: 0, y: 0, width: 1440, height: 900 } })
  // 3) 列幅のドラッグ(目標 列の右端を +100px)
  const t = await cellRect(page, 0, '目標')
  const w0 = t.hw
  await page.mouse.move(t.hx - 2, t.hy)
  await page.waitForTimeout(100)
  await page.mouse.down()
  for (let i = 1; i <= 10; i++) { await page.mouse.move(t.hx - 2 + i * 10, t.hy); await page.waitForTimeout(16) }
  await page.waitForTimeout(100)
  const tMid = await cellRect(page, 0, '目標')
  await page.mouse.up()
  await page.waitForTimeout(200)
  const t2 = await cellRect(page, 0, '目標')
  console.log('resize: header screen width', w0.toFixed(1), '→ during', tMid.hw.toFixed(1), '→ after', t2.hw.toFixed(1), '(pointer moved +100 screen px; edge at', (t.hx + 98).toFixed(1), 'vs right', t2.hx.toFixed(1), ')')
  // 4) 編集のオーバーレイ位置
  const e = await cellRect(page, 3, '件数')
  await page.mouse.dblclick(e.cx, e.cy)
  await page.waitForTimeout(300)
  console.log('editor', JSON.stringify({ cell: [e.x, e.y, e.w, e.h].map((v) => +v.toFixed(1)), editor: await rect(page, `${S} .ssg-cell-editor`) }))
  await page.keyboard.press('Escape')
  // 5) 列メニューの位置
  const mb = await page.locator(`${S} [aria-label="実績 の列メニュー"]`).boundingBox()
  await page.mouse.move(mb.x + 2, mb.y + 2)
  await page.mouse.click(mb.x + mb.width / 2, mb.y + mb.height / 2)
  await page.waitForTimeout(300)
  console.log('menu btn', JSON.stringify(mb), 'menu', JSON.stringify(await rect(page, '.ssg-menu-panel')))
  await shot(page, `scale-${scale}-menu`)
  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)
  // 6) フィルハンドル(実績 0 行目を選んで 2 行下へ)
  const f = await cellRect(page, 0, '件数')
  await page.mouse.click(f.cx, f.cy)
  await page.waitForTimeout(200)
  const fh = await rect(page, `${S} .ssg-fill-handle, ${S} [class*=fill-handle]`)
  console.log('fill handle', JSON.stringify(fh), 'cell br', (f.x + f.w).toFixed(1), (f.y + f.h).toFixed(1))
  // 7) ホイールでスクロール
  await page.mouse.move(c.cx, c.cy)
  await page.mouse.wheel(0, 200)
  await page.waitForTimeout(300)
  console.log('scrollTop', await page.evaluate(() => document.querySelector('[data-testid=scale-section] .ssg-scroll-container').scrollTop))
  const l = logs.filter((x) => !x.includes('React DevTools'))
  if (l.length) console.log('logs:', l.join('\n'))
  await browser.close()
})()

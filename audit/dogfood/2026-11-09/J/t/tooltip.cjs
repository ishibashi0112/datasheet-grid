const { open, shot } = require('./lib.cjs')
const { openDialog } = require('./dlib.cjs')
;(async () => {
  const { browser, page, logs } = await open('?dark=1')
  await openDialog(page)
  const mb = await page.locator('[data-testid=dialog] [aria-label="地域 の列メニュー"]').boundingBox()
  await page.mouse.move(mb.x + 4, mb.y + 4)
  await page.mouse.move(mb.x + 8, mb.y + 8, { steps: 3 })
  await page.waitForTimeout(1200)
  const t = await page.evaluate(() => { const t = document.querySelector('.ssg-tooltip'); if (!t) return null; const r = t.getBoundingClientRect(); const cs = getComputedStyle(t); const hit = document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2); return { text: t.textContent, vis: cs.visibility, op: cs.opacity, z: cs.zIndex, bg: cs.backgroundColor, onTop: t.contains(hit) || hit === t, r: [r.x, r.y, r.width, r.height].map(Math.round), cls: t.className } })
  console.log(JSON.stringify(t))
  await shot(page, 'tooltip-dialog-dark', { clip: { x: mb.x - 200, y: mb.y - 60, width: 400, height: 140 } })
  await browser.close()
})()

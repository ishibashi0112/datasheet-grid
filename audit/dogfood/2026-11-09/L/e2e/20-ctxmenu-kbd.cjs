const { launch, shot, iphone, cdpTap, BASE } = require('./lib.cjs')
const { cellCenter, state } = require('./helpers.cjs')
const menuOpen = (page) => page.evaluate(() => [...document.querySelectorAll('.ssg-menu-panel')].map((p) => ({ role: p.getAttribute('role'), items: [...p.querySelectorAll('.ssg-menu-item')].map((i) => i.textContent).join('/') })))
;(async () => {
  const { browser, page, logs } = await launch({ viewport: { width: 1280, height: 800 }, locale: 'ja-JP' })
  await page.goto(BASE); await page.waitForSelector('.ssg-body-row'); await page.waitForTimeout(800)
  const c = await cellCenter(page, 4, 'item'); await page.mouse.click(c.x, c.y); await page.waitForTimeout(200)
  for (const k of ['Shift+F10', 'ContextMenu']) {
    await page.keyboard.press(k); await page.waitForTimeout(400)
    console.log(k, 'menu:', await menuOpen(page), 'focus', await page.evaluate(() => document.activeElement.className))
    await page.keyboard.press('Escape'); await page.waitForTimeout(200)
  }
  // マウスの右クリック
  await page.mouse.click(c.x, c.y, { button: 'right' }); await page.waitForTimeout(400)
  console.log('right click menu:', await menuOpen(page), 'focus', await page.evaluate(() => document.activeElement.className + ' ' + document.activeElement.textContent.slice(0, 20)))
  await page.keyboard.press('ArrowDown'); await page.waitForTimeout(100)
  console.log('↓ focus', await page.evaluate(() => document.activeElement.className + ' ' + document.activeElement.textContent.slice(0, 20)))
  await page.keyboard.press('Escape'); await page.waitForTimeout(200)
  console.log('after Esc', await page.evaluate(() => document.activeElement.className))
  // 列の固定(onColumnsChange あり)を キーボードで
  await page.keyboard.press('Alt+ArrowDown'); await page.waitForTimeout(400)
  for (let i = 0; i < 5; i++) await page.keyboard.press('ArrowDown')
  console.log('focused', await page.evaluate(() => document.activeElement.textContent))
  await page.keyboard.press('ArrowRight'); await page.waitForTimeout(300)
  console.log('ArrowRight on 列の固定: submenu?', await page.evaluate(() => ({ focus: document.activeElement.textContent, panels: document.querySelectorAll('.ssg-menu-panel, .ssg-menu-submenu').length, sub: [...document.querySelectorAll('[class*=submenu] .ssg-menu-item')].map((e) => e.textContent).join('/') })))
  await page.keyboard.press('Enter'); await page.waitForTimeout(300)
  console.log('Enter on 列の固定: ', await page.evaluate(() => ({ focus: document.activeElement.textContent, sub: [...document.querySelectorAll('[class*=submenu] .ssg-menu-item, [class*=submenu] button')].map((e) => e.textContent).join('/') })))
  await shot(page, '20-pin-submenu-kbd')
  await page.keyboard.press('Escape'); await page.waitForTimeout(200); await page.keyboard.press('Escape')
  // タッチで 列の固定
  const m = await launch({ ...iphone(), locale: 'ja-JP' })
  const cdp = await m.context.newCDPSession(m.page)
  await m.page.goto(BASE); await m.page.waitForSelector('.ssg-body-row'); await m.page.waitForTimeout(800)
  const k = await m.page.evaluate(() => { const h = [...document.querySelectorAll('[role=columnheader]')].find((e) => e.textContent.includes('項目')); const r = h.querySelector('button').getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } })
  await cdpTap(m.page, cdp, k.x, k.y); await m.page.waitForTimeout(500)
  const pin = await m.page.evaluate(() => { const e = [...document.querySelectorAll('.ssg-menu-item')].find((x) => x.textContent.includes('列の固定')); const r = e.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } })
  await cdpTap(m.page, cdp, pin.x, pin.y); await m.page.waitForTimeout(500)
  const sub = await m.page.evaluate(() => [...document.querySelectorAll('.ssg-menu-item')].map((e) => { const r = e.getBoundingClientRect(); return { t: e.textContent, x: r.x + r.width / 2, y: r.y + r.height / 2, vis: r.right <= innerWidth && r.left >= 0 } }))
  console.log('touch after tapping 列の固定', sub.map((s) => `${s.t}@${Math.round(s.x)},${Math.round(s.y)} vis=${s.vis}`).join(' | '))
  console.log(await shot(m.page, '20-pin-submenu-touch'))
  const right = sub.find((s) => s.t.includes('右'))
  if (right) { await cdpTap(m.page, cdp, right.x, right.y); await m.page.waitForTimeout(500) }
  console.log('pinned?', await m.page.evaluate(() => [...document.querySelectorAll('.ssg-body-row[aria-rowindex="2"]')].map((r) => r.getAttribute('data-pane') + ':' + [...r.querySelectorAll('[data-ssg-col-key]')].map((c) => c.getAttribute('data-ssg-col-key')).join(',')).join(' | ')))
  console.log(await shot(m.page, '20-pinned-right-touch'))
  console.log('LOGS\n' + logs.join('\n') + m.logs.join('\n'))
  await m.browser.close(); await browser.close()
})()

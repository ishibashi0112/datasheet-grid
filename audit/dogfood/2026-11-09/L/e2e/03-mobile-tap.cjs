const { launch, shot, iphone, cdpTap, BASE } = require('./lib.cjs')
const { cellCenter, state, revealColumn } = require('./helpers.cjs')
const cellText = (page, vr, key) => page.evaluate(({ vr, key }) => { for (const r of document.querySelectorAll(`.ssg-body-row[aria-rowindex="${vr + 2}"]`)) { const c = r.querySelector(`[data-ssg-col-key="${key}"]`); if (c) return c.textContent } return null }, { vr, key })
async function dbl(page, cdp, c, gap = 120) { await cdpTap(page, cdp, c.x, c.y); await page.waitForTimeout(gap); await cdpTap(page, cdp, c.x, c.y); await page.waitForTimeout(500) }
;(async () => {
  const { browser, context, page, logs } = await launch(iphone())
  const cdp = await context.newCDPSession(page)
  await page.goto(BASE)
  await page.waitForSelector('.ssg-body-row')
  await page.waitForTimeout(800)
  // ---- select(結果)
  await revealColumn(page, 'result')
  let c = await cellCenter(page, 0, 'result')
  console.log('result cell', c)
  await dbl(page, cdp, c)
  console.log('double tap result r1', await state(page))
  console.log(await shot(page, '03-iphone-select-editor'))
  const opts = await page.evaluate(() => [...document.querySelectorAll('[role=option]')].map((o) => { const b = o.getBoundingClientRect(); return { t: o.textContent, x: b.x + b.width / 2, y: b.y + b.height / 2, h: b.height } }))
  console.log('options', opts)
  const ng = opts.find((o) => o.t.includes('要注意'))
  if (ng) { await cdpTap(page, cdp, ng.x, ng.y); await page.waitForTimeout(500) }
  console.log('after tapping option', await state(page), 'value=', await cellText(page, 0, 'result'))
  // ---- checkbox(写真)
  await revealColumn(page, 'photo')
  const cb = await page.evaluate(() => { const e = document.querySelector('.ssg-body-row[aria-rowindex="2"] [data-ssg-col-key="photo"] [role=checkbox]'); const b = e.getBoundingClientRect(); return { x: b.x + b.width / 2, y: b.y + b.height / 2, checked: e.getAttribute('aria-checked') } })
  await cdpTap(page, cdp, cb.x, cb.y)
  await page.waitForTimeout(400)
  const cb2 = await page.evaluate(() => document.querySelector('.ssg-body-row[aria-rowindex="2"] [data-ssg-col-key="photo"] [role=checkbox]').getAttribute('aria-checked'))
  console.log('checkbox tap', cb.checked, '->', cb2, await state(page))
  // セルの空き(チェックの外)をタップ
  c = await cellCenter(page, 1, 'photo')
  await cdpTap(page, cdp, c.x + 25, c.y)
  await page.waitForTimeout(400)
  const cb3 = await page.evaluate(() => document.querySelector('.ssg-body-row[aria-rowindex="3"] [data-ssg-col-key="photo"] [role=checkbox]').getAttribute('aria-checked'))
  console.log('tap photo cell margin r2 checked=', cb3, await state(page))
  // ---- number(測定値)
  await revealColumn(page, 'value', 2)
  c = await cellCenter(page, 2, 'value')
  await dbl(page, cdp, c)
  console.log('double tap value r3', await state(page))
  await page.keyboard.insertText('412.5')
  await page.waitForTimeout(100)
  console.log(await shot(page, '03-iphone-number-editor'))
  await page.keyboard.press('Enter')
  await page.waitForTimeout(400)
  console.log('after enter', await state(page), 'value=', await cellText(page, 2, 'value'))
  // ---- multiline(メモ)
  await revealColumn(page, 'memo', 4)
  c = await cellCenter(page, 4, 'memo')
  await dbl(page, cdp, c)
  console.log('double tap memo r5', await state(page))
  await page.keyboard.insertText('ナット緩み')
  await page.waitForTimeout(100)
  console.log(await shot(page, '03-iphone-memo-editor'))
  // 別のセルをタップして確定
  c = await cellCenter(page, 7, 'memo')
  await cdpTap(page, cdp, c.x, c.y)
  await page.waitForTimeout(500)
  console.log('after tap elsewhere', await state(page), 'memo r5 =', await cellText(page, 4, 'memo'))
  // ---- date(点検日)
  await revealColumn(page, 'inspectedAt', 0)
  c = await cellCenter(page, 0, 'inspectedAt')
  await dbl(page, cdp, c)
  console.log('double tap date r1', await state(page))
  console.log(await shot(page, '03-iphone-date-editor'))
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  console.log('after esc', await state(page))
  console.log('LOGS\n' + logs.join('\n'))
  await browser.close()
})()

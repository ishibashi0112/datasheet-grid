const { launch, shot, BASE } = require('./lib.cjs')
const { state } = require('./helpers.cjs')
const focusDesc = (page) => page.evaluate(() => { const e = document.activeElement; return `${e?.tagName}.${(e?.className || '').toString().split(' ')[0]}「${(e?.getAttribute('aria-label') || e?.closest('label')?.textContent || e?.textContent || '').trim().slice(0, 16)}」` })
const popOpen = (page) => page.evaluate(() => !!document.querySelector('.ssg-filter-popover'))
;(async () => {
  const { browser, page, logs } = await launch({ viewport: { width: 1280, height: 800 }, locale: 'ja-JP' })
  await page.goto(BASE)
  await page.waitForSelector('.ssg-body-row')
  await page.waitForTimeout(800)
  await page.focus('input[name=inspector]')
  for (let i = 0; i < 7; i++) await page.keyboard.press('Tab')
  console.log('focus', await focusDesc(page))
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowRight')
  await page.keyboard.press('Alt+ArrowDown'); await page.waitForTimeout(400)
  await page.keyboard.press('Enter'); await page.waitForTimeout(1000)
  console.log('opened', await popOpen(page), await focusDesc(page))
  for (let i = 0; i < 10; i++) {
    await page.keyboard.press('Tab'); await page.waitForTimeout(120)
    console.log(' Tab', i + 1, await focusDesc(page), 'popover open=', await popOpen(page))
  }
  await shot(page, '09-popover-tab-out')
  await page.keyboard.press('Escape'); await page.waitForTimeout(300)
  console.log('Esc while outside: popover open=', await popOpen(page), await focusDesc(page))
  // Shift+Tab で戻る
  await page.keyboard.press('Shift+Tab'); await page.waitForTimeout(150)
  console.log('Shift+Tab', await focusDesc(page), await popOpen(page))
  console.log('LOGS\n' + logs.join('\n'))
  await browser.close()
})()

const { launch, shot, ipad, cdpTap, cdpTouchDrag, BASE } = require('./lib.cjs')
const { cellCenter, state, revealColumn } = require('./helpers.cjs')
const rectOf = (page, sel) => page.evaluate((sel) => [...document.querySelectorAll(sel)].map((e) => { const b = e.getBoundingClientRect(); return { t: e.textContent.trim().slice(0, 30), x: b.x + b.width / 2, y: b.y + b.height / 2, w: Math.round(b.width), h: Math.round(b.height), top: Math.round(b.top), bottom: Math.round(b.bottom), left: Math.round(b.left), right: Math.round(b.right) } }), sel)
;(async () => {
  const { browser, context, page, logs } = await launch({ ...ipad(), locale: 'ja-JP' })
  const cdp = await context.newCDPSession(page)
  await page.goto(BASE)
  await page.waitForSelector('.ssg-body-row')
  await page.waitForTimeout(800)
  console.log('viewport', page.viewportSize())
  console.log(await shot(page, '06-ipad-portrait'))
  const sc = (await rectOf(page, '.ssg-scroll-container'))[0]
  await cdpTouchDrag(page, cdp, { x: sc.left + 400, y: sc.top + 500 }, { x: sc.left + 400, y: sc.top + 100 }, 15)
  await page.waitForTimeout(500)
  console.log('scrollTop', await page.evaluate(() => document.querySelector('.ssg-scroll-container').scrollTop))
  let c = await cellCenter(page, 15, 'result')
  await cdpTap(page, cdp, c.x, c.y); await page.waitForTimeout(150); await cdpTap(page, cdp, c.x, c.y); await page.waitForTimeout(500)
  console.log('dbl tap result', await state(page))
  const opt = (await rectOf(page, '[role=option]')).find((o) => o.t === '不良')
  await cdpTap(page, cdp, opt.x, opt.y); await page.waitForTimeout(500)
  console.log('picked 不良', await state(page))
  console.log(await shot(page, '06-ipad-after-pick'))
  // 不良 にしたのでメモ / 写真にマーク
  const marks = await page.evaluate(() => [...document.querySelectorAll('.ssg-body-row[aria-rowindex="17"] .ssg-body-cell')].map((c) => `${c.getAttribute('data-ssg-col-key')}:${c.className.replace(/ssg-body-cell ?/g, '')}`))
  console.log('row marks', marks)
  // 横向き
  await page.setViewportSize({ width: 1080, height: 810 })
  await page.waitForTimeout(800)
  console.log(await shot(page, '06-ipad-landscape'))
  console.log('landscape state', await state(page), await page.evaluate(() => { const sc = document.querySelector('.ssg-scroll-container'); return { ch: sc.clientHeight, cw: sc.clientWidth, sw: sc.scrollWidth } }))
  console.log('LOGS\n' + logs.join('\n'))
  await browser.close()
})()

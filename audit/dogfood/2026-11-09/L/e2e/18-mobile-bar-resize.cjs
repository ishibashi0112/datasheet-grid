const { launch, shot, iphone, cdpTap, cdpTouchDrag, BASE } = require('./lib.cjs')
const { state, revealColumn } = require('./helpers.cjs')
const rectOf = (page, sel) => page.evaluate((sel) => [...document.querySelectorAll(sel)].map((e) => { const b = e.getBoundingClientRect(); return { t: e.textContent.trim().slice(0, 40), cls: e.className.toString().slice(0, 50), x: b.x + b.width / 2, y: b.y + b.height / 2, w: Math.round(b.width), h: Math.round(b.height), top: Math.round(b.top), bottom: Math.round(b.bottom), left: Math.round(b.left), right: Math.round(b.right) } }), sel)
;(async () => {
  const { browser, context, page, logs } = await launch({ ...iphone(), locale: 'ja-JP' })
  const cdp = await context.newCDPSession(page)
  await page.goto(BASE); await page.waitForSelector('.ssg-body-row'); await page.waitForTimeout(800)
  await revealColumn(page, 'value', 0)
  const hdr = (await rectOf(page, '[role=columnheader]')).find((h) => h.t.includes('測定値'))
  await cdpTap(page, cdp, hdr.x + 20, hdr.y); await page.waitForTimeout(800)
  console.log('tap 測定値 header', await state(page))
  console.log(await shot(page, '18-iphone-col-selected-bar'))
  const bar = await rectOf(page, '.ssg-root > div:last-child, [class*=bottom]')
  console.log('bottom bar-ish', bar.filter((b) => b.h > 0).slice(0, 6))
  // 列の幅: 「項目」と「結果」の境目を指でドラッグ
  const before = await page.evaluate(() => [...document.querySelectorAll('[role=columnheader]')].map((h) => `${h.textContent.replace('⋮', '').trim().slice(0, 4)}:${Math.round(h.getBoundingClientRect().width)}`).join(' '))
  const handles = await rectOf(page, '[class*=resize]')
  console.log('resize handles', handles.slice(0, 5))
  const h = handles.find((x) => x.w > 0 && x.top < 300)
  if (h) {
    await cdpTouchDrag(page, cdp, { x: h.x, y: h.y }, { x: h.x + 60, y: h.y }, 10, 100)
    await page.waitForTimeout(500)
  }
  const after = await page.evaluate(() => [...document.querySelectorAll('[role=columnheader]')].map((h) => `${h.textContent.replace('⋮', '').trim().slice(0, 4)}:${Math.round(h.getBoundingClientRect().width)}`).join(' '))
  console.log('widths before', before, '\nwidths after ', after)
  console.log('scroll', await page.evaluate(() => document.querySelector('.ssg-scroll-container').scrollLeft))
  console.log('LOGS\n' + logs.join('\n'))
  await browser.close()
})()

// 最小再現(min.html): 主な所見をまとめて確かめる。MIN=URL で本番(preview)にも向けられる
const { launch, shot, iphone, cdpTap, cdpTouchDrag } = require('./lib.cjs')
const fs = require('fs')
const axeSrc = fs.readFileSync(require.resolve('axe-core/axe.min.js'), 'utf8')
const URL_ = process.env.MIN || 'http://127.0.0.1:5412/min.html'
const tag = process.env.TAG || 'dev'
const cellC = (page, rowIndex, key) => page.evaluate(({ rowIndex, key }) => { const c = document.querySelector(`.ssg-body-row[aria-rowindex="${rowIndex}"] [data-ssg-col-key="${key}"]`); if (!c) return null; const r = c.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } }, { rowIndex, key })
const hdrBtn = (page, title) => page.evaluate((title) => { const h = [...document.querySelectorAll('[role=columnheader]')].find((e) => e.textContent.includes(title)); const b = h.querySelector('button[aria-label$="列メニュー"]').getBoundingClientRect(); const hr = h.getBoundingClientRect(); return { menu: { x: b.x + b.width / 2, y: b.y + b.height / 2 }, head: { x: hr.right - 22, y: hr.y + hr.height / 2 } } }, title)
const item = (page, sel, text) => page.evaluate(({ sel, text }) => { const e = [...document.querySelectorAll(sel)].find((b) => b.textContent.includes(text)); if (!e) return null; e.scrollIntoView({ block: 'nearest' }); const r = e.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } }, { sel, text })
const tipVisible = (page) => page.evaluate(() => { const t = document.querySelector('.ssg-tooltip--visible'); return t ? t.textContent : null })
const ae = (page) => page.evaluate(() => { const a = document.activeElement; return a.tagName + '.' + String(a.className).split(' ')[0] + (a.getAttribute('aria-label') ? '[' + a.getAttribute('aria-label') + ']' : '') })
;(async () => {
  // ---- タッチ(iPhone 13 相当)
  {
    const { browser, context, page, logs } = await launch({ ...iphone(), locale: 'ja-JP' })
    const cdp = await context.newCDPSession(page)
    await page.goto(URL_); await page.waitForSelector('.ssg-body-row'); await page.waitForTimeout(800)
    // 1. 検査 NG のセル(行 2 = 状態「不良」、メモ空)
    const attrs = await page.evaluate(() => { const c = document.querySelector('.ssg-body-row[aria-rowindex="3"] [data-ssg-col-key="memo"]'); return { cls: c.className, tip: c.getAttribute('data-ssg-tooltip'), ariaInvalid: c.getAttribute('aria-invalid'), describedby: c.getAttribute('aria-describedby'), ariaDesc: c.getAttribute('aria-description') } })
    console.log('[1] invalid cell attrs', JSON.stringify(attrs))
    let p = await cellC(page, 3, 'memo')
    if (!p) { console.log('memo not visible; scroll'); }
    await cdpTap(page, cdp, p.x, p.y); await page.waitForTimeout(900)
    console.log('[1] tap -> tooltip', await tipVisible(page))
    await cdpTouchDrag(page, cdp, p, p, 1, 900); await page.waitForTimeout(300)
    console.log('[1] long press -> tooltip', await tipVisible(page))
    // 2. 列見出しのタップで列選択 → 下部バーの集計
    const q = await hdrBtn(page, '数量')
    await cdpTap(page, cdp, q.head.x, q.head.y); await page.waitForTimeout(800)
    const agg = await page.evaluate(() => { const i = document.querySelector('.ssg-bar-aggregates-inner'); if (!i) return null; const ir = i.getBoundingClientRect(); return { inner: [Math.round(ir.left), Math.round(ir.right)], sw: i.scrollWidth, cw: i.clientWidth, items: [...i.children].map((c) => { const r = c.getBoundingClientRect(); return c.textContent + ' [' + Math.round(r.left) + '-' + Math.round(r.right) + ']' }) } })
    console.log('[2] aggregates', JSON.stringify(agg))
    console.log(await shot(page, `30-${tag}-agg`))
    await page.evaluate(() => { const i = document.querySelector('.ssg-bar--bottom'); i.scrollIntoView() })
    await page.screenshot({ path: `shots/30-${tag}-agg-bar.png`, clip: await page.evaluate(() => { const r = document.querySelector('.ssg-bar--bottom').getBoundingClientRect(); return { x: 0, y: r.top - 2, width: innerWidth, height: r.height + 4 } }) })
    // 3. 列の固定(小メニュー)をタップ
    const s = await hdrBtn(page, '状態')
    await cdpTap(page, cdp, s.menu.x, s.menu.y); await page.waitForTimeout(500)
    const pin = await item(page, '.ssg-menu-item', '列の固定')
    await cdpTap(page, cdp, pin.x, pin.y); await page.waitForTimeout(700)
    const sub = await page.evaluate(() => [...document.querySelectorAll('.ssg-menu-item')].map((e) => e.textContent.trim()).filter((t) => /固定しない|左に固定|右に固定/.test(t)))
    console.log('[3] after tap 列の固定: submenu items =', JSON.stringify(sub))
    console.log(await shot(page, `30-${tag}-pin`))
    console.log('[3] menu still open?', await page.evaluate(() => document.querySelectorAll('.ssg-menu-panel').length))
    await cdpTap(page, cdp, pin.x, pin.y); await page.waitForTimeout(700)
    console.log('[3] after 2nd tap: submenu items =', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('.ssg-menu-item')].map((e) => e.textContent.trim()).filter((t) => /固定しない|左に固定|右に固定/.test(t)))))
    console.log('LOGS', logs.filter((l) => !l.includes('vite')).join(' | '))
    await browser.close()
  }
  // ---- 横向きのスマホでツールパネル
  {
    const { browser, context, page } = await launch({ ...iphone(), viewport: { width: 664, height: 390 }, locale: 'ja-JP' })
    const cdp = await context.newCDPSession(page)
    await page.goto(URL_); await page.waitForSelector('.ssg-body-row'); await page.waitForTimeout(800)
    const s = await hdrBtn(page, '状態')
    await cdpTap(page, cdp, s.menu.x, s.menu.y); await page.waitForTimeout(500)
    const it = await item(page, '.ssg-menu-item', '列の表示')
    await cdpTap(page, cdp, it.x, it.y); await page.waitForTimeout(1200)
    const tp = await page.evaluate(() => { const p = document.querySelector('.ssg-toolpanel'); const r = p.getBoundingClientRect(); const reset = [...p.querySelectorAll('button')].find((b) => b.textContent.includes('初期状態')); const rr = reset && reset.getBoundingClientRect(); return { top: Math.round(r.top), bottom: Math.round(r.bottom), vh: innerHeight, reset: rr ? [Math.round(rr.top), Math.round(rr.bottom)] : null } })
    console.log('[4] toolpanel landscape', JSON.stringify(tp))
    console.log(await shot(page, `30-${tag}-toolpanel-land`))
    await browser.close()
  }
  // ---- キーボード(デスクトップ)
  {
    const { browser, page, logs } = await launch({ viewport: { width: 1000, height: 700 }, locale: 'ja-JP' })
    await page.goto(URL_); await page.waitForSelector('.ssg-body-row'); await page.waitForTimeout(800)
    for (let i = 0; i < 6; i++) { await page.keyboard.press('Tab'); if ((await ae(page)).includes('ssg-shell')) break }
    console.log('[5] Tab ->', await ae(page))
    await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowRight')
    // 5. Shift+F10 / ContextMenu キー
    await page.keyboard.press('Shift+F10'); await page.waitForTimeout(400)
    console.log('[5] Shift+F10 -> menu', await page.evaluate(() => !!document.querySelector('.ssg-menu-panel')))
    await page.keyboard.press('ContextMenu'); await page.waitForTimeout(400)
    console.log('[5] ContextMenu key -> menu', await page.evaluate(() => !!document.querySelector('.ssg-menu-panel')))
    // 6. 列フィルターのポップオーバー: 最後のボタンから Tab
    await page.keyboard.press('Alt+ArrowDown'); await page.waitForTimeout(400)
    console.log('[6] menu first item', await ae(page))
    const fi = await page.evaluate(() => [...document.querySelectorAll('.ssg-menu-item')].findIndex((e) => e.textContent.includes('フィルター')))
    for (let i = 0; i < fi; i++) await page.keyboard.press('ArrowDown')
    await page.keyboard.press('Enter'); await page.waitForTimeout(1000)
    const popInfo = await page.evaluate(() => { const p = document.querySelector('.ssg-filter-popover'); return p ? { role: p.getAttribute('role'), label: p.getAttribute('aria-label'), modal: p.getAttribute('aria-modal') } : null })
    console.log('[6] popover', JSON.stringify(popInfo), 'focus', await ae(page))
    for (let i = 0; i < 12; i++) { await page.keyboard.press('Tab'); const a = await ae(page); if (!(await page.evaluate(() => document.activeElement.closest('.ssg-filter-popover')))) { console.log('[6] left popover after Tab x' + (i + 1), a, 'popover open', await page.evaluate(() => !!document.querySelector('.ssg-filter-popover'))); break } }
    await page.keyboard.press('Escape'); await page.waitForTimeout(300)
    console.log('[6] Esc outside -> popover open', await page.evaluate(() => !!document.querySelector('.ssg-filter-popover')), await ae(page))
    // 閉じる
    await page.mouse.click(5, 5); await page.waitForTimeout(300)
    // 7. エディタの名前(axe)
    await page.evaluate(() => document.querySelector('.ssg-shell').focus())
    await page.keyboard.press('Control+Home'); await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowRight')
    await page.keyboard.press('F2'); await page.waitForTimeout(300)
    console.log('[7] editing', await ae(page))
    await page.addScriptTag({ content: axeSrc })
    const v = await page.evaluate(async () => { const r = await axe.run(document.querySelector('.ssg-root'), { resultTypes: ['violations'] }); return r.violations.map((x) => `${x.id}(${x.impact}) ${x.nodes.map((n) => n.target.join(' ')).slice(0, 2).join(', ')}`) })
    console.log('[7] axe while editing text', JSON.stringify(v, null, 1))
    await page.keyboard.press('Escape')
    await page.keyboard.press('ArrowLeft'); await page.keyboard.press('ArrowLeft')
    await page.keyboard.press('F2'); await page.waitForTimeout(400)
    const v2 = await page.evaluate(async () => { const r = await axe.run(document.querySelector('.ssg-root'), { resultTypes: ['violations'] }); return r.violations.map((x) => `${x.id}(${x.impact}) ${x.nodes.map((n) => n.target.join(' ')).slice(0, 2).join(', ')}`) })
    console.log('[7] axe while editing select', await ae(page), JSON.stringify(v2, null, 1))
    // 8. キーボードで NG セルに来たとき
    await page.keyboard.press('Escape')
    await page.keyboard.press('Control+Home'); await page.keyboard.press('ArrowDown')
    for (let i = 0; i < 3; i++) await page.keyboard.press('ArrowRight')
    await page.waitForTimeout(900)
    console.log('[8] keyboard on invalid cell -> tooltip', await tipVisible(page), 'active desc', await page.evaluate(() => { const s = document.querySelector('.ssg-shell'); const c = document.getElementById(s.getAttribute('aria-activedescendant')); return c && (c.getAttribute('data-ssg-col-key') + ' invalid=' + c.getAttribute('aria-invalid') + ' describedby=' + c.getAttribute('aria-describedby')) }))
    console.log('LOGS', logs.filter((l) => !l.includes('vite') && !l.includes('DevTools')).join(' | '))
    await browser.close()
  }
})()

const { launch, iphone, cdpTap, BASE } = require('./lib.cjs')
const { revealColumn } = require('./helpers.cjs')
;(async () => {
  const { browser, context, page, logs } = await launch({ ...iphone(), locale: 'ja-JP' })
  const cdp = await context.newCDPSession(page)
  await page.goto(BASE)
  await page.waitForSelector('.ssg-body-row')
  await page.waitForTimeout(800)
  await revealColumn(page, 'result')
  const kebab = await page.evaluate(() => { const h = [...document.querySelectorAll('[role=columnheader]')].find((e) => e.textContent.includes('結果')); const r = h.querySelector('button').getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } })
  await cdpTap(page, cdp, kebab.x, kebab.y)
  await page.waitForTimeout(600)
  console.log(await page.evaluate(() => document.querySelector('.ssg-menu-panel').outerHTML.replace(/<svg.*?<\/svg>/g, '<svg/>').slice(0, 4000)))
  console.log(await page.evaluate(() => { const p = document.querySelector('.ssg-menu-panel'); return { sh: p.scrollHeight, ch: p.clientHeight, ov: getComputedStyle(p).overflowY, ae: document.activeElement?.outerHTML.slice(0, 200) } }))
  await browser.close()
})()

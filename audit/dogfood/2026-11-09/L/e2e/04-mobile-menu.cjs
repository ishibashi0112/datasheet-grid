const { launch, shot, iphone, cdpTap, cdpTouchDrag, BASE } = require('./lib.cjs')
const { cellCenter, state, revealColumn } = require('./helpers.cjs')
const popRect = (page) => page.evaluate(() => [...document.body.children].filter((e) => e.id !== 'root' && e.getBoundingClientRect().width > 0).map((e) => { const b = e.getBoundingClientRect(); return { cls: e.className?.toString().slice(0, 80), x: Math.round(b.x), y: Math.round(b.y), w: Math.round(b.width), h: Math.round(b.height), right: Math.round(b.right), bottom: Math.round(b.bottom) } }))
const rectOf = (page, sel) => page.evaluate((sel) => [...document.querySelectorAll(sel)].map((e) => { const b = e.getBoundingClientRect(); return { t: e.textContent.trim().slice(0, 30), x: b.x + b.width / 2, y: b.y + b.height / 2, w: Math.round(b.width), h: Math.round(b.height), top: Math.round(b.top), bottom: Math.round(b.bottom), right: Math.round(b.right) } }), sel)
;(async () => {
  const { browser, context, page, logs } = await launch({ ...iphone(), locale: 'ja-JP' })
  const cdp = await context.newCDPSession(page)
  await page.goto(BASE)
  await page.waitForSelector('.ssg-body-row')
  await page.waitForTimeout(800)
  await revealColumn(page, 'result')
  const kebabAttrs = await page.evaluate(() => { const h = [...document.querySelectorAll('[role=columnheader]')].find((e) => e.textContent.includes('結果')); const b = h.querySelector('button'); return [...b.attributes].map((a) => `${a.name}=${a.value}`) })
  console.log('kebab attrs', kebabAttrs)
  const kebab = await page.evaluate(() => { const h = [...document.querySelectorAll('[role=columnheader]')].find((e) => e.textContent.includes('結果')); const r = h.querySelector('button').getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } })
  await cdpTap(page, cdp, kebab.x, kebab.y)
  await page.waitForTimeout(600)
  const items = await rectOf(page, '.ssg-menu-item')
  console.log('menu item heights', items.map((i) => `${i.t}:${i.h}`).join(' | '))
  const f = items.find((i) => i.t.includes('フィルター…'))
  await cdpTap(page, cdp, f.x, f.y)
  await page.waitForTimeout(1500)
  console.log(await shot(page, '04-iphone-filter'))
  console.log('popups', await popRect(page))
  const pop = await page.evaluate(() => { const p = document.querySelector('.ssg-filter-popover'); if (!p) return null; return { role: p.getAttribute('role'), label: p.getAttribute('aria-label'), sh: p.scrollHeight, ch: p.clientHeight, ae: document.activeElement?.outerHTML.slice(0, 160) } })
  console.log('filter popover', pop)
  const labels = await rectOf(page, '.ssg-filter-popover label')
  console.log('filter labels', labels)
  // 「不良」のチェックを外す…ではなく「すべて」を外して 不良 だけ
  const all = labels.find((l) => l.t.includes('すべて'))
  if (all) { await cdpTap(page, cdp, all.x, all.y); await page.waitForTimeout(300) }
  const ng = (await rectOf(page, '.ssg-filter-popover label')).find((l) => l.t === '不良')
  if (ng) { await cdpTap(page, cdp, ng.x, ng.y); await page.waitForTimeout(300) }
  console.log(await shot(page, '04-iphone-filter-checked'))
  const btns = await rectOf(page, '.ssg-filter-popover button')
  console.log('filter buttons', btns.map((b) => `${b.t}:${b.w}x${b.h}@${b.top}-${b.bottom}`).join(' | '))
  const apply = btns.find((b) => b.t === '適用' || b.t.includes('適用'))
  if (apply) { await cdpTap(page, cdp, apply.x, apply.y); await page.waitForTimeout(800) }
  console.log('after apply popups', await popRect(page))
  console.log(await shot(page, '04-iphone-filtered'))
  const bar = await page.evaluate(() => document.querySelector('.ssg-root').innerText.split('\n').slice(0, 12))
  console.log('top text', bar)
  console.log('LOGS\n' + logs.join('\n'))
  await browser.close()
})()

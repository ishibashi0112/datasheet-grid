const { launch, shot, iphone, cdpTap, BASE } = require('./lib.cjs')
const rect = (page, sel, text) => page.evaluate(({ sel, text }) => { const e = [...document.querySelectorAll(sel)].find((x) => !text || x.textContent.includes(text)); if (!e) return null; const r = e.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2, l: Math.round(r.left), r: Math.round(r.right), t: Math.round(r.top), b: Math.round(r.bottom) } }, { sel, text })
;(async () => {
  const { browser, context, page, logs } = await launch({ ...iphone(), locale: 'ja-JP' })
  const cdp = await context.newCDPSession(page)
  await page.goto(BASE); await page.waitForSelector('.ssg-body-row'); await page.waitForTimeout(800)
  const k = await page.evaluate(() => { const h = [...document.querySelectorAll('[role=columnheader]')].find((e) => e.textContent.includes('項目')); const r = h.querySelector('button[aria-label$="列メニュー"]').getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } })
  await cdpTap(page, cdp, k.x, k.y); await page.waitForTimeout(500)
  const it = await rect(page, '.ssg-menu-item', '列の表示')
  await cdpTap(page, cdp, it.x, it.y); await page.waitForTimeout(1200)
  console.log('toolpanel', await rect(page, '.ssg-toolpanel'), 'viewport', page.viewportSize())
  console.log(await shot(page, '22-iphone-toolpanel'))
  const unit = await rect(page, '.ssg-chooser-toggle', '単位')
  console.log('単位 toggle', unit)
  if (unit) { await cdpTap(page, cdp, unit.x, unit.y); await page.waitForTimeout(500) }
  console.log('headers', await page.evaluate(() => [...document.querySelectorAll('[role=columnheader]')].map((h) => h.textContent.replace(/[⋮⠿]/g, '').trim()).join(',')))
  console.log('colcount', await page.evaluate(() => document.querySelector('[role=grid]').getAttribute('aria-colcount')), await page.evaluate(() => [...document.querySelectorAll('.ssg-body-row[aria-rowindex="2"] [role=gridcell]')].map((c) => c.getAttribute('aria-colindex') + ':' + c.getAttribute('data-ssg-col-key')).join(' ')))
  console.log(await shot(page, '22-iphone-toolpanel-after'))
  const close = await rect(page, '.ssg-popover-close')
  if (close) { await cdpTap(page, cdp, close.x, close.y); await page.waitForTimeout(400) }
  console.log('closed?', await page.evaluate(() => !!document.querySelector('.ssg-toolpanel') && getComputedStyle(document.querySelector('.ssg-toolpanel')).display))
  console.log('LOGS\n' + logs.join('\n'))
  await browser.close()
})()

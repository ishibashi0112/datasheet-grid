const { launch, shot, BASE } = require('./lib.cjs')
const { cellCenter, revealRow } = require('./helpers.cjs')
;(async () => {
  const { browser, page, logs } = await launch({ viewport: { width: 1000, height: 640 }, locale: 'ja-JP', forcedColors: 'active', colorScheme: 'dark' })
  await page.goto(BASE); await page.waitForSelector('.ssg-body-row'); await page.waitForTimeout(800)
  console.log('matches forced-colors', await page.evaluate(() => matchMedia('(forced-colors: active)').matches))
  // キーボードで入って、矢印 → アクティブセル
  await page.focus('input[name=inspector]')
  for (let i = 0; i < 7; i++) await page.keyboard.press('Tab')
  await page.waitForTimeout(200)
  console.log(await shot(page, '13-fc-tab-into-grid'))
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowRight'); await page.waitForTimeout(300)
  console.log(await shot(page, '13-fc-active-cell'))
  // 範囲選択(Shift+矢印)
  await page.keyboard.press('Shift+ArrowDown'); await page.keyboard.press('Shift+ArrowDown'); await page.keyboard.press('Shift+ArrowRight'); await page.waitForTimeout(300)
  console.log(await shot(page, '13-fc-range'))
  // 行選択(行番号クリック)
  const rn = await page.evaluate(() => { const e = document.querySelector('.ssg-body-row[aria-rowindex="8"] .ssg-row-header-cell'); const b = e.getBoundingClientRect(); return { x: b.x + b.width / 2, y: b.y + b.height / 2 } })
  await page.mouse.click(rn.x, rn.y); await page.waitForTimeout(300)
  await page.mouse.move(5, 5)
  console.log(await shot(page, '13-fc-row-selected'))
  // 編集
  const c = await cellCenter(page, 3, 'memo'); await page.mouse.dblclick(c.x, c.y); await page.waitForTimeout(300)
  console.log(await shot(page, '13-fc-editing'))
  await page.keyboard.press('Escape')
  // 列メニュー + フィルター
  const k = await page.evaluate(() => { const h = [...document.querySelectorAll('[role=columnheader]')].find((e) => e.textContent.includes('結果')); const r = h.querySelector('button').getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } })
  await page.mouse.move(k.x - 30, k.y); await page.waitForTimeout(200); await page.mouse.click(k.x, k.y); await page.waitForTimeout(300)
  await page.keyboard.press('ArrowDown'); await page.waitForTimeout(100)
  console.log(await shot(page, '13-fc-colmenu'))
  await page.evaluate(() => [...document.querySelectorAll('.ssg-menu-item')].find((m) => m.textContent.includes('フィルター…')).click()); await page.waitForTimeout(1000)
  console.log(await shot(page, '13-fc-filter'))
  await page.keyboard.press('Escape'); await page.waitForTimeout(300)
  console.log('LOGS\n' + logs.join('\n'))
  await browser.close()
})()

const { launch, shot, iphone, cdpTap, BASE } = require('./lib.cjs')
const { cellCenter, state } = require('./helpers.cjs')
;(async () => {
  const { browser, context, page, logs } = await launch({ ...iphone(), locale: 'ja-JP' })
  const cdp = await context.newCDPSession(page)
  await page.goto(BASE)
  await page.waitForSelector('.ssg-body-row')
  await page.waitForTimeout(800)
  let c = await cellCenter(page, 2, 'item')
  await cdpTap(page, cdp, c.x, c.y); await page.waitForTimeout(300)
  console.log('A', await state(page))
  await page.evaluate(() => document.querySelector('.ssg-scroll-container').scrollTo({ top: 3000 }))
  await page.waitForTimeout(500)
  console.log('B after programmatic scroll', await state(page))
  c = await cellCenter(page, 86, 'item')
  console.log('c', c, await page.evaluate(({ x, y }) => { const e = document.elementFromPoint(x, y); return e?.className + ' / ' + e?.textContent?.slice(0, 20) }, c))
  await cdpTap(page, cdp, c.x, c.y); await page.waitForTimeout(300)
  console.log('C after tap', await state(page))
  await browser.close()
})()

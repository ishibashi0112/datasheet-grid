const { chromium } = require('playwright')
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ deviceScaleFactor: 1, viewport: { width: 600, height: 600 } })
  await page.goto('http://127.0.0.1:5406/mini.html?case=drag')
  await page.waitForSelector('.ssg-body-cell')
  const input = page.getByLabel('外の入力欄')
  await input.click(); await page.keyboard.press('End'); await page.keyboard.type('def')
  const hb = await page.locator('.ssg-row-drag-handle').first().boundingBox()
  await page.mouse.move(hb.x + hb.width / 2, hb.y + hb.height / 2); await page.mouse.down()
  await page.mouse.move(hb.x + hb.width / 2, hb.y + 20, { steps: 3 }); await page.mouse.move(hb.x + hb.width / 2, hb.y + 130, { steps: 10 }); await page.mouse.up()
  await page.waitForTimeout(400)
  const names = () => page.evaluate(() => window.__mini.rows.slice(0, 5).map((r) => r.name).join(','))
  console.log('after drag', await names(), '| focus:', await page.evaluate(() => document.activeElement?.tagName + ' ' + (document.activeElement?.getAttribute('aria-label') ?? document.activeElement?.className)))
  await page.keyboard.press('Control+z'); await page.waitForTimeout(200)
  console.log('after Ctrl+Z', await names(), '| input value:', await input.inputValue())
  // セルを 1 度クリックした後なら?
  await page.locator('.ssg-body-cell').nth(3).click()
  await page.keyboard.press('Control+z'); await page.waitForTimeout(200)
  console.log('after click cell + Ctrl+Z', await names())
  await browser.close()
})()

const { chromium } = require('playwright')
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ deviceScaleFactor: 1 })
  const logs = []
  page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) logs.push(m.text().slice(0, 300)) })
  await page.goto('http://127.0.0.1:5406/mini.html?case=custom-noguard')
  await page.waitForSelector('.ssg-body-cell')
  const st = () => page.evaluate(() => ({ res: window.__res, changes: window.__changes, rows: window.__mini.rows.slice(0, 4).map((r) => r.name), active: window.__mini.ref.current.getActiveCell(), undo: window.__mini.ref.current.canUndo() }))
  await page.locator('[role=gridcell]', { hasText: '品目 2' }).first().click()
  await page.keyboard.type('X')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(300)
  console.log('Enter:', JSON.stringify(await st()))
  await page.keyboard.type('Y')
  await page.keyboard.press('Tab')
  await page.waitForTimeout(300)
  console.log('Tab:', JSON.stringify(await st()))
  await page.keyboard.press('Shift+Tab')
  await page.keyboard.type('Z')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  console.log('Esc:', JSON.stringify(await st()))
  console.log(logs)
  await browser.close()
})()

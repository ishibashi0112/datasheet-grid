const { open, shot, handle, appState, clickCell } = require('./lib.cjs')
const log = (...a) => console.log(...a)
const act = (page) => handle(page, 'return JSON.stringify(g.getActiveCell())')
;(async () => {
  const { browser, page, logs } = await open('', { viewport: { width: 1280, height: 1000 } })
  // 工事の最後の行(大工工事 view 6) をクリック → Ctrl+Enter
  await clickCell(page, 6, '数量')
  await page.keyboard.press('Control+Enter')
  await page.waitForTimeout(200)
  await page.keyboard.type('LED')
  await page.waitForTimeout(700)
  await page.keyboard.press('Tab') // 候補 1 件目を選んで右へ
  await page.waitForTimeout(200)
  log('after name Tab active', await act(page), 'editing?', await page.evaluate(() => document.activeElement?.tagName))
  await page.keyboard.type('8')
  await page.keyboard.press('Tab')
  await page.waitForTimeout(150)
  log('after qty Tab active', await act(page))
  // 単位: select。印字キーで頭出し? 「台」は IME が要るので Enter で開いて ↓
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  log('select open', await page.evaluate(() => document.activeElement?.outerHTML.slice(0, 100)))
  await shot(page, '20-select-open')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Tab')
  await page.waitForTimeout(150)
  log('after unit Tab active', await act(page))
  await page.keyboard.type('7000')
  await page.keyboard.press('Tab') // 金額は読み取り専用 → 備考へ?
  await page.waitForTimeout(150)
  log('after price Tab active', await act(page))
  await page.keyboard.press('Tab')
  await page.waitForTimeout(150)
  log('after amount Tab active', await act(page))
  await page.keyboard.type('x')  // 備考を印字キーで開始
  await page.keyboard.press('Enter')
  await page.keyboard.type('y')
  await page.keyboard.press('Control+Enter')
  await page.waitForTimeout(200)
  log('after note commit active', await act(page), 'focus', await page.evaluate(() => document.activeElement?.className))
  let st = await appState(page)
  const r = st.rows.find((x) => x.name === 'LED ダウンライト' && x.qty === 8)
  log('new row', JSON.stringify(r))
  // もう 1 回 Ctrl+Enter (編集外) → 次の行
  await page.keyboard.press('Control+Enter')
  await page.waitForTimeout(200)
  log('2nd insert editor', await page.locator('.name-editor__input').count())
  // Shift+Tab で品名から左へ (テキスト確定)
  await page.keyboard.type('ABC')
  await page.waitForTimeout(100)
  await page.keyboard.press('Shift+Tab')
  await page.waitForTimeout(200)
  log('after name Shift+Tab active', await act(page), 'focus', await page.evaluate(() => document.activeElement?.className))
  // 数量で Shift+Tab → 品名へ
  await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowRight')
  log('after 2 ArrowRight', await act(page))
  await page.keyboard.press('Enter'); await page.keyboard.type('3'); await page.keyboard.press('Shift+Tab')
  await page.waitForTimeout(150)
  log('after qty Shift+Tab', await act(page))
  await page.keyboard.press('Shift+Tab')
  await page.waitForTimeout(150)
  log('Shift+Tab on name (not editing)', await act(page), 'focus', await page.evaluate(() => document.activeElement?.className))
  // 合計の一致
  st = await appState(page)
  const total = await page.locator('.ssg-total-row[data-pane="center"]').innerText()
  log('app total', st.grandTotal, 'grid total row', total.replace(/\n/g, ' '))
  // undo: 品名(候補選択)を戻すと単位・単価も戻るか
  for (let i = 0; i < 3; i++) { await handle(page, 'g.undo()'); await page.waitForTimeout(100) }
  st = await appState(page)
  log('rows after 3 undo (last 3 of 工事)', JSON.stringify(st.rows.slice(6, 10).map((r) => r.kind === 'item' ? [r.name, r.qty, r.unit, r.price, r.note] : r.label)))
  // 入力チェック
  await page.getByRole('button', { name: '入力チェック' }).click()
  await page.waitForTimeout(200)
  log('check msg', await page.locator('.toolbar__msg').innerText(), 'active', await act(page))
  log('LOGS', logs)
  await browser.close()
})()

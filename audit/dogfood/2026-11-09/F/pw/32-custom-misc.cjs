const { open, shot, handle, appState, clickCell, cellBox } = require('./lib.cjs')
const log = (...a) => console.log(...a)
;(async () => {
  const { browser, page, logs } = await open('?extra=30')
  // A: 編集中に件名の入力欄をクリック
  await clickCell(page, 2, '品名')
  await page.keyboard.press('F2'); await page.keyboard.press('End'); await page.keyboard.type('X')
  await page.getByLabel('件名').click()
  await page.waitForTimeout(250)
  let st = await appState(page)
  log('A name', st.rows[2].name, 'focus', await page.evaluate(() => document.activeElement?.getAttribute('aria-label') || document.activeElement?.className))
  await page.keyboard.type('Z')
  log('A subject', await page.getByLabel('件名').inputValue())
  // B: 編集中に Ctrl+Z (入力欄のネイティブ undo)
  await clickCell(page, 3, '品名')
  await page.keyboard.press('F2'); await page.keyboard.press('End'); await page.keyboard.type('YY')
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(150)
  log('B editor value after Ctrl+Z', await page.locator('.name-editor__input').inputValue().catch(() => '(closed)'))
  st = await appState(page)
  log('B rows[2].name (grid undo should not run)', st.rows[2].name)
  await page.keyboard.press('Escape')
  // C: 編集中にホイールでスクロール
  await clickCell(page, 4, '品名')
  await page.keyboard.press('F2')
  await page.waitForTimeout(600)
  const before = await page.locator('.name-editor').boundingBox()
  await page.mouse.move(700, 450)
  await page.mouse.wheel(0, 300)
  await page.waitForTimeout(400)
  const after = await page.locator('.name-editor').boundingBox().catch(() => null)
  log('C editor box before', JSON.stringify(before), 'after', JSON.stringify(after), 'scrollTop', JSON.stringify(await handle(page, 'return g.getScrollPosition()')))
  await shot(page, '32-scroll-while-editing')
  // ホイールを候補リストの上で
  await page.keyboard.press('Escape')
  await clickCell(page, 4, '品名')
  await page.keyboard.press('F2')
  await page.keyboard.press('Control+a')
  await page.keyboard.press('Backspace')
  await page.waitForTimeout(700)
  const lb = await page.locator('.name-suggest').boundingBox().catch(() => null)
  log('list box', JSON.stringify(lb))
  if (lb) {
    const s0 = await handle(page, 'return g.getScrollPosition().top')
    await page.mouse.move(lb.x + 50, lb.y + 30)
    await page.mouse.wheel(0, 200)
    await page.waitForTimeout(300)
    log('wheel on list: grid scrollTop', s0, '->', await handle(page, 'return g.getScrollPosition().top'), 'list scrollTop', await page.evaluate(() => document.querySelector('.name-suggest')?.scrollTop))
  }
  log('LOGS', logs)
  await browser.close()
})()

const { open, shot, handle, appState, clickCell } = require('./lib.cjs')
const log = (...a) => console.log(...a)
const viewNames = (page) => page.evaluate(() => [...document.querySelectorAll('.ssg-body-row[data-pane="center"]')].sort((a,b)=>+a.getAttribute('aria-rowindex')-+b.getAttribute('aria-rowindex')).map(r => r.hasAttribute('data-ssg-label-row') ? '[' + r.innerText.split('\n')[0] + ']' : (r.querySelector('[aria-colindex="3"]')?.innerText ?? '?')).join(' | '))
;(async () => {
  const { browser, page, logs } = await open('', { viewport: { width: 1280, height: 1000 } })
  // 金額の見出しを Shift+クリック → 昇順
  const hdr = page.locator('[role="columnheader"]', { hasText: '金額' })
  await hdr.click({ modifiers: ['Shift'] })
  await page.waitForTimeout(400)
  log('sorted asc:', await viewNames(page))
  log('state sort', JSON.stringify((await handle(page, 'return g.getState()')).sort))
  log('drag handles disabled', await page.locator('.ssg-row-drag-handle--disabled').count(), '/', await page.locator('.ssg-row-drag-handle').count())
  await shot(page, '13-sorted')
  // ソート中に行を追加(今の行の下) → どこに出るか / startEditing されるか
  await clickCell(page, 2, '数量')
  await page.getByRole('button', { name: '行を追加' }).click()
  await page.waitForTimeout(300)
  log('after insert while sorted:', await viewNames(page))
  log('editor open', await page.locator('.name-editor__input').count(), 'active', JSON.stringify(await handle(page, 'return g.getActiveCell()')))
  await page.keyboard.press('Escape')
  // 降順
  await hdr.click({ modifiers: ['Shift'] })
  await page.waitForTimeout(300)
  log('sorted desc:', await viewNames(page))
  // 解除
  await hdr.click({ modifiers: ['Shift'] })
  await page.waitForTimeout(300)
  log('unsorted:', await viewNames(page))
  // 列フィルター: 単位 = m2 だけ(列メニュー → フィルター)
  await page.locator('[role="columnheader"]', { hasText: '単位' }).hover()
  await page.getByRole('button', { name: '単位 の列メニュー' }).click()
  await page.waitForTimeout(300)
  await shot(page, '13-colmenu')
  const items = await page.locator('.ssg-menu-item').allInnerTexts()
  log('menu items', JSON.stringify(items))
  await page.keyboard.press('Escape')
  // グローバルフィルターは top bar を消したので handle の applyState で
  await handle(page, `g.applyState({ filters: { globalText: '費', columnFilters: {} } })`)
  await page.waitForTimeout(400)
  log('global "費":', await viewNames(page))
  log('total row', await page.locator('.ssg-total-row[data-pane="center"]').innerText())
  log('label render counts', await page.locator('[data-pane="center"][data-ssg-label-row]').allInnerTexts())
  await shot(page, '13-global-filter')
  log('LOGS', logs)
  await browser.close()
})()

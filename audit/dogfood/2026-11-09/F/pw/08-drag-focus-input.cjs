const { open, handle, appState } = require('./lib.cjs')
const log = (...a) => console.log(...a)
;(async () => {
  const { browser, page, logs } = await open()
  const subj = page.getByLabel('件名')
  await subj.click()
  await page.keyboard.press('End')
  await page.keyboard.type('(追加)')
  const h = await page.evaluateHandle(() => [...document.querySelectorAll('.ssg-body-row')].filter((r) => r.getAttribute('aria-rowindex') === '3').map((r) => r.querySelector('.ssg-row-drag-handle')).find(Boolean))
  const hb = await h.asElement().boundingBox()
  await page.mouse.move(hb.x + 5, hb.y + 5); await page.mouse.down()
  await page.mouse.move(hb.x + 5, hb.y + 20, { steps: 3 }); await page.mouse.move(hb.x + 5, hb.y + 160, { steps: 10 }); await page.mouse.up()
  await page.waitForTimeout(400)
  const st1 = await appState(page)
  log('order after drag:', st1.rows.slice(0, 6).map((r) => r.name || r.label).join(' | '))
  log('activeElement', await page.evaluate(() => document.activeElement?.tagName + ' ' + (document.activeElement?.getAttribute('aria-label') || document.activeElement?.parentElement?.textContent?.slice(0, 4))))
  await page.keyboard.press('Control+z'); await page.waitForTimeout(200)
  const st2 = await appState(page)
  log('order after Ctrl+Z:', st2.rows.slice(0, 6).map((r) => r.name || r.label).join(' | '))
  log('subject value', await subj.inputValue())
  log('LOGS', logs)
  await browser.close()
})()

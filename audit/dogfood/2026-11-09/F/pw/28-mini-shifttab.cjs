const { chromium } = require('playwright')
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ deviceScaleFactor: 1, viewport: { width: 600, height: 600 } })
  await page.goto('http://127.0.0.1:5406/mini.html?case=drag')
  await page.waitForSelector('.ssg-body-cell')
  const act = () => page.evaluate(() => JSON.stringify(window.__mini.ref.current.getActiveCell()) + ' focus=' + (document.activeElement?.className || document.activeElement?.tagName) + ' bar=' + document.querySelector('.ssg-bar--bottom')?.innerText.replace(/\n/g, ' ').match(/セル \S+ \S+/)?.[0])
  await page.locator('[role=gridcell]', { hasText: '品目 3' }).first().click()
  console.log('click 品目 3', await act())
  await page.keyboard.press('Shift+Tab'); console.log('Shift+Tab', await act())
  await page.keyboard.press('Shift+Tab'); console.log('Shift+Tab 2', await act())
  await page.locator('[role=gridcell]', { hasText: '品目 3' }).first().click()
  await page.keyboard.press('Home'); console.log('Home', await act())
  await page.keyboard.press('Control+ArrowLeft'); console.log('Ctrl+Left', await act())
  // 編集中の Shift+Tab
  await page.keyboard.press('ArrowRight'); await page.keyboard.press('Enter'); await page.keyboard.press('Shift+Tab'); await page.waitForTimeout(100)
  console.log('qty edit Shift+Tab', await act())
  await page.keyboard.press('Enter'); await page.keyboard.press('Shift+Tab'); await page.waitForTimeout(100)
  console.log('name edit Shift+Tab', await act())
  await browser.close()
})()

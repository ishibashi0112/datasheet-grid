const { open, shot, handle, clickCell, appState, cellBox } = require('./lib.cjs')
const log = (...a) => console.log(...a)
const names = (st) => st.rows.map((r) => (r.kind === 'section' ? `[${r.label}]` : r.name || '(空)')).join(' | ')
;(async () => {
  const { browser, page, logs } = await open()
  // 1. ボタンで今の行の下に追加
  await clickCell(page, 3, '数量')
  await page.getByRole('button', { name: '行を追加' }).click()
  await page.waitForTimeout(300)
  let st = await appState(page)
  log('after insert(btn):', names(st))
  log('editor open?', await page.locator('.name-editor__input').count(), 'focused', await page.evaluate(() => document.activeElement?.className))
  log('active', JSON.stringify(await handle(page, 'return g.getActiveCell()')))
  await shot(page, '05-insert-btn')
  // 候補から選んで確定
  await page.keyboard.type('塗装')
  await page.waitForTimeout(800)
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Tab')
  await page.waitForTimeout(200)
  // 数量を入れる
  await page.keyboard.type('20')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  st = await appState(page)
  log('new row', JSON.stringify(st.rows[4]), 'active', JSON.stringify(await handle(page, 'return g.getActiveCell()')))
  log('canUndo', await handle(page, 'return g.canUndo()'))
  // 2. ショートカット Ctrl+Enter(グリッドにフォーカスがある状態)
  await clickCell(page, 9, '単価')
  await page.keyboard.press('Control+Enter')
  await page.waitForTimeout(300)
  st = await appState(page)
  log('after insert(ctrl+enter):', names(st))
  log('editor open?', await page.locator('.name-editor__input').count())
  // 何も入れずに Esc
  await page.keyboard.press('Escape')
  await page.waitForTimeout(150)
  log('validate marks', await page.locator('.ssg-body-cell--invalid').count())
  // 3. 行を削除(ボタン): 範囲で 2 行を選んで
  const a = await cellBox(page, 5, '数量'), b = await cellBox(page, 6, '数量')
  await page.mouse.move(a.x + 10, a.y + 10); await page.mouse.down(); await page.mouse.move(b.x + 10, b.y + 10, { steps: 4 }); await page.mouse.up()
  await page.getByRole('button', { name: '行を削除' }).click()
  await page.waitForTimeout(200)
  st = await appState(page)
  log('after delete:', names(st), '| msg', await page.locator('.toolbar__msg').innerText())
  log('focus after delete', await page.evaluate(() => document.activeElement?.className), 'active', JSON.stringify(await handle(page, 'return g.getActiveCell()')))
  // Ctrl+Z で戻る
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(200)
  st = await appState(page)
  log('after undo:', names(st))
  // 4. Ctrl+Delete
  await clickCell(page, 2, '品名')
  await page.keyboard.press('Control+Delete')
  await page.waitForTimeout(200)
  st = await appState(page)
  log('after ctrl+delete:', names(st))
  // 5. 区分をまたいで範囲選択して削除: 範囲にラベル行が入るとき
  const c = await cellBox(page, 6, '品名'), d = await cellBox(page, 8, '品名')
  await page.mouse.move(c.x + 10, c.y + 10); await page.mouse.down(); await page.mouse.move(d.x + 10, d.y + 10, { steps: 4 }); await page.mouse.up()
  const selRows = await handle(page, 'return g.getSelectedRows().map(r => r.kind === "section" ? "[" + r.label + "]" : r.name)')
  log('selected rows spanning label:', JSON.stringify(selRows))
  await page.keyboard.press('Control+Delete')
  await page.waitForTimeout(200)
  st = await appState(page)
  log('after delete spanning:', names(st))
  // undo を連続
  for (let i = 0; i < 6; i++) { await page.keyboard.press('Control+z'); await page.waitForTimeout(80) }
  st = await appState(page)
  log('after 6 undo:', names(st))
  for (let i = 0; i < 6; i++) { await page.keyboard.press('Control+y'); await page.waitForTimeout(80) }
  st = await appState(page)
  log('after 6 redo:', names(st))
  log('LOGS', logs)
  await browser.close()
})()

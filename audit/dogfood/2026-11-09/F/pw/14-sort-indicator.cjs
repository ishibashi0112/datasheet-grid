const { open, shot } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open('')
  const hdr = page.locator('[role="columnheader"]', { hasText: '金額' })
  await hdr.click({ modifiers: ['Shift'] })
  await page.mouse.move(600, 500)
  await page.waitForTimeout(400)
  await shot(page, '14-sort-header', { clip: { x: 56, y: 130, width: 1170, height: 50 } })
  const q = page.locator('[role="columnheader"]', { hasText: '数量' })
  await q.click({ modifiers: ['Shift'] })
  await page.mouse.move(600, 500)
  await page.waitForTimeout(400)
  await shot(page, '14-sort-header2', { clip: { x: 56, y: 130, width: 1170, height: 50 } })
  console.log(await page.evaluate(() => [...document.querySelectorAll('[role=columnheader]')].map(h => h.getAttribute('aria-sort') + ':' + h.innerText.replace(/\n/g, '/'))))
  console.log(logs)
  await browser.close()
})()

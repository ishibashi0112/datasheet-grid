const { open, shot, handle, appState, clickCell } = require('./lib.cjs')
const log = (...a) => console.log(...a)
async function ime(page, cdp, text, commit) {
  for (let i = 1; i <= text.length; i++) {
    await cdp.send('Input.imeSetComposition', { text: text.slice(0, i), selectionStart: i, selectionEnd: i })
    await page.waitForTimeout(30)
  }
  await cdp.send('Input.insertText', { text: commit })
  await page.waitForTimeout(200)
}
;(async () => {
  const { browser, page, logs } = await open('?ime=1')
  const cdp = await page.context().newCDPSession(page)
  // 1. 備考(text multiline)で IME 直接入力
  await clickCell(page, 2, '備考')
  log('focus', await page.evaluate(() => document.activeElement?.outerHTML.slice(0, 80)))
  await ime(page, cdp, 'めも', 'メモ')
  log('note editor open', await page.evaluate(() => document.activeElement?.tagName + ' ' + document.activeElement?.value))
  await page.keyboard.press('Control+Enter')
  await page.waitForTimeout(200)
  let st = await appState(page)
  log('note', JSON.stringify(st.rows[2].note))
  // 2. 数量(number)で IME 直接入力 "１２"
  await clickCell(page, 3, '数量')
  await ime(page, cdp, '１２', '１２')
  log('qty editor', await page.evaluate(() => document.activeElement?.tagName + ' ' + document.activeElement?.value))
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  st = await appState(page)
  log('qty', st.rows[3].qty)
  // 3. 品名(custom)で IME 直接入力 "あしば"
  await clickCell(page, 4, '品名')
  await ime(page, cdp, 'あしば', '足場')
  await page.waitForTimeout(300)
  log('name editor open?', await page.locator('.name-editor__input').count(), 'value', await page.locator('.name-editor__input').inputValue().catch(() => '-'))
  await shot(page, '17-ime-custom')
  st = await appState(page)
  log('name', st.rows[4].name)
  // 4. 品名で F2 してから IME
  await page.keyboard.press('Escape')
  await clickCell(page, 4, '品名')
  await page.keyboard.press('F2')
  await page.keyboard.press('Control+a')
  await ime(page, cdp, 'あしば', '足場')
  await page.waitForTimeout(800)
  log('after F2+IME value', await page.locator('.name-editor__input').inputValue().catch(() => '-'), 'options', await page.locator('.name-suggest li[role=option]').count())
  // 変換中の Enter は確定にならないか(ime composition 中に Enter キー)
  await cdp.send('Input.imeSetComposition', { text: 'こうじ', selectionStart: 3, selectionEnd: 3 })
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  log('editor still open during composition Enter?', await page.locator('.name-editor__input').count())
  await cdp.send('Input.insertText', { text: '工事' })
  await page.waitForTimeout(200)
  log('value', await page.locator('.name-editor__input').inputValue().catch(() => '-'))
  log('LOGS', logs)
  await browser.close()
})()

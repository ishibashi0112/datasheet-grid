const { open, shot, handle, appState, clickCell } = require('./lib.cjs')
const log = (...a) => console.log(...a)
const names = (st) => st.rows.map((r) => (r.kind === 'section' ? `[${r.label}]` : `${r.name}/${r.qty}/${r.unit}/${r.price}`)).join(' | ')
;(async () => {
  const { browser, page, logs } = await open('', { viewport: { width: 1280, height: 1000 } })
  // 工事の最後の行(view 5) から 4 行 × 4 列 を貼る → 材料の見出しをまたぐ
  const tsv = ['シーリング打替え\t１２０\tm\t"1,200"', '養生シート張り\t45.5\tm2\t350', '美装工事\t1\t式\t45000', 'ガラス交換\t2\t枚\t１８，０００'].join('\r\n')
  await page.evaluate((t) => navigator.clipboard.writeText(t), tsv)
  await clickCell(page, 5, '品名')
  await page.keyboard.press('Control+v')
  await page.waitForTimeout(300)
  let st = await appState(page)
  log(names(st))
  log('canUndo', await handle(page, 'return g.canUndo()'), 'sel', JSON.stringify(await handle(page, 'return g.getSelection()')))
  await shot(page, '16-paste')
  await page.keyboard.press('Control+z'); await page.waitForTimeout(200)
  st = await appState(page)
  log('after undo', names(st).slice(0, 300))
  // 末尾を超えて貼る → createRow
  const lastV = await handle(page, `return g.getViewRowIndex(window.__estimate.rows.at(-1).id)`)
  await handle(page, `g.selectCell(arg, g.getColIndex('name'), { scrollIntoView: true })`, lastV)
  await page.evaluate((t) => navigator.clipboard.writeText(t), tsv)
  await handle(page, 'g.focus()')
  await page.keyboard.press('Control+v')
  await page.waitForTimeout(300)
  st = await appState(page)
  log('overflow paste: rows', st.rows.length, names(st).split(' | ').slice(-5).join(' | '))
  // 全選択 → コピー(ラベル行と合計行は含まない?)
  await page.keyboard.press('Control+a')
  await page.keyboard.press('Control+c')
  await page.waitForTimeout(150)
  const clip = await page.evaluate(() => navigator.clipboard.readText())
  log('copy all lines', clip.split('\r\n').length, JSON.stringify(clip.split('\r\n').slice(0, 3)))
  // Delete で品名を消す → validate
  await clickCell(page, 2, '品名')
  await page.keyboard.press('Delete')
  await page.waitForTimeout(200)
  st = await appState(page)
  log('after Delete name:', JSON.stringify(st.rows[2]), 'invalid', await page.locator('.ssg-body-cell--invalid').count())
  // 範囲で Delete: 数量と単価
  log('LOGS', logs)
  await browser.close()
})()

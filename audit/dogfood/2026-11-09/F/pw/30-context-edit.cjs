const { open, shot, handle, appState, cellBox } = require('./lib.cjs')
const log = (...a) => console.log(...a)
;(async () => {
  const { browser, page, logs } = await open('')
  const b = await cellBox(page, 3, '単価')
  await page.mouse.click(b.x + 20, b.y + 10, { button: 'right' })
  await page.waitForTimeout(250)
  await page.getByText('下に行を挿入').click()
  for (const t of [0, 50, 200, 600]) {
    await page.waitForTimeout(t)
    log(`+${t}ms editor`, await page.locator('.name-editor__input').count(), 'focus', await page.evaluate(() => document.activeElement?.className))
  }
  let st = await appState(page)
  log('row4', JSON.stringify(st.rows[4]))
  // キーボードで開いたときは?(メニューを Enter で実行)
  await page.keyboard.press('Escape')
  await page.mouse.click(b.x + 20, b.y + 10, { button: 'right' })
  await page.waitForTimeout(250)
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(400)
  log('kbd: editor', await page.locator('.name-editor__input').count(), 'focus', await page.evaluate(() => document.activeElement?.className))
  log('LOGS', logs)
  await browser.close()
})()

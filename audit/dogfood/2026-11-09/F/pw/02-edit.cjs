const { open, shot, handle, clickCell, cellText, appState } = require('./lib.cjs')
const log = (...a) => console.log(...a)
;(async () => {
  const { browser, page, logs } = await open()
  // 1. 数量を編集
  await clickCell(page, 1, '数量')
  await page.keyboard.type('10')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  let st = await appState(page)
  log('qty row1', st.rows[1].qty, 'amount cell', await cellText(page, 1, '金額'), 'grand', st.grandTotal)
  log('active after enter', await handle(page, 'return g.getActiveCell()'))
  log('label text', await page.locator('[data-pane="center"][data-ssg-label-row]').first().innerText())
  log('total row', await page.locator('[data-pane="center"].ssg-total-row, .ssg-total-row[data-pane="center"]').first().innerText().catch(()=>'?'), await page.locator('.ssg-total-row').count())
  log('header subtotal', await page.getByTestId('subtotal').innerText())
  log('undo btn disabled', await page.getByRole('button', { name: '元に戻す' }).isDisabled())
  // 2. undo / redo
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(150)
  st = await appState(page)
  log('after undo qty', st.rows[1].qty, 'active', await handle(page, 'return g.getActiveCell()'))
  await page.keyboard.press('Control+y')
  await page.waitForTimeout(150)
  st = await appState(page)
  log('after redo qty', st.rows[1].qty)
  // 3. 品名 custom エディタ: F2 → 候補 → ↓ → Enter
  await clickCell(page, 2, '品名')
  await page.keyboard.press('F2')
  await page.waitForTimeout(100)
  log('editor open', await page.locator('.name-editor__input').count(), 'value', await page.locator('.name-editor__input').inputValue().catch(() => null))
  await page.waitForTimeout(700)
  log('suggest items', await page.locator('.name-suggest li[role=option]').count())
  await shot(page, '02-suggest-f2')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(250)
  st = await appState(page)
  log('row2 after pick', JSON.stringify(st.rows[2]))
  log('active after pick', await handle(page, 'return g.getActiveCell()'))
  // 4. 印字キーで開始: 'LED'
  await clickCell(page, 4, '品名')
  await page.keyboard.type('LED')
  await page.waitForTimeout(800)
  log('editor value', await page.locator('.name-editor__input').inputValue().catch(() => null))
  log('suggest first', await page.locator('.name-suggest li[role=option]').first().innerText().catch(() => null))
  await shot(page, '02-suggest-typed')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(250)
  st = await appState(page)
  log('row4 after typed pick', JSON.stringify(st.rows[4]))
  // 5. Escape で取り消し
  await clickCell(page, 5, '品名')
  await page.keyboard.type('xyz')
  await page.waitForTimeout(300)
  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)
  st = await appState(page)
  log('row5 after esc', st.rows[5].name, 'editor count', await page.locator('.name-editor').count(), 'active', await handle(page, 'return g.getActiveCell()'))
  // focus after escape
  log('activeElement', await page.evaluate(() => document.activeElement?.className))
  // 6. Tab: テキストのまま確定して右へ (候補なし)
  await clickCell(page, 6, '品名')
  await page.keyboard.press('F2')
  await page.keyboard.press('Control+a')
  await page.keyboard.type('特注の造作棚')
  await page.waitForTimeout(700)
  log('suggest status', await page.locator('.name-suggest').innerText())
  await page.keyboard.press('Tab')
  await page.waitForTimeout(200)
  st = await appState(page)
  log('row6 after tab', st.rows[6].name, 'active', await handle(page, 'return g.getActiveCell()'))
  // 7. blur 確定: 編集して別のセルをクリック
  await clickCell(page, 9, '品名')
  await page.keyboard.press('F2')
  await page.keyboard.press('End')
  await page.keyboard.type('(追加)')
  await clickCell(page, 10, '数量')
  await page.waitForTimeout(200)
  st = await appState(page)
  log('row9 after blur', st.rows[9]?.name, '/ row idx9 kind', st.rows[9]?.kind, 'active', await handle(page, 'return g.getActiveCell()'))
  log('LOGS', logs)
  await browser.close()
})()

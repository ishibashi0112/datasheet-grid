const { chromium } = require('playwright')
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ deviceScaleFactor: 1, viewport: { width: 600, height: 600 } })
  await page.goto('http://127.0.0.1:5406/mini.html?case=drag')
  await page.waitForSelector('.ssg-body-cell')
  const names = () => page.evaluate(() => window.__mini.rows.slice(0, 5).map((r) => r.name).join(','))
  const cu = () => page.evaluate(() => window.__mini.ref.current.canUndo())
  const hb = await page.locator('.ssg-row-drag-handle').first().boundingBox()
  await page.mouse.move(hb.x + hb.width / 2, hb.y + hb.height / 2); await page.mouse.down()
  await page.mouse.move(hb.x + hb.width / 2, hb.y + 20, { steps: 3 }); await page.mouse.move(hb.x + hb.width / 2, hb.y + 130, { steps: 10 }); await page.mouse.up()
  await page.waitForTimeout(400)
  console.log('after drag', await names(), 'canUndo', await cu(), 'focus', await page.evaluate(() => document.activeElement?.tagName))
  const cell = page.locator('[role=gridcell]', { hasText: '品目 5' }).first()
  await cell.click()
  console.log('after click focus', await page.evaluate(() => document.activeElement?.className), 'canUndo', await cu())
  await page.keyboard.press('Control+z'); await page.waitForTimeout(300)
  console.log('after Ctrl+Z', await names(), 'canUndo', await cu())
  await browser.close()
})()

const { open, shot, handle, clickCell, appState } = require('./lib.cjs')
const log = (...a) => console.log(...a)
;(async () => {
  const { browser, page, logs } = await open()
  // A: 単価(number)を編集中に別のセルをクリック
  await clickCell(page, 2, '単価')
  await page.keyboard.type('2000')
  await clickCell(page, 4, '数量')
  await page.waitForTimeout(250)
  let st = await appState(page)
  log('A number: price', st.rows[2].price, 'active', JSON.stringify(await handle(page, 'return g.getActiveCell()')), 'sel', JSON.stringify(await handle(page, 'return g.getSelection()')))
  // B: 備考(multiline)を編集中に別のセルをクリック
  await clickCell(page, 2, '備考')
  await page.keyboard.type('メモ')
  await clickCell(page, 4, '単位')
  await page.waitForTimeout(250)
  st = await appState(page)
  log('B multiline: note', st.rows[2].note, 'active', JSON.stringify(await handle(page, 'return g.getActiveCell()')))
  // C: 品名(custom)を編集中に別のセルをクリック
  await clickCell(page, 2, '品名')
  await page.keyboard.press('F2')
  await page.keyboard.press('End')
  await page.keyboard.type('A')
  await page.waitForTimeout(100)
  await clickCell(page, 4, '単価')
  await page.waitForTimeout(250)
  st = await appState(page)
  log('C custom: name', st.rows[2].name, 'active', JSON.stringify(await handle(page, 'return g.getActiveCell()')))
  // D: custom を編集中に別のセルからドラッグで範囲選択
  await clickCell(page, 3, '品名')
  await page.keyboard.press('F2')
  await page.keyboard.press('End')
  await page.keyboard.type('B')
  const { cellBox } = require('./lib.cjs')
  const a = await cellBox(page, 5, '数量'), b = await cellBox(page, 6, '単価')
  await page.mouse.move(a.x + 10, a.y + 10); await page.mouse.down(); await page.mouse.move(b.x + 10, b.y + 10, { steps: 5 }); await page.mouse.up()
  await page.waitForTimeout(250)
  st = await appState(page)
  log('D custom drag: name', st.rows[3].name, 'active', JSON.stringify(await handle(page, 'return g.getActiveCell()')), 'sel', JSON.stringify(await handle(page, 'return g.getSelection()')))
  // E: number を編集中にドラッグ
  await clickCell(page, 3, '数量')
  await page.keyboard.type('7')
  await page.mouse.move(a.x + 10, a.y + 10); await page.mouse.down(); await page.mouse.move(b.x + 10, b.y + 10, { steps: 5 }); await page.mouse.up()
  await page.waitForTimeout(250)
  log('E number drag active', JSON.stringify(await handle(page, 'return g.getActiveCell()')), 'sel', JSON.stringify(await handle(page, 'return g.getSelection()')))
  log('LOGS', logs)
  await browser.close()
})()

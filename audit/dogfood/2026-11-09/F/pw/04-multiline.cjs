const { open, shot, handle, clickCell, appState, cellBox } = require('./lib.cjs')
const log = (...a) => console.log(...a)
;(async () => {
  const { browser, page, logs } = await open()
  // 備考: enterKey 'newline' → Enter で改行、Ctrl+Enter で確定
  await clickCell(page, 2, '備考')
  await page.keyboard.press('Enter')  // 編集開始
  await page.waitForTimeout(100)
  log('editor tag', await page.evaluate(() => document.activeElement?.tagName))
  await page.keyboard.type('一行目')
  await page.keyboard.press('Enter')
  await page.keyboard.type('二行目')
  await page.keyboard.press('Shift+Enter')
  await page.keyboard.type('三行目')
  await shot(page, '04-multiline-editing')
  log('value in textarea', JSON.stringify(await page.evaluate(() => document.activeElement?.value)))
  await page.keyboard.press('Control+Enter')
  await page.waitForTimeout(250)
  let st = await appState(page)
  log('note saved', JSON.stringify(st.rows[2].note), 'active', JSON.stringify(await handle(page, 'return g.getActiveCell()')))
  const b = await cellBox(page, 2, '備考')
  log('row height after', b.height)
  await shot(page, '04-multiline-after')
  // Ctrl+Enter の確定がアプリのショートカット(行追加)に化けないか
  log('rows length', st.rows.length)
  // Tab で確定
  await clickCell(page, 4, '備考')
  await page.keyboard.press('F2')
  await page.keyboard.type('abc')
  await page.keyboard.press('Enter')
  await page.keyboard.type('def')
  await page.keyboard.press('Tab')
  await page.waitForTimeout(200)
  st = await appState(page)
  log('tab commit', JSON.stringify(st.rows[4].note), 'active', JSON.stringify(await handle(page, 'return g.getActiveCell()')), 'rows', st.rows.length)
  // Escape で取り消し
  await clickCell(page, 4, '備考')
  await page.keyboard.press('F2')
  await page.keyboard.type('XYZ')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)
  st = await appState(page)
  log('esc', JSON.stringify(st.rows[4].note))
  // コピー: 改行入りのセルをコピー
  await clickCell(page, 2, '備考')
  await page.keyboard.press('Control+c')
  await page.waitForTimeout(150)
  log('clipboard', JSON.stringify(await page.evaluate(() => navigator.clipboard.readText())))
  log('LOGS', logs)
  await browser.close()
})()

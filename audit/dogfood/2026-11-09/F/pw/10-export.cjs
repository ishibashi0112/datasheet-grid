const { open, handle, appState } = require('./lib.cjs')
const fs = require('fs')
const log = (...a) => console.log(...a)
;(async () => {
  const { browser, page, logs } = await open()
  const [dl] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'CSV 出力' }).click()])
  const p = await dl.path()
  const buf = fs.readFileSync(p)
  log('download name', dl.suggestedFilename(), 'bytes', buf.length, 'BOM', buf.slice(0, 3).toString('hex'))
  log(buf.toString('utf8'))
  log('--- getExportData ---')
  const data = await handle(page, 'return g.getExportData({ includeLabelRows: true, includeTotalRow: true })')
  log(JSON.stringify(data.columns))
  log(JSON.stringify(data.rowKinds))
  log(JSON.stringify(data.rows.slice(0, 3)))
  log(JSON.stringify(data.rows.at(-1)))
  log('--- exportCsv default ---')
  log(await handle(page, 'return g.exportCsv()'))
  log('--- exportCsv raw + labels ---')
  log(await handle(page, `return g.exportCsv({ scope: 'raw', includeLabelRows: true, includeTotalRow: true })`))
  log('LOGS', logs)
  await browser.close()
})()

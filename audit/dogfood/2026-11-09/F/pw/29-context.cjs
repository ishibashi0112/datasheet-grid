const { open, shot, handle, appState, clickCell, cellBox } = require('./lib.cjs')
const log = (...a) => console.log(...a)
const names = (st) => st.rows.map((r) => (r.kind === 'section' ? `[${r.label}]` : r.name || '(空)')).join(' | ')
;(async () => {
  const { browser, page, logs } = await open('')
  // セルを右クリック
  const b = await cellBox(page, 3, '単価')
  await page.mouse.click(b.x + 20, b.y + 10, { button: 'right' })
  await page.waitForTimeout(250)
  log('menu items', JSON.stringify(await page.locator('.ssg-menu-item').allInnerTexts()))
  await shot(page, '29-context')
  await page.getByText('この行を複製').click()
  await page.waitForTimeout(300)
  let st = await appState(page)
  log('after duplicate', names(st).slice(0, 120), 'editor', await page.locator('.name-editor__input').count())
  await page.keyboard.press('Escape')
  // キーボード: Shift+F10 / ContextMenu キー
  await clickCell(page, 5, '数量')
  await page.keyboard.press('Shift+F10')
  await page.waitForTimeout(200)
  log('Shift+F10 menu?', await page.locator('.ssg-menu-panel').count())
  await page.keyboard.press('ContextMenu')
  await page.waitForTimeout(200)
  log('ContextMenu key menu?', await page.locator('.ssg-menu-panel').count())
  await page.keyboard.press('Escape')
  // 行番号を押して行を選ぶ → 右クリック → 選択した行を削除
  const rh = await page.evaluateHandle(() => [...document.querySelectorAll('[role="rowheader"]')].find((e) => e.textContent.trim() === '6'))
  const rb = await rh.asElement().boundingBox()
  await page.mouse.click(rb.x + 10, rb.y + 10)
  await page.mouse.click(rb.x + 10, rb.y + 10 + 36 * 2, { modifiers: ['Shift'] })  // 6〜? (ラベル行を挟む)
  await page.waitForTimeout(150)
  log('sel', JSON.stringify(await handle(page, 'return g.getSelection()')), 'selRows', JSON.stringify(await handle(page, 'return g.getSelectedRows().map(r=>r.name||r.label)')))
  await page.mouse.click(rb.x + 10, rb.y + 10, { button: 'right' })
  await page.waitForTimeout(250)
  log('menu items (rowheader)', JSON.stringify(await page.locator('.ssg-menu-item').allInnerTexts()))
  await page.getByText('選択した行を削除').click()
  await page.waitForTimeout(300)
  st = await appState(page)
  log('after delete selected', names(st))
  // ラベル行を右クリック
  const lab = page.locator('[data-pane="center"][data-ssg-label-row]').first()
  const lb = await lab.boundingBox()
  await page.mouse.click(lb.x + 400, lb.y + 10, { button: 'right' })
  await page.waitForTimeout(200)
  log('label row right click → grid menu?', await page.locator('.ssg-menu-panel').count())
  log('LOGS', logs)
  await browser.close()
})()

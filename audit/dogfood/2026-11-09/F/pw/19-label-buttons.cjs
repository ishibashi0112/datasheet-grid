const { open, shot, handle, appState } = require('./lib.cjs')
const log = (...a) => console.log(...a)
const names = (st) => st.rows.map((r) => (r.kind === 'section' ? `[${r.label}]` : r.name || '(空)')).join(' | ')
;(async () => {
  const { browser, page, logs } = await open('?extra=40')
  page.on('dialog', async (d) => { log('dialog', d.message(), d.defaultValue()); await d.accept(d.defaultValue() === '材料' ? '材料費' : '追加工事') })
  // 材料の「名前を変更」(本物のラベル行)
  const btn = page.locator('[data-pane="center"][data-ssg-label-row]').filter({ hasText: '材料' }).getByRole('button', { name: '名前を変更' })
  log('rename buttons for 材料 (center pane)', await btn.count())
  await btn.click()
  await page.waitForTimeout(300)
  let st = await appState(page)
  log('after rename', names(st).slice(0, 120))
  log('canUndo', await handle(page, 'return g.canUndo()'), 'active', JSON.stringify(await handle(page, 'return g.getActiveCell()')))
  // 下へスクロールして sticky の見出しの「＋ 行」を押す
  await handle(page, 'g.scrollToRow(30, { align: "start" })')
  await page.waitForTimeout(300)
  await shot(page, '19-sticky')
  const stickies = await page.evaluate(() => [...document.querySelectorAll('[aria-hidden="true"]')].filter((e) => e.querySelector?.('.section-label')).map((e) => e.className + ' :: ' + e.innerText.replace(/\n/g, ' ')))
  log('sticky copies', JSON.stringify(stickies))
  // sticky のボタンの位置をクリック(画面上の材料費の見出しの ＋ 行)
  const plus = page.locator('.section-label__btn', { hasText: '＋ 行' })
  const boxes = []
  for (let i = 0; i < await plus.count(); i++) { const b = await plus.nth(i).boundingBox(); if (b) boxes.push(b) }
  log('plus button boxes', JSON.stringify(boxes.map((b) => [Math.round(b.x), Math.round(b.y)])))
  const top = boxes.sort((a, b) => a.y - b.y).find((b) => b.y > 170 && b.y < 200)
  if (top) {
    const hit = await page.evaluate(({ x, y }) => document.elementFromPoint(x, y)?.textContent, { x: top.x + 5, y: top.y + 5 })
    log('element at sticky plus', hit)
    await page.mouse.click(top.x + 5, top.y + 5)
    await page.waitForTimeout(400)
    st = await appState(page)
    const idx = st.rows.findIndex((r) => r.kind === 'section' && r.label === '諸経費')
    log('row before 諸経費:', JSON.stringify(st.rows[idx - 1]), 'editor', await page.locator('.name-editor__input').count())
    await shot(page, '19-after-sticky-plus')
  }
  // 区分を追加(ツールバー)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '区分を追加' }).click()
  await page.waitForTimeout(400)
  st = await appState(page)
  log('after addSection last 3', names(st).split(' | ').slice(-3).join(' | '), 'editor', await page.locator('.name-editor__input').count())
  await shot(page, '19-add-section')
  log('LOGS', logs)
  await browser.close()
})()

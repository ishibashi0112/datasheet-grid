const { launch, BASE, clickCell, chaos, texts } = require('./lib.cjs')
;(async () => {
  const { browser, ctx, page, logs } = await launch()
  await ctx.grantPermissions(['clipboard-read', 'clipboard-write'])
  await chaos(page, { getFailRate: 0, patchFailRate: 0, getDelay: 100 })
  await page.goto(BASE + '/users')
  await page.locator('.ssg-body-row:not([data-skeleton-row])').first().waitFor()
  await clickCell(page, 0, 'email')
  await page.keyboard.press('Control+End'); await page.waitForTimeout(1200)
  const last = await page.evaluate(() => { const a = document.querySelector('[id$="-active-cell"]'); return [a?.closest('[role=row]')?.getAttribute('aria-rowindex'), a?.getAttribute('data-ssg-col-key'), a?.textContent, document.querySelector('[role=grid]').getAttribute('aria-rowcount')] })
  await page.screenshot({ path: 'shot-ctrl-end.png' })
  await page.keyboard.press('Control+Home'); await page.waitForTimeout(800)
  const first = await page.evaluate(() => { const a = document.querySelector('[id$="-active-cell"]'); return [a?.closest('[role=row]')?.getAttribute('aria-rowindex'), a?.getAttribute('data-ssg-col-key'), a?.textContent] })
  // PageDown x3 + Shift+矢印でコピー
  await clickCell(page, 0, 'name')
  await page.keyboard.down('Shift'); for (let i = 0; i < 3; i++) await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowRight'); await page.keyboard.up('Shift')
  await page.keyboard.press('Control+c'); await page.waitForTimeout(300)
  const clip = await page.evaluate(() => navigator.clipboard.readText())
  // Ctrl+A → Ctrl+C(読み込み済みの行だけ)
  await page.keyboard.press('Control+a'); await page.keyboard.press('Control+c'); await page.waitForTimeout(500)
  const all = await page.evaluate(() => navigator.clipboard.readText())
  console.log(JSON.stringify({ last, first, clip, allLines: all.split('\n').length, bars: await texts(page, '.ssg-bar--bottom .ssg-bar-chip') }))
  console.log(logs.join('\n'))
  await browser.close()
})()

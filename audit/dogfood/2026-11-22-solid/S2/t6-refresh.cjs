const { launch, BASE, serverLog, clearLog, chaos, cell, clickCell, texts } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await launch()
  await chaos(page, { getFailRate: 0, patchFailRate: 0, getDelay: 100 })
  await page.goto(BASE + '/users')
  await page.waitForSelector('.ssg-body-row:not([data-skeleton-row])')
  const out = []
  // 少しスクロールしてから追加 → refreshServerSide はスクロール位置を保つか
  await page.mouse.move(700, 400)
  await page.mouse.wheel(0, 360)
  await page.waitForTimeout(500)
  const topBefore = await page.evaluate(() => document.querySelector('.ssg-scroll-container').scrollTop)
  await clearLog(page)
  await page.getByRole('button', { name: 'Add user' }).click()
  await page.waitForTimeout(1200)
  const topAfter = await page.evaluate(() => document.querySelector('.ssg-scroll-container').scrollTop)
  await page.mouse.wheel(0, -2000)
  await page.waitForTimeout(800)
  out.push(['add', topBefore, topAfter, await cell(page, 0, 'name').textContent(), await cell(page, 0, 'id').textContent(), await texts(page, '.ssg-bar--top .ssg-bar-chip'), JSON.stringify((await serverLog(page)).map((x) => x.method + (x.start ?? '')))])
  // 削除(renderCell のボタン)
  const id0 = await cell(page, 0, 'id').textContent()
  await page.locator('.ssg-scroll-container').evaluate((e) => (e.scrollLeft = 10000))
  await page.waitForTimeout(400)
  const btn = page.locator('.ssg-body-row[data-row-index="0"] [data-ssg-col-key="actions"] button')
  const bb = await btn.boundingBox()
  await page.mouse.click(bb.x + bb.width / 2, bb.y + bb.height / 2)
  await page.waitForTimeout(1200)
  out.push(['delete', id0, await cell(page, 0, 'id').textContent(), await texts(page, '.ssg-bar--top .ssg-bar-chip'), await page.evaluate(() => ({ active: document.querySelector('[id$="-active-cell"]')?.getAttribute('data-ssg-col-key'), sel: document.querySelectorAll('[aria-selected="true"]').length }))])
  await page.screenshot({ path: 'shot-after-delete.png' })
  await page.locator('.ssg-scroll-container').evaluate((e) => (e.scrollLeft = 0))
  // 取得の失敗 → エラーバー → retryServerSideLoads
  await chaos(page, { getFailRate: 1 })
  await page.mouse.move(700, 400)
  for (let i = 0; i < 5; i++) { await page.mouse.wheel(0, 5000); await page.waitForTimeout(100) }
  await page.waitForTimeout(1200)
  out.push(['fail bar', await texts(page, '.ssg-root [role="alert"]'), await page.locator('[data-testid="last-error"]').textContent().catch(() => null), await page.evaluate(() => document.querySelectorAll('[data-skeleton-row]').length)])
  await page.screenshot({ path: 'shot-loadfail.png' })
  // スクロールでは再要求しない
  await clearLog(page)
  await page.mouse.wheel(0, -300); await page.waitForTimeout(300); await page.mouse.wheel(0, 300); await page.waitForTimeout(800)
  out.push(['no refetch on scroll', JSON.stringify((await serverLog(page)).map((x) => x.method + x.start))])
  await chaos(page, { getFailRate: 0 })
  await clearLog(page)
  await page.getByRole('button', { name: 'Retry failed loads' }).click()
  await page.waitForTimeout(1200)
  out.push(['retry', JSON.stringify((await serverLog(page)).map((x) => x.method + x.start)), await texts(page, '.ssg-root [role="alert"]'), await page.evaluate(() => document.querySelectorAll('[data-skeleton-row]').length)])
  // 組み込みの「再試行」ボタン
  await chaos(page, { getFailRate: 1 })
  for (let i = 0; i < 5; i++) { await page.mouse.wheel(0, 5000); await page.waitForTimeout(100) }
  await page.waitForTimeout(1000)
  await chaos(page, { getFailRate: 0 })
  const alertBtns = await page.evaluate(() => [...document.querySelectorAll(".ssg-root [role=alert], .ssg-root [role=status]")].map(e => e.outerHTML.replace(/<svg.*?<\/svg>/g, "").slice(0, 600)))
  console.log(JSON.stringify(out, null, 0)); console.log(alertBtns); await page.screenshot({ path: "shot-loadfail2.png" }); process.exit(0)
  await page.locator('.ssg-root [role="alert"] button', { hasText: 'Retry' }).first().click()
  await page.waitForTimeout(1200)
  out.push(['builtin retry', alertBtns, await texts(page, '.ssg-root [role="alert"]'), await page.evaluate(() => document.querySelectorAll('[data-skeleton-row]').length)])
  for (const o of out) console.log(JSON.stringify(o))
  console.log(logs.join('\n'))
  await browser.close()
})()

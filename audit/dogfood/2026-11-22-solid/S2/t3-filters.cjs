const { launch, BASE, openColumnMenu, texts, serverLog, clearLog, chaos } = require('./lib.cjs')
const lastGet = async (page) => { const l = (await serverLog(page)).filter((x) => x.method === 'GET'); return l[l.length - 1] }
const vis = (page, key) => page.evaluate((k) => [...document.querySelectorAll(`.ssg-body-row:not([data-skeleton-row]) [data-ssg-col-key="${k}"]`)].slice(0, 6).map((e) => e.textContent.trim()), key)
const openFilter = async (page, key) => {
  await openColumnMenu(page, key)
  await page.locator('[role="menu"] .ssg-menu-item', { hasText: 'Filter…' }).click()
  await page.waitForTimeout(400)
}
;(async () => {
  const { browser, page, logs } = await launch()
  await chaos(page, { getFailRate: 0, patchFailRate: 0, getDelay: 150 })
  await page.goto(BASE + '/users')
  await page.waitForSelector('.ssg-body-row:not([data-skeleton-row])')
  await clearLog(page)
  const out = []
  // 1. text
  await openFilter(page, 'name')
  await page.locator('.ssg-filter-popover input.ssg-filter-input').fill('alice')
  await page.locator('.ssg-filter-popover .ssg-filter-btn-primary').click()
  await page.waitForTimeout(1200)
  out.push(['text', JSON.stringify((await lastGet(page)).query), await vis(page, 'name'), page.url()])
  // 2. set: uncheck Admin
  await openFilter(page, 'role')
  await page.locator('.ssg-filter-popover .ssg-filter-option', { hasText: 'Admin' }).click()
  await page.waitForTimeout(200)
  await page.keyboard.press('Escape')
  await page.waitForTimeout(1200)
  out.push(['set', JSON.stringify((await lastGet(page)).query), await vis(page, 'role'), page.url()])
  // 3. number
  await openFilter(page, 'logins')
  await page.locator('.ssg-filter-popover input.ssg-filter-input').fill('1000')
  await page.locator('.ssg-filter-popover .ssg-filter-btn-primary').click()
  await page.waitForTimeout(1200)
  out.push(['number', JSON.stringify((await lastGet(page)).query), await vis(page, 'logins'), page.url()])
  // 4. dateSet range
  await openFilter(page, 'createdAt')
  await page.locator('.ssg-filter-popover input[aria-label="Start date"]').fill('2024/01/01')
  await page.locator('.ssg-filter-popover input[aria-label="End date"]').fill('2024/03/31')
  await page.keyboard.press('Tab')
  await page.waitForTimeout(200)
  await page.screenshot({ path: 'shot-dateset.png' })
  const btns = await texts(page, '.ssg-filter-popover .ssg-filter-footer button')
  out.push(['dateset footer', btns])
  await page.locator('.ssg-filter-popover .ssg-filter-btn-primary').click()
  await page.waitForTimeout(1200)
  out.push(['dateSet', JSON.stringify((await lastGet(page)).query), await vis(page, 'createdAt'), page.url()])
  // 5. date (substring)
  await openFilter(page, 'lastLogin')
  await page.locator('.ssg-filter-popover input.ssg-filter-input').fill('2024-0')
  await page.locator('.ssg-filter-popover .ssg-filter-btn-primary').click()
  await page.waitForTimeout(1200)
  out.push(['date', JSON.stringify((await lastGet(page)).query), await vis(page, 'lastLogin'), page.url()])
  // 6. sort desc logins
  await openColumnMenu(page, 'logins')
  await page.locator('[role="menu"] .ssg-menu-item', { hasText: 'Sort descending' }).click()
  await page.waitForTimeout(1200)
  out.push(['sort', JSON.stringify((await lastGet(page)).query.sort), await vis(page, 'logins'), page.url()])
  // 7. global
  await page.locator('input[aria-label="Filter all columns"]').fill('marketing')
  await page.waitForTimeout(1500)
  out.push(['global', JSON.stringify((await lastGet(page)).query.globalText), await vis(page, 'department'), page.url()])
  const bars = await texts(page, '.ssg-bar-chip')
  out.push(['bars', bars])
  await page.screenshot({ path: 'shot-filtered.png' })
  // 8. back / forward
  const urls = []
  await page.goBack(); await page.waitForTimeout(1500)
  urls.push(['back1', page.url(), JSON.stringify((await lastGet(page)).query), await page.inputValue('input[aria-label="Filter all columns"]')])
  await page.goBack(); await page.waitForTimeout(1500)
  urls.push(['back2', page.url(), JSON.stringify((await lastGet(page)).query.sort), await vis(page, 'logins')])
  await page.goForward(); await page.waitForTimeout(1500)
  urls.push(['fwd', page.url(), JSON.stringify((await lastGet(page)).query.sort), await vis(page, 'logins')])
  out.push(['history', urls])
  // 9. reload with URL → SSR initialState
  const u = page.url()
  await clearLog(page)
  await page.goto(u)
  await page.waitForTimeout(2000)
  out.push(['reload', JSON.stringify((await serverLog(page)).filter((x) => x.method === 'GET').map((x) => [x.start, JSON.stringify(x.query)])), await vis(page, 'logins'), await texts(page, '.ssg-bar--top .ssg-bar-chip')])
  for (const o of out) console.log(JSON.stringify(o))
  console.log(logs.join('\n'))
  await browser.close()
})()

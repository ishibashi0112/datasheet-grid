const { launch, BASE, serverLog, clearLog, chaos, cell, clickCell, texts } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await launch()
  await chaos(page, { getFailRate: 0, patchFailRate: 0, getDelay: 100 })
  await page.goto(BASE + '/users')
  await page.waitForSelector('.ssg-body-row:not([data-skeleton-row])')
  await clearLog(page)
  await clickCell(page, 2, 'note')
  console.log('active', await page.evaluate(() => document.querySelector('[id$="-active-cell"]')?.getAttribute('data-ssg-col-key')))
  await page.keyboard.type('hello note')
  await page.waitForTimeout(100)
  console.log('editor', await page.evaluate(() => document.activeElement?.className + ' ' + document.activeElement?.value))
  await page.keyboard.press('Enter')
  await page.waitForTimeout(100)
  console.log('after enter', await cell(page, 2, 'note').textContent())
  await page.mouse.move(700, 400)
  for (let i = 0; i < 10; i++) { await page.mouse.wheel(0, 4000); await page.waitForTimeout(30) }
  await page.waitForTimeout(600)
  console.log('far rows', await page.evaluate(() => [...document.querySelectorAll('.ssg-body-row[data-pane="center"]')].slice(0, 2).map((r) => r.getAttribute('data-row-index') + (r.hasAttribute('data-skeleton-row') ? 's' : ''))))
  for (let i = 0; i < 10; i++) { await page.mouse.wheel(0, -4000); await page.waitForTimeout(30) }
  await page.waitForTimeout(1500)
  console.log('back', await cell(page, 2, 'note').textContent())
  console.log(JSON.stringify((await serverLog(page)).map((x) => x.method + ' ' + (x.start ?? '') + ' ' + JSON.stringify(x.body ?? ''))))
  console.log(logs.join('\n'))
  await browser.close()
})()

const { launch, BASE, openColumnMenu } = require('./lib.cjs')
;(async () => {
  const { browser, page } = await launch()
  const logs = []
  page.on('console', (m) => { if (/RELAY|TEAR|\[[A-Z_]{6,}\]/.test(m.text())) logs.push(m.text().split('\n')[0].slice(0, 160)) })
  const mark = (s) => logs.push('--- ' + s)
  await page.goto(BASE + '/users')
  await page.locator('.ssg-body-row:not([data-skeleton-row])').first().waitFor()
  await page.waitForTimeout(800)
  mark('sort')
  await openColumnMenu(page, 'logins')
  await page.locator('[role="menu"] .ssg-menu-item', { hasText: 'Sort descending' }).click()
  await page.waitForTimeout(1500)
  mark('text filter')
  await openColumnMenu(page, 'name')
  await page.locator('[role="menu"] .ssg-menu-item', { hasText: 'Filter…' }).click(); await page.waitForTimeout(300)
  await page.locator('.ssg-filter-popover input.ssg-filter-input').fill('alice')
  await page.locator('.ssg-filter-popover .ssg-filter-btn-primary').click()
  await page.waitForTimeout(1500)
  mark('global')
  await page.locator('input[aria-label="Filter all columns"]').fill('sales')
  await page.waitForTimeout(1500)
  mark('back')
  await page.goBack(); await page.waitForTimeout(1500)
  mark('end')
  console.log(logs.join('\n'))
  await browser.close()
})()

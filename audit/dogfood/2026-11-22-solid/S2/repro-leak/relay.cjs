// SSRM で列メニューから並べ替え / フィルターしたときの開発時の診断を集める
const { chromium } = require('playwright')
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1000, height: 700 } })
  const logs = []
  page.on('console', (m) => { if (!/vite/.test(m.text())) logs.push(m.type() + ' ' + m.text().split('\n').slice(0, 3).join(' | ')) })
  await page.goto(process.argv[2])
  await page.waitForTimeout(1500)
  const h = page.locator('[role="columnheader"][data-ssg-col-key="name"]').first()
  await h.hover(); await page.waitForTimeout(150)
  const b = await h.locator('button[aria-haspopup="menu"]').boundingBox()
  await page.mouse.click(b.x + 5, b.y + 5); await page.waitForTimeout(300)
  await page.locator('[role="menu"] .ssg-menu-item', { hasText: /降順|descending/ }).click()
  await page.waitForTimeout(1500)
  await h.hover(); await page.waitForTimeout(150)
  await page.mouse.click(b.x + 5, b.y + 5); await page.waitForTimeout(300)
  await page.locator('[role="menu"] .ssg-menu-item', { hasText: /フィルター|Filter/ }).first().click(); await page.waitForTimeout(300)
  await page.locator('.ssg-filter-popover input.ssg-filter-input').fill('9')
  await page.locator('.ssg-filter-popover .ssg-filter-btn-primary').click()
  await page.waitForTimeout(1500)
  logs.push('--- global')
  await page.locator('input.ssg-bar-input').fill('99')
  await page.waitForTimeout(1500)
  console.log([...new Set(logs)].join('\n') || '(no console output)')
  await browser.close()
})()

const { open, cell } = require('./lib.cjs')
;(async () => {
  const { browser, page } = await open(`http://localhost:5501/?tab=signal`)
  const r = () => page.evaluate(() => window.__getRows()[2].reorder)
  const box = await (await cell(page, 4, 9)).boundingBox()
  console.log('init', await r())
  await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2)
  await page.waitForTimeout(100)
  console.log('click checkbox', await r())
  await page.mouse.click(box.x + 4, box.y + 4)
  await page.waitForTimeout(100)
  console.log('click cell edge', await r())
  await page.keyboard.press(' ')
  await page.waitForTimeout(100)
  console.log('space', await r())
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(100)
  console.log('undo', await r())
  await browser.close()
})()

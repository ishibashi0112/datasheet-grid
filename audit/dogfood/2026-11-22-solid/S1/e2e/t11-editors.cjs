const { open, click, text, shot } = require('./lib.cjs')
;(async () => {
  const tab = process.argv[2] || 'signal'
  const { browser, page, logs } = await open(`${process.env.BASE || "http://localhost:5501/"}?tab=${tab}`)
  const row = (i) => page.evaluate((i) => ({ ...window.__getRows()[i] }), i)
  // 単価 2,000,000 → reject(編集は続き、吹き出し)
  await click(page, 3, 6)
  await page.keyboard.type('2000000')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  const bubble = await page.evaluate(() => { const b = document.querySelector('.ssg-cell-editor-error, [class*="error-bubble"], [role="alert"]'); return b ? b.textContent : null })
  console.log('reject: editing?', (await page.$('.ssg-cell-editor')) !== null, 'bubble', bubble, 'price', (await row(1)).price)
  await shot(page, `t11-reject-${tab}`)
  await page.keyboard.press('Escape')
  await page.waitForTimeout(100)
  // 品名を空に → mark
  await click(page, 3, 3)
  await page.keyboard.press('Delete')
  await page.waitForTimeout(150)
  console.log('name cleared', JSON.stringify((await row(1)).name), 'invalid', await page.$$eval('.ssg-body-cell[aria-invalid="true"]', (e) => e.map((x) => x.getAttribute('aria-description'))))
  // 備考 multiline: Alt+Enter で改行、Enter で確定
  await click(page, 3, 10, { clickCount: 2 })
  await page.waitForTimeout(100)
  await page.keyboard.type('一行目')
  await page.keyboard.press('Alt+Enter')
  await page.keyboard.type('二行目')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(150)
  console.log('note', JSON.stringify((await row(1)).note), 'active', await page.evaluate(() => JSON.stringify(window.__grid.getActiveCell())))
  // 既存の改行入りの備考(行 1 は確定済み → 行 8 = P-00008)を開いて閉じる
  await click(page, 9, 10, { clickCount: 2 })
  await page.waitForTimeout(100)
  console.log('textarea?', await page.evaluate(() => document.activeElement.tagName), JSON.stringify(await page.evaluate(() => document.activeElement.value)))
  await shot(page, `t11-multiline-${tab}`)
  await page.keyboard.press('Escape')
  // 要発注 checkbox: Space
  await click(page, 4, 9)
  await page.keyboard.press(' ')
  await page.waitForTimeout(100)
  console.log('reorder r3 after space', (await row(2)).reorder)
  // 区分 select: Enter で開いて ↓ Enter
  await click(page, 4, 4)
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  const opts = await page.$$eval('[role="option"]', (e) => e.map((x) => x.textContent))
  console.log('select options', opts)
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(150)
  console.log('category r3', (await row(2)).category, await text(page, 4, 4))
  // 日付を文字で打ち始め
  await click(page, 4, 8)
  await page.keyboard.type('2026/11/1')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(150)
  console.log('due r3', (await row(2)).due)
  // 数量を全角で打ち始め(IME なしで全角文字を insertText)
  await click(page, 4, 5)
  await page.keyboard.insertText('１，２００')
  await page.waitForTimeout(100)
  console.log('qty editor value', await page.evaluate(() => document.activeElement.value), await page.evaluate(() => document.activeElement.type))
  await page.keyboard.press('Enter')
  await page.waitForTimeout(150)
  console.log('qty r3', (await row(2)).qty)
  console.log('LOGS:\n' + logs.filter((l) => !l.includes('[vite]')).join('\n'))
  await browser.close()
})()

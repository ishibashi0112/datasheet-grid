const { open, shot } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open(process.argv[2] || 'http://localhost:5501/min-render.html')
  const h = page.locator('[role="columnheader"][aria-colindex="3"]').first()
  await h.hover(); await page.waitForTimeout(100)
  await h.locator('button, [role="button"]').last().click(); await page.waitForTimeout(200)
  await page.getByRole('menuitem', { name: /列の固定/ }).click(); await page.waitForTimeout(200)
  const items = await page.$$eval('[role="menuitemradio"]', (e) => e.map((x) => x.textContent + ':' + x.getAttribute('aria-checked')))
  console.log('pin submenu', items)
  await page.getByRole('menuitemradio', { name: /左/ }).first().click(); await page.waitForTimeout(300)
  console.log('qty header pane', await page.evaluate(() => document.querySelector('[role="columnheader"][data-ssg-col-key="qty"]')?.closest('[data-pane]')?.getAttribute('data-pane')), 'cols pinned', await page.evaluate(() => JSON.stringify(window.grid.getState().columns)))
  await shot(page, 'pin-left')
  console.log(logs.filter((l) => !l.includes('vite')).join('\n'))
  await browser.close()
})()

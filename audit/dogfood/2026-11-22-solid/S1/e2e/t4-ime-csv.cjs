const fs = require('fs')
const { open, click, text, shot } = require('./lib.cjs')
;(async () => {
  const tab = process.argv[2] || 'signal'
  const { browser, page, logs, context } = await open(`${process.env.BASE || "http://localhost:5501/"}?tab=${tab}`)
  const cdp = await context.newCDPSession(page)
  await page.click('#btn-ime')
  await page.waitForTimeout(200)
  // 品名(行 2)をクリック → IME で「りんご」→ 確定
  await click(page, 3, 3)
  await page.waitForTimeout(100)
  console.log('activeElement', await page.evaluate(() => `${document.activeElement.tagName}.${document.activeElement.className}`))
  await cdp.send('Input.imeSetComposition', { text: 'りんご', selectionStart: 3, selectionEnd: 3 })
  await page.waitForTimeout(100)
  await shot(page, `t4-ime-composing-${tab}`)
  await cdp.send('Input.insertText', { text: '林檎' })
  await page.waitForTimeout(200)
  const editorVal = await page.evaluate(() => document.activeElement && document.activeElement.value)
  console.log('editor value after commit composition', editorVal, await page.evaluate(() => document.activeElement.getAttribute('aria-label')))
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  console.log('cell after enter', await text(page, 3, 3), 'active', await page.evaluate(() => JSON.stringify(window.__grid.getActiveCell())))
  // number 列で全角
  await click(page, 4, 5)
  await cdp.send('Input.imeSetComposition', { text: '１２', selectionStart: 2, selectionEnd: 2 })
  await cdp.send('Input.insertText', { text: '１２' })
  await page.waitForTimeout(200)
  console.log('number editor value', await page.evaluate(() => document.activeElement && document.activeElement.value))
  await page.keyboard.press('Enter')
  await page.waitForTimeout(200)
  console.log('qty r3', await text(page, 4, 5), await page.evaluate(() => window.__getRows()[2].qty))
  // select 列での IME は捨てる
  await click(page, 4, 4)
  await cdp.send('Input.imeSetComposition', { text: 'しょくひん', selectionStart: 5, selectionEnd: 5 })
  await cdp.send('Input.insertText', { text: '食品' })
  await page.waitForTimeout(200)
  console.log('select col after IME', await text(page, 4, 4), 'editing?', await page.$('.ssg-cell-editor') !== null)
  await page.keyboard.press('Escape')
  // 確定済みの行(行 1)では捨てる
  await click(page, 2, 3)
  await cdp.send('Input.imeSetComposition', { text: 'あ', selectionStart: 1, selectionEnd: 1 })
  await cdp.send('Input.insertText', { text: 'あ' })
  await page.waitForTimeout(200)
  console.log('confirmed row after IME', await text(page, 2, 3), 'editing?', (await page.$('.ssg-cell-editor')) !== null)
  await page.click('#btn-ime')

  // CSV: 品名に =SUM を入れて escapeFormulas を確かめる
  await click(page, 5, 3, { clickCount: 2 })
  await page.keyboard.press('Control+a')
  await page.keyboard.type('=SUM(A1:A9)')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(150)
  const [dl] = await Promise.all([page.waitForEvent('download'), page.click('#btn-csv')])
  const p = await dl.path()
  const buf = fs.readFileSync(p)
  const csv = buf.toString('utf8')
  console.log('csv filename', dl.suggestedFilename(), 'bom', buf[0] === 0xef, 'lines', csv.split('\r\n').length)
  console.log(csv.split(/\r?\n/).slice(0, 5).join('\n'))
  console.log('...')
  console.log(csv.split(/\r?\n/).slice(-3).join('\n'))
  fs.writeFileSync(__dirname + `/../shots/export-${tab}.csv`, buf)
  console.log('LOGS:\n' + logs.filter((l) => !l.includes('[vite]')).join('\n'))
  await browser.close()
})()

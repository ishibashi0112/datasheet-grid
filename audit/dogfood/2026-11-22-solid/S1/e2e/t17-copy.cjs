const { open, click } = require('./lib.cjs')
;(async () => {
  const { browser, page } = await open(`${process.env.BASE || 'http://localhost:5501/'}?tab=signal`)
  await click(page, 2, 3)
  await page.keyboard.down('Shift'); await click(page, 3, 11); await page.keyboard.up('Shift')
  await page.keyboard.press('Control+c'); await page.waitForTimeout(200)
  console.log(JSON.stringify(await page.evaluate(() => navigator.clipboard.readText())))
  console.log('copy overlay', await page.$('.ssg-copy-range-overlay') !== null)
  // コピーしたものを別の行へ貼る(往復)
  await click(page, 5, 3)
  await page.keyboard.press('Control+v'); await page.waitForTimeout(200)
  console.log(JSON.stringify(await page.evaluate(() => window.__getRows().slice(3, 5).map((r) => [r.name, r.category, r.qty, r.price, r.due, r.reorder, r.note, r.status]))))
  await browser.close()
})()

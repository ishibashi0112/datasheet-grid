const { open, click, text } = require('./lib.cjs')
;(async () => {
  const { browser, page } = await open(`${process.env.BASE || 'http://localhost:5501/'}?tab=signal`)
  await click(page, 3, 5)
  await page.keyboard.type('42')
  console.log('during', await page.evaluate(() => `${document.activeElement.type} ${document.activeElement.value}`))
  await page.keyboard.press('Enter'); await page.waitForTimeout(100)
  console.log('qty r2 cell', await text(page, 3, 5))
  await click(page, 3, 6)
  await page.keyboard.type('123', { delay: 0 })
  await page.keyboard.press('Enter'); await page.waitForTimeout(100)
  console.log('price r2 cell', await text(page, 3, 6))
  await browser.close()
})()

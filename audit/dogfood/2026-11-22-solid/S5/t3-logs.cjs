const { open, sleep } = require('./lib.cjs')
const label = process.argv[2]
;(async () => {
  const { browser, page, logs } = await open('http://127.0.0.1:5505/' + (process.argv[3] ?? ''))
  await page.waitForSelector('.ssg-body-cell', { timeout: 60000 }); await sleep(1500)
  const topBar = () => page.evaluate(() => document.querySelector('.ssg-bar--top')?.innerText.replace(/\s+/g, ' '))
  // 1) dateSet の「今日」
  const th = page.locator('.ssg-header-cell', { hasText: '時刻' })
  await th.hover(); await th.locator('.ssg-icon-btn').last().click(); await sleep(300)
  await page.locator('.ssg-menu-panel .ssg-menu-item', { hasText: 'フィルター…' }).first().click()
  await page.waitForSelector('.ssg-filter-popover', { timeout: 10000 }); await sleep(500)
  await page.screenshot({ path: __dirname + `/shots/${label}-datefilter.png` })
  const chip = page.locator('.ssg-filter-popover button', { hasText: '今日' })
  console.log('preset chips', await page.locator('.ssg-filter-popover button').allInnerTexts())
  await chip.first().click(); await sleep(1500)
  console.log('today:', await topBar())
  await page.locator('.ssg-filter-popover button', { hasText: '閉じる' }).click(); await sleep(300)
  await page.evaluate(() => window.__logGrid.applyState({ filters: { columnFilters: {} } })); await sleep(1500)
  // 2) ERROR かつ auth(5 万行以下 → autoHeight が効く)
  await page.evaluate(() => window.__logGrid.applyState({ filters: { columnFilters: { level: { kind: 'set', values: ['ERROR'] }, service: { kind: 'set', values: ['auth'] } } } }))
  await sleep(2000)
  console.log('ERROR+auth:', await topBar())
  const heights = await page.evaluate(() => [...new Set([...document.querySelectorAll('.ssg-body-row[data-pane=center]')].map((r) => r.style.height))])
  console.log('row heights (autoHeight?)', heights.join(','))
  await page.screenshot({ path: __dirname + `/shots/${label}-autoheight.png` })
  // 3) 展開行
  const toggle = page.locator('.ssg-body-row[data-pane=left] [aria-expanded]').first()
  console.log('toggles', await page.locator('[aria-expanded]').count())
  await toggle.click(); await sleep(600)
  console.log('detail json shown', await page.locator('[data-testid=detail-json]').count(), (await page.locator('[data-testid=detail-json]').first().innerText().catch(() => '')).slice(0, 60).replace(/\s+/g, ' '))
  await page.screenshot({ path: __dirname + `/shots/${label}-detail.png` })
  // 4) Ctrl+F(フィルター中)
  await page.locator('.ssg-body-row[data-pane=center] .ssg-body-cell').first().click()
  await page.keyboard.press('Control+f'); await sleep(200); await page.keyboard.insertText('stack'); await sleep(1200)
  console.log('find in filtered:', await page.evaluate(() => document.querySelector('.ssg-find-bar')?.innerText.replace(/\s+/g, ' ')))
  await page.keyboard.press('Escape')
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('auto-height')).join('\n'))
  await browser.close()
})()

const { open, sleep } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open('http://127.0.0.1:5503/')
  await page.waitForSelector('.ssg-body-cell', { timeout: 15000 })
  await sleep(500)
  await page.click('[data-testid=open-dialog]')
  await page.waitForSelector('[data-testid=dialog-grid] .ssg-body-cell', { timeout: 10000 })
  await sleep(1000)
  const dlg = page.locator('[data-testid=dialog]')
  const c = dlg.locator(`.ssg-body-row[data-pane="center"][data-row-key="P00003"] [data-ssg-col-key="price"]`)
  await page.evaluate(() => { window.__ctx = []; document.addEventListener('contextmenu', (e) => window.__ctx.push(`${e.target.className} prevented=${e.defaultPrevented}`), false) })
  await c.click({ button: 'right' }); await sleep(400)
  console.log('ctx events', await page.evaluate(() => window.__ctx))
  console.log('panels', await page.locator('.ssg-menu-panel').count())
  await page.screenshot({ path: __dirname + '/shots/t9b.png' })
  // 一度左クリックしてから右クリック
  await c.click(); await sleep(200)
  await c.click({ button: 'right' }); await sleep(400)
  console.log('after left-click first: panels', await page.locator('.ssg-menu-panel').count(), await page.evaluate(() => window.__ctx))
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('HUGE_FAN')).join('\n'))
  await browser.close()
})()

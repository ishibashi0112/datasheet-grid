const { open, sleep } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open('http://127.0.0.1:5503/?grid=mixed')
  await page.waitForSelector('[data-testid=mixed-grid] .ssg-body-cell', { timeout: 15000 }); await sleep(1000)
  const m = (k, c) => page.locator(`[data-testid=main-grid] .ssg-body-row[data-pane="center"][data-row-key="${k}"] [data-ssg-col-key="${c}"]`)
  const x = (k, c) => page.locator(`[data-testid=mixed-grid] .ssg-body-row[data-pane="center"][data-row-key="${k}"] [data-ssg-col-key="${c}"]`)
  await m('P00002', 'name').dblclick(); await page.keyboard.press('Control+a'); await page.keyboard.type('混在テスト'); await page.keyboard.press('Enter'); await sleep(300)
  console.log('main edited, mixed shows', await x('P00002', 'name').innerText())
  await x('P00003', 'price').click(); await page.keyboard.type('777'); await page.keyboard.press('Enter'); await sleep(300)
  console.log('mixed edited, main shows', await m('P00003', 'price').innerText())
  // 全部入りの列メニュー → フィルター(遅延チャンク)
  const hdr = page.locator('[data-testid=mixed-grid] .ssg-header-cell', { hasText: '価格' })
  await hdr.hover(); await hdr.locator('.ssg-icon-btn').last().click(); await sleep(300)
  await page.locator('.ssg-menu-panel .ssg-menu-item', { hasText: 'フィルター…' }).first().click(); await sleep(600)
  console.log('filter popover from full grid', await page.locator('.ssg-filter-popover').count())
  await page.keyboard.press('Escape')
  const hdr2 = page.locator('[data-testid=main-grid] .ssg-header-cell', { hasText: 'ブランド' })
  await hdr2.hover(); await hdr2.locator('.ssg-icon-btn').last().click(); await sleep(300)
  await page.locator('.ssg-menu-panel .ssg-menu-item', { hasText: 'フィルター…' }).first().click(); await sleep(600)
  console.log('filter popover from lite grid', await page.locator('.ssg-filter-popover').count())
  await page.screenshot({ path: __dirname + '/shots/t12-mixed.png' })
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('HUGE_FAN')).join('\n'))
  await browser.close()
})()

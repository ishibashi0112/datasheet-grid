const { open, sleep, cell, val } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open('http://127.0.0.1:5503/')
  await page.waitForSelector('.ssg-body-cell', { timeout: 15000 })
  await sleep(800)
  const st = () => page.evaluate(() => {
    const ed = document.querySelector('.ssg-cell-editor')
    return `active=${document.activeElement?.tagName} editors=${document.querySelectorAll('.ssg-cell-editor').length} editorY=${ed ? Math.round(ed.getBoundingClientRect().y) : '-'} input=${document.querySelector('[data-testid=supplier-editor] input')?.value ?? '-'} bar=${document.querySelector('.ssg-shell')?.innerText.match(/セル [A-Z]+\d+/)?.[0]}`
  })
  await cell(page, 'P00004', 'supplier').dblclick()
  await sleep(500)
  await cell(page, 'P00006', 'supplier').dblclick()
  await sleep(500)
  console.log('A', await st())
  await page.keyboard.press('k')
  await sleep(200)
  console.log('after k', await st())
  await page.keyboard.press('ArrowDown')
  await sleep(200)
  console.log('after ArrowDown', await st())
  await page.keyboard.press('Enter')
  await sleep(300)
  console.log('after Enter', await st(), 'P00006=', await val(page, 'P00006', 'supplier'), 'P00007=', await val(page, 'P00007', 'supplier'))
  await page.screenshot({ path: __dirname + '/shots/t3e.png' })
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('HUGE_FAN')).join('\n'))
  await browser.close()
})()

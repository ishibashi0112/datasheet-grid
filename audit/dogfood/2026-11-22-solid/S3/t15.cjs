const { open, sleep, cell } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open('http://127.0.0.1:5503/')
  await page.waitForSelector('.ssg-body-cell', { timeout: 15000 }); await sleep(800)
  await cell(page, 'P00005', 'supplier').dblclick(); await sleep(500)
  const lb = await page.locator('[data-testid=supplier-list]').boundingBox()
  await page.mouse.move(lb.x + 50, lb.y + 50); await page.mouse.wheel(0, 300); await sleep(400)
  console.log('wheel on list: editor', await page.locator('.ssg-cell-editor').count(), 'list', await page.locator('[data-testid=supplier-list]').count())
  await page.locator('[data-testid=supplier-list] li').nth(20).click(); await sleep(300)
  console.log('picked after list scroll:', await cell(page, 'P00005', 'supplier').innerText())
  await cell(page, 'P00007', 'supplier').dblclick(); await sleep(500)
  const gb = await page.locator('.ssg-scroll-container').boundingBox()
  await page.mouse.move(gb.x + 200, gb.y + 300); await page.mouse.wheel(0, 300); await sleep(400)
  console.log('wheel on grid: editor', await page.locator('.ssg-cell-editor').count(), 'list', await page.locator('[data-testid=supplier-list]').count())
  // ラベル行の sticky
  await page.mouse.wheel(0, 9000); await sleep(600)
  await page.screenshot({ path: __dirname + '/shots/t15-sticky.png' })
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('HUGE_FAN')).join('\n'))
  await browser.close()
})()

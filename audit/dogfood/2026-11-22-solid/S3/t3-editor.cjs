const { open, sleep, cell, val } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open('http://127.0.0.1:5503/')
  await page.waitForSelector('.ssg-body-cell', { timeout: 15000 })
  await sleep(800)
  // 1) custom エディタ: ダブルクリックで開き、候補を絞ってキーボードで選ぶ
  console.log('before P00002 supplier =', await val(page, 'P00002', 'supplier'))
  await cell(page, 'P00002', 'supplier').dblclick()
  await sleep(300)
  console.log('editor count', await page.locator('[data-testid=supplier-editor]').count(), 'list', await page.locator('[data-testid=supplier-list]').count())
  await page.keyboard.type('大阪')
  await sleep(200)
  console.log('candidates', await page.locator('[data-testid=supplier-list] li').count())
  await page.screenshot({ path: __dirname + '/shots/t3-custom-open.png' })
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await sleep(300)
  console.log('after enter P00002 supplier =', await val(page, 'P00002', 'supplier'), 'editor', await page.locator('[data-testid=supplier-editor]').count(), 'list', await page.locator('[data-testid=supplier-list]').count())
  const active = await page.evaluate(() => { const a = document.querySelector('.ssg-body-cell--active, [data-ssg-active]'); return a ? a.closest('.ssg-body-row')?.getAttribute('data-row-key') + ' ' + a.getAttribute('data-ssg-col-key') : 'none' })
  console.log('active after enter', active, 'lastCommit', JSON.stringify(await page.evaluate(() => window.__lastCommit)))
  // 2) マウスで候補を押す
  await cell(page, 'P00004', 'supplier').dblclick()
  await sleep(400)
  const opt = page.locator('[data-testid=supplier-list] li').nth(5)
  const optText = await opt.innerText()
  await opt.click()
  await sleep(300)
  console.log('clicked', optText.replace(/\s+/g, ' '), '-> P00004 =', await val(page, 'P00004', 'supplier'), 'editor', await page.locator('[data-testid=supplier-editor]').count())
  // 3) 候補の一覧をスクロールしても閉じない(ホイール)
  await cell(page, 'P00005', 'supplier').dblclick()
  await sleep(400)
  const lb = await page.locator('[data-testid=supplier-list]').boundingBox()
  await page.mouse.move(lb.x + 50, lb.y + 50)
  await page.mouse.wheel(0, 200)
  await sleep(300)
  console.log('after list wheel: editor', await page.locator('[data-testid=supplier-editor]').count(), 'list', await page.locator('[data-testid=supplier-list]').count())
  // Escape で取り消し
  await page.keyboard.press('Escape')
  await sleep(200)
  console.log('after esc: editor', await page.locator('[data-testid=supplier-editor]').count(), 'list', await page.locator('[data-testid=supplier-list]').count(), 'P00005', await val(page, 'P00005', 'supplier'))
  // 4) Tab で確定して右へ
  await cell(page, 'P00006', 'supplier').dblclick()
  await sleep(300)
  await page.keyboard.type('東京')
  await page.keyboard.press('Tab')
  await sleep(300)
  console.log('after tab P00006 =', await val(page, 'P00006', 'supplier'))
  const active2 = await page.evaluate(() => { const a = document.querySelector('.ssg-body-cell--active'); return a ? a.closest('.ssg-body-row')?.getAttribute('data-row-key') + ' ' + a.getAttribute('data-ssg-col-key') : 'none' })
  console.log('active after tab', active2)
  // 5) 英字キーで打ち始め
  await cell(page, 'P00007', 'supplier').click()
  await page.keyboard.press('s')
  await sleep(300)
  console.log('typed s: input value =', await page.locator('[data-testid=supplier-editor] input').inputValue().catch(() => 'no editor'))
  await page.keyboard.press('Escape')
  // 6) Ctrl+Z
  await page.keyboard.press('Control+z')
  await sleep(200)
  console.log('after undo P00006 =', await val(page, 'P00006', 'supplier'))
  await page.screenshot({ path: __dirname + '/shots/t3-after.png' })
  console.log(logs.filter((l) => !l.includes('[vite]')).join('\n'))
  await browser.close()
})()

const { open, sleep, cell, val, activeRef, drag, center } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open('http://127.0.0.1:5503/')
  await page.waitForSelector('.ssg-body-cell', { timeout: 15000 })
  await sleep(800)
  const order = () => page.evaluate(() => [...document.querySelectorAll('.ssg-body-row[data-pane=left]')].sort((a, b) => +a.dataset.rowIndex - +b.dataset.rowIndex).slice(0, 8).map((r) => r.dataset.rowKey ?? 'LABEL').join(','))
  console.log('order before', await order())
  const h3 = await center(cell(page, 'P00003', '__ssg_row_drag_handle__', 'left'))
  const r1 = await center(cell(page, 'P00001', 'sku', 'left'))
  // P00003 を P00001 の上へ
  await page.mouse.move(h3.x, h3.y)
  await page.mouse.down()
  await page.mouse.move(h3.x, h3.y - 5, { steps: 3 })
  await page.mouse.move(h3.x, r1.y - 12, { steps: 15 })
  await sleep(200)
  await page.screenshot({ path: __dirname + '/shots/t6-drag-mid.png' })
  await page.mouse.up()
  await sleep(600)
  console.log('order after', await order())
  console.log('log', await page.locator('[data-testid=log]').innerText())
  // セクションをまたいで(文具 → 日用品)動かせないこと: 日用品のラベル行まで行く
  await page.evaluate(() => {})
  // undo
  await page.keyboard.press('Control+z')
  await sleep(400)
  console.log('order after undo', await order())
  // 最初のセクションの最初の行をラベル行の上(セクションの外)へ: canDropRow で拒否される
  const h1 = await center(cell(page, 'P00001', '__ssg_row_drag_handle__', 'left'))
  const label = await center(page.locator('.ssg-body-row[data-pane=left][data-ssg-label-row]').first())
  await page.mouse.move(h1.x, h1.y)
  await page.mouse.down()
  await page.mouse.move(h1.x, h1.y - 5, { steps: 3 })
  await page.mouse.move(h1.x, label.y - 10, { steps: 10 })
  await sleep(200)
  const indicator = await page.locator('.ssg-row-drop-indicator').count()
  await page.screenshot({ path: __dirname + '/shots/t6-drag-refuse.png' })
  await page.mouse.up()
  await sleep(500)
  console.log('refuse: indicator during', indicator, 'order', await order())
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('HUGE_FAN')).join('\n'))
  await browser.close()
})()

const { open, sleep, cell } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open('http://127.0.0.1:5503/')
  await page.waitForSelector('.ssg-body-cell', { timeout: 15000 }); await sleep(800)
  await page.click('[data-testid=dark]'); await sleep(400)
  await cell(page, 'P00003', 'stock').click()
  await page.keyboard.down('Shift'); await cell(page, 'P00006', 'releasedAt').click(); await page.keyboard.up('Shift')
  await sleep(300)
  await page.screenshot({ path: __dirname + '/shots/t10-dark.png' })
  // 列メニューとフィルター(ダーク)
  const hdr = page.locator('.ssg-header-cell', { hasText: '価格' })
  await hdr.hover(); await hdr.locator('.ssg-icon-btn').last().click(); await sleep(300)
  await page.screenshot({ path: __dirname + '/shots/t10-dark-menu.png' })
  await page.locator('.ssg-menu-panel .ssg-menu-item', { hasText: 'フィルター…' }).first().click(); await sleep(600)
  await page.screenshot({ path: __dirname + '/shots/t10-dark-filter.png' })
  await page.keyboard.press('Escape')
  // カスタムエディタ(ダーク)
  await cell(page, 'P00008', 'supplier').dblclick(); await sleep(500)
  await page.screenshot({ path: __dirname + '/shots/t10-dark-custom.png' })
  await page.keyboard.press('Escape')
  // CSV
  await page.click('[data-testid=csv]'); await sleep(300)
  const csv = await page.evaluate(() => window.__csv)
  console.log(csv.split('\n').slice(0, 4).join('\n'))
  console.log('csv lines', csv.split('\n').length)
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('HUGE_FAN')).join('\n'))
  await browser.close()
})()

const { open, sleep, cell, val, activeRef, center } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open('http://127.0.0.1:5503/')
  await page.waitForSelector('.ssg-body-cell', { timeout: 15000 })
  await sleep(800)
  await page.click('[data-testid=open-dialog]')
  await page.waitForSelector('[data-testid=dialog-grid] .ssg-body-cell', { timeout: 10000 })
  await sleep(1200)
  const dlg = page.locator('[data-testid=dialog]')
  const dcell = (k, c) => dlg.locator(`.ssg-body-row[data-pane="center"][data-row-key="${k}"] [data-ssg-col-key="${c}"]`)
  const topAt = async (sel) => page.evaluate((sel) => {
    const el = document.querySelector(sel); if (!el) return 'none'
    const r = el.getBoundingClientRect(); const hit = document.elementFromPoint(r.x + r.width / 2, r.y + Math.min(20, r.height / 2))
    return `inDialog=${!!el.closest('dialog')} hitSelf=${el.contains(hit)} hit=${hit?.tagName}.${(hit?.className || '').toString().slice(0, 30)}`
  }, sel)
  const isOpen = () => page.evaluate(() => document.querySelector('dialog').open)
  // 1. 列メニュー
  const hdr = dlg.locator('.ssg-header-cell', { hasText: 'ブランド' })
  await hdr.hover(); await sleep(100)
  await hdr.locator('.ssg-icon-btn').last().click(); await sleep(300)
  console.log('column menu:', await topAt('.ssg-menu-panel'))
  await page.screenshot({ path: __dirname + '/shots/t8-colmenu.png' })
  await page.keyboard.press('Escape'); await sleep(200)
  console.log('after Esc (menu close) dialog open =', await isOpen(), 'menu', await page.locator('.ssg-menu-panel').count())
  // 2. 列フィルター
  await hdr.hover(); await hdr.locator('.ssg-icon-btn').last().click(); await sleep(300)
  await page.locator('.ssg-menu-panel .ssg-menu-item', { hasText: 'フィルター…' }).first().click(); await sleep(600)
  console.log('filter popover:', await topAt('.ssg-filter-popover'))
  await page.screenshot({ path: __dirname + '/shots/t8-filter.png' })
  await page.keyboard.press('Escape'); await sleep(200)
  console.log('after Esc (filter close) dialog open =', await isOpen())
  // 3. 右クリック
  await dcell('P00003', 'price').click({ button: 'right', delay: 60 }); await sleep(300)
  console.log('context menu:', await topAt('.ssg-menu-panel'), 'items', (await page.locator('.ssg-menu-panel .ssg-menu-item').allInnerTexts()).join('|'))
  await page.screenshot({ path: __dirname + '/shots/t8-ctx.png' })
  await page.keyboard.press('Escape'); await sleep(200)
  console.log('after Esc (ctx close) dialog open =', await isOpen())
  // 4. select エディタ
  await dcell('P00003', 'brand').dblclick(); await sleep(400)
  console.log('select popover:', await topAt('.ssg-select-editor-popover'))
  await page.keyboard.press('Escape'); await sleep(200)
  console.log('after Esc (select cancel) dialog open =', await isOpen(), 'editor', await page.locator('.ssg-cell-editor').count())
  // 5. custom エディタ(ポータルで body)
  await dcell('P00003', 'supplier').dblclick(); await sleep(500)
  console.log('custom list:', await topAt('[data-testid=supplier-list]'))
  await page.screenshot({ path: __dirname + '/shots/t8-custom.png' })
  await page.keyboard.press('Escape'); await sleep(200)
  console.log('after Esc (custom cancel) dialog open =', await isOpen(), 'editor', await page.locator('.ssg-cell-editor').count())
  // 6. text エディタの Esc
  await dcell('P00004', 'name').dblclick(); await sleep(200)
  await page.keyboard.press('Escape'); await sleep(200)
  console.log('after Esc (text cancel) dialog open =', await isOpen(), 'active', await page.evaluate(() => document.querySelector('dialog .ssg-bar--bottom')?.innerText.match(/セル\s*(\S+)/)?.[1]))
  // 7. 範囲選択して Esc → 範囲解除(閉じない)→ もう一度 Esc で閉じる
  await dcell('P00004', 'price').click()
  await page.keyboard.down('Shift'); await dcell('P00006', 'stock').click(); await page.keyboard.up('Shift')
  await page.keyboard.press('Escape'); await sleep(200)
  console.log('after Esc (range clear) dialog open =', await isOpen())
  await page.keyboard.press('Escape'); await sleep(300)
  console.log('after 2nd Esc dialog open =', await isOpen())
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('HUGE_FAN')).join('\n'))
  await browser.close()
})()

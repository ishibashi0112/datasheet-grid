const { open, sleep, cell, val, activeRef, drag, center } = require('./lib.cjs')
;(async () => {
  const { browser, page, logs } = await open('http://127.0.0.1:5503/')
  await page.waitForSelector('.ssg-body-cell', { timeout: 15000 })
  await sleep(800)
  // フィルハンドル: 在庫 P00001..P00002 を選んで下へ 4 行
  await cell(page, 'P00001', 'stock').click()
  await page.keyboard.down('Shift'); await cell(page, 'P00002', 'stock').click(); await page.keyboard.up('Shift')
  const v1 = await val(page, 'P00001', 'stock'), v2 = await val(page, 'P00002', 'stock')
  await sleep(200)
  const fh = await center(page.locator('.ssg-fill-handle'))
  const t6 = await center(cell(page, 'P00006', 'stock'))
  await page.mouse.move(fh.x, fh.y); await page.mouse.down()
  await page.mouse.move(fh.x, fh.y + 5, { steps: 2 }); await page.mouse.move(fh.x, t6.y, { steps: 10 })
  await sleep(200)
  await page.screenshot({ path: __dirname + '/shots/t7-fill-mid.png' })
  await page.mouse.up(); await sleep(400)
  console.log('fill stock', v1, v2, '->', await val(page, 'P00003', 'stock'), await val(page, 'P00004', 'stock'), await val(page, 'P00005', 'stock'), await val(page, 'P00006', 'stock'))
  // 日付の連続
  await cell(page, 'P00001', 'releasedAt').click()
  await sleep(100)
  const fh2 = await center(page.locator('.ssg-fill-handle'))
  const t4 = await center(cell(page, 'P00004', 'releasedAt'))
  await page.mouse.move(fh2.x, fh2.y); await page.mouse.down()
  await page.mouse.move(fh2.x, fh2.y + 5, { steps: 2 }); await page.mouse.move(fh2.x, t4.y, { steps: 10 })
  await page.mouse.up(); await sleep(400)
  console.log('fill date', await val(page, 'P00001', 'releasedAt'), '->', await val(page, 'P00002', 'releasedAt'), await val(page, 'P00003', 'releasedAt'), await val(page, 'P00004', 'releasedAt'))
  await page.keyboard.press('Control+z'); await sleep(200)
  console.log('undo fill date ->', await val(page, 'P00002', 'releasedAt'))

  // 検索
  await cell(page, 'P00001', 'name').click()
  await page.keyboard.press('Control+f'); await sleep(300)
  console.log('find bar', await page.locator('.ssg-find-bar').count())
  await page.keyboard.type('pasta'); await sleep(100)
  await page.keyboard.press('Control+a'); await page.keyboard.insertText('ドッグフード'); await sleep(600)
  console.log('find bar text', (await page.locator('.ssg-find-bar').innerText()).replace(/\s+/g, ' '))
  await page.keyboard.press('Enter'); await sleep(400)
  console.log('active after find enter', await activeRef(page), 'marks', await page.locator('.ssg-find-mark').count())
  await page.screenshot({ path: __dirname + '/shots/t7-find.png' })
  await page.keyboard.press('Escape'); await sleep(200)
  console.log('find closed', await page.locator('.ssg-find-bar').count())
  await page.keyboard.press('Control+Home'); await sleep(400)

  // 右クリックメニュー
  await cell(page, 'P00010', 'price').click({ button: 'right' }); await sleep(300)
  const items = await page.locator('.ssg-menu-panel .ssg-menu-item').allInnerTexts()
  console.log('context menu items', items.map((s) => s.replace(/\s+/g, ' ')).join(' | '))
  await page.keyboard.press('Escape'); await sleep(200)

  // 列メニュー → フィルター(ブランド set)
  const hdr = page.locator('.ssg-header-cell', { hasText: 'ブランド' })
  await hdr.hover(); await sleep(100)
  await hdr.locator('.ssg-icon-btn').last().click(); await sleep(300)
  const colItems = await page.locator('.ssg-menu-panel .ssg-menu-item').allInnerTexts()
  console.log('column menu items', colItems.map((s) => s.replace(/\s+/g, ' ')).join(' | '))
  await page.locator('.ssg-menu-panel .ssg-menu-item', { hasText: 'フィルター' }).first().click(); await sleep(600)
  console.log('filter popover', await page.locator('.ssg-filter-popover').count())
  await page.screenshot({ path: __dirname + '/shots/t7-filter.png' })
  const search = page.locator('.ssg-filter-popover input[type=text], .ssg-filter-popover input:not([type])').first()
  await search.fill('ミナト'); await sleep(300)
  await page.screenshot({ path: __dirname + '/shots/t7-filter2.png' })
  const applyBtn = page.locator('.ssg-filter-popover button', { hasText: /適用|OK/ })
  console.log('apply buttons', await applyBtn.allInnerTexts())
  if (await applyBtn.count()) await applyBtn.first().click()
  else await page.keyboard.press('Enter')
  await sleep(500)
  console.log('top bar', (await page.locator('.ssg-bar--top').innerText()).replace(/\s+/g, ' '))
  console.log('count label rows visible', await page.locator('.ssg-body-row[data-pane=left][data-ssg-label-row]').count())
  await page.screenshot({ path: __dirname + '/shots/t7-filtered.png' })
  // フィルター中は行ドラッグが淡色
  console.log('drag handle disabled', await page.locator('.ssg-row-drag-handle--disabled').count())
  console.log(logs.filter((l) => !l.includes('[vite]') && !l.includes('HUGE_FAN')).join('\n'))
  await browser.close()
})()
